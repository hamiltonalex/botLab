// ВИДЕ ЛОЖИТСЯ НА ДИСК. PURE: ни файлов, ни Date.now (`nowMs` приходит параметром). Слой main
// ПОВЕРХ движка, прецедент `scn-boot.js`: сам автомат сводку не хранит и хранить не должен.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ ЕСТЬ, ОДНИМ АБЗАЦЕМ. Сводка жила ТОЛЬКО в памяти главного процесса, а отметка
// последнего решения (`lastDecisionAt`) персистилась вместе с состоянием движка. После перезапуска
// каданс был уже отсчитан, следующая оценка приходила через сутки, и всё это время карточка
// говорила «оценки ещё не было» - рядом с фактическим временем этой самой оценки строкой выше и
// записанной строкой того же цикла в журнале. Подпись карточки при этом требует, чтобы два показа
// одной оценки совпадали, и прямо называет расхождение дефектом. То есть карточка нарушала
// собственное обещание, а лечится это ровно одним: сводка обязана переживать перезапуск НАРАВНЕ с
// отметкой, которую она объясняет.
//
// ПОЧЕМУ ПОЛИТИКА ВЫНЕСЕНА СЮДА, А НЕ ОСТАЛАСЬ ТРЕМЯ СТРОКАМИ В `main.js`. Три её правила
// («снимать только на цикле решения», «гасить при взводе и выключении», «поднимать только целую
// запись») друг с другом связаны, и любое из них, нарушенное поодиночке, даёт КАРТОЧКУ, КОТОРАЯ
// ВРЁТ, а не сломанное приложение: экран продолжает работать и продолжает объяснять. Такие правила
// обязаны быть под тестом, а `main.js` тянет за собой Electron и под тест не идёт.

export const FA_EVAL_SCHEMA_VERSION = 1;

// ── КОГДА СНИМАЕТСЯ. Только на ЦИКЛЕ РЕШЕНИЯ, и это не экономия записи. Тик идёт раз в пять минут,
// а вселенную правило пересчитывает раз в каданс (сутки): на 287 тиках из 288 `evalMarkets` пуст, и
// класть эту пустоту поверх последней снятой оценки значило бы гасить единственный честный ответ на
// вопрос «что бот видел по каждому рынку». Возврат `null` читается как «не трогать», а не как
// «стереть»: разница между ними и есть весь смысл функции.
export function faEvalOfTick(tick, { nowMs, cadenceH = null, capitalUsd = null } = {}) {
  if (!tick || !tick.decided || !Array.isArray(tick.evalMarkets)) return null;
  if (!Number.isFinite(nowMs)) return null;
  return {
    at: nowMs,
    cadenceH: Number.isFinite(cadenceH) ? cadenceH : null,
    // ПОТОЛОК КАПИТАЛА ЕДЕТ ВМЕСТЕ СО СТРОКАМИ, потому что ранг посчитан ПРОТИВ НЕГО
    // (`bestAlternative(capitalUsd)`): без него строку ранга не с чем сверить, а сводка,
    // ранжированная против другого потолка, это оценка другого автомата.
    capitalUsd: Number.isFinite(capitalUsd) ? capitalUsd : null,
    markets: tick.evalMarkets,
  };
}

// ── КОГДА ГАСНЕТ. Два случая, и оба про то, что оценка перестала описывать работающий автомат.
//
//   ВЗВОД. Параметры замораживаются заново, и капитал в них бывает ДРУГОЙ. Ранг старой сводки
//   посчитан против прежнего потолка, то есть это оценка другого автомата, а не устаревшая своя.
//   `armAuto` обнуляет накопитель непрерывности ровно за этим и ровно поэтому.
//
//   ВЫКЛЮЧЕНИЕ. Штамп карточки обещает «следующая не раньше T», а пилюля зоны «Рынок бота» называет
//   кандидата. Ни того, ни другого больше не будет, и обещание несуществующего хуже пустоты.
//
// ЗАПРОШЕННАЯ ОСТАНОВКА ПРИ ОТКРЫТОЙ СДЕЛКЕ НЕ ГАСИТ НИЧЕГО, и это третий случай, а не частный
// второй: автомат остаётся включённым, ведёт сделку правилом выхода и решает каждый каданс, значит
// сводка ЖИВАЯ и гасить её было бы неправдой в обратную сторону.
export function faEvalClears({ arming = false, on = false } = {}) {
  return arming ? true : !on;
}

// ── В КАКОМ ВИДЕ ЛОЖИТСЯ. Гашение пишется ЯВНОЙ пустой записью, а не удалением файла: отсутствие
// файла и «сводки нет» должны читаться одинаково, но удалять уже записанное на диске - операция, у
// которой отказ некому заметить.
export function faEvalToDisk(botId, ev) {
  const base = { schemaVersion: FA_EVAL_SCHEMA_VERSION, botId };
  if (!ev) return { ...base, at: null, cadenceH: null, capitalUsd: null, markets: [] };
  return { ...base, at: ev.at, cadenceH: ev.cadenceH ?? null, capitalUsd: ev.capitalUsd ?? null, markets: ev.markets };
}

// ── ЧТО ПОДНИМАЕТСЯ ОБРАТНО. Форма проверяется ЦЕЛИКОМ, и половина сводки отвергается наравне с
// мусором: карточка показывает строки как ВСЮ вселенную, поэтому неполный список читался бы как
// «рынков стало меньше». Не поднявшаяся сводка это `null`, и карточка про такой случай говорит
// отдельными словами («решение было, данных о нём нет»), а не «оценки ещё не было».
export function faEvalFromDisk(raw) {
  if (!raw || typeof raw !== "object") return null;
  if (!Number.isFinite(raw.at) || !Array.isArray(raw.markets) || !raw.markets.length) return null;
  for (const m of raw.markets) if (!m || typeof m !== "object" || m.token === undefined) return null;
  return {
    at: raw.at,
    cadenceH: Number.isFinite(raw.cadenceH) ? raw.cadenceH : null,
    capitalUsd: Number.isFinite(raw.capitalUsd) ? raw.capitalUsd : null,
    markets: raw.markets,
  };
}
