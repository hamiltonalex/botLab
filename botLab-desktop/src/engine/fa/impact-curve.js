// «0.1-1.2 бп» задания фазы, а оно, в свою очередь, из шапки `sizing.js`. Замер по сегодняшнему
// снимку его не подтверждает ни на всех 63 рынках, ни даже на BTC и ETH, где при $2500 выходит
