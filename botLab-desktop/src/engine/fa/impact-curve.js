// И ЭТО ДОПУЩЕНИЕ, А НЕ ЗАМЕРЕННЫЙ ПОРОГ. Под ним одна скорость на одном промежутке, продолженная
// прямой. Второй механизм старения, ДРЕЙФ ГЛУБИНЫ на покрытых рынках, не замерен ничем: живьём
// удар не наблюдаем вовсе (в REST GMX нет ни одного поля impact), и узнать дрейф можно только
// новым снимком. Та же оговорка стоит у книги входа (`pf-lib.mjs`, `loadCapacity`).
//
// ЧТО ПРОИСХОДИТ ПОСЛЕ СРОКА, И ПОЧЕМУ НЕ БОЛЬШЕ ЭТОГО. Бот продолжает считать по снимку, а
// возраст и просрочка едут В ЗАПИСЬ РЕШЕНИЯ и в журнал. Обе замены измерены и обе ХУЖЕ:
// плоская константа ошибается в медиане на 10.00 бп против 0.07 у яруса и переоценивает удар в 125
// наблюдениях из 126, а отказ рынку без своей кривой снимает с вселенной 31% инструментов, включая
// все рынки Avalanche и каждый новый листинг. То есть «протух» здесь означает «считаем тем же и
// говорим об этом вслух», и сказать это обязаны запись и оператор, а не читатель догадкой.
// Офлайн-смоук `npm run smoke:impact` после срока падает кодом возврата: срок, о котором никто не
// узнает, отличается от отсутствующего только длиной шапки.
export const IMPACT_SHELF_LIFE_DAYS = 180;

// Конец периода снимка в миллисекундах либо null. Поле `meta.period` человекочитаемое, но метки
// времени в нём лежат числами (`ts <от>..<до>`), и берутся именно они: разбирать дату из строки
// значило бы завести второй формат даты там, где первый уже есть.
export function impactPeriodEndMs(snapshot) {
  const m = /ts\s+(\d+)\.\.(\d+)/.exec(String(snapshot?.meta?.period ?? ""));
  if (!m) return null;
  const sec = Number(m[2]);
  return Number.isFinite(sec) && sec > 0 ? sec * 1000 : null;
}

// Возраст снимка на момент `nowMs`. НЕИЗВЕСТНЫЙ ВОЗРАСТ СЧИТАЕТСЯ ПРОСРОЧЕННЫМ, а не свежим: это
// тот же принцип, что у `tierOfRoom` и `usdOf` в отборе, неизвестность не поворачивается в
// удобную сторону. Снимка нет вовсе - возраст тоже неизвестен, и ответ тот же.
export function impactSnapshotAge({ periodEndMs = null, nowMs = null, shelfLifeDays = IMPACT_SHELF_LIFE_DAYS } = {}) {
  if (!Number.isFinite(periodEndMs) || !Number.isFinite(nowMs)) return { days: null, stale: true, periodEndMs: null };
  const days = (nowMs - periodEndMs) / 86400e3;
  return { days, stale: days > shelfLifeDays, periodEndMs };
}

// Имена источников кривой. Молчаливого источника нет: каждая строка среза несёт своё имя, и
// `none` называется так же явно, как остальные.
export const IMPACT_SOURCES = Object.freeze(["market", "tier", "pooled", "none"]);

// Запасные пути, от самого частного к самому общему. `none` это отказ от подстановки вовсе.
export const IMPACT_FALLBACKS = Object.freeze(["tier", "pooled", "none"]);

// ЯРУСЫ ЛИКВИДНОСТИ СНИМКА. Метки взяты из снимка ДОСЛОВНО (`markets[*].tier`, ключи `_tiers`), и
// переименовывать их нельзя: это ключи чужого файла, а не наши имена.
//
// ГРАНИЦЫ ВОССТАНОВЛЕНЫ ПО СНИМКУ, а не угаданы: у снимка ярус считается от СУММЫ свободной
// ёмкости обеих сторон, и на 63 рынках это разбиение сходится без единого пересечения и без единой
// ошибки (D до $0.175M, C от $0.210M до $0.619M, B от $1.042M до $9.746M, A от $14.860M).
//
// А ЗДЕСЬ ЯРУС СЧИТАЕТСЯ ОТ ХУДШЕЙ СТОРОНЫ, И ЭТО ОСОЗНАННОЕ РАСХОЖДЕНИЕ. Инструмент несёт
// `roomUsd`, а это `Math.min` двух сторон (`universe-scan.js`), суммы у него нет вовсе. Завести
// ради точного яруса новое поле в отборе значило бы тронуть отбор ради 0.024 бп медианной ошибки
// (0.073 против 0.049 на том же leave-one-out), а p95 и максимум у обоих совпадают. Расхождение
// сдвигает рынок В ТЕСНЫЙ ярус, то есть в сторону БОЛЬШЕГО удара, и это безопасное направление.
export const IMPACT_TIERS = Object.freeze([
  { tier: "A_свободная_ликвидность>=10M", minRoomUsd: 10e6 },
  { tier: "B_1-10M", minRoomUsd: 1e6 },
  { tier: "C_200k-1M", minRoomUsd: 200e3 },
  { tier: "D_<200k", minRoomUsd: 0 },
]);

// Ярус по суммарной свободной ёмкости. Нечитаемая ёмкость даёт САМЫЙ ТЕСНЫЙ ярус, а не самый
// широкий: неизвестное место это не бесконечное место, тот же принцип, что у `usdOf` в отборе.
export function tierOfRoom(roomUsd) {
  const r = Number(roomUsd);
  if (!Number.isFinite(r) || r < 0) return IMPACT_TIERS[IMPACT_TIERS.length - 1].tier;
  for (const t of IMPACT_TIERS) if (r >= t.minRoomUsd) return t.tier;
  return IMPACT_TIERS[IMPACT_TIERS.length - 1].tier;
}

// Узлы первоисточника в узлы правила. ЗНАК ПРИВОДИТСЯ ЗДЕСЬ (см. шапку), и это единственное место
// в приложении, где он приводится.
function nodesFrom(raw) {
  if (!Array.isArray(raw)) return null;
  const out = [];
  for (const n of raw) {
    const sizeUsd = Number(n?.sizeUsd);
    if (!Number.isFinite(sizeUsd) || sizeUsd <= 0) continue;
    out.push({ sizeUsd, bps: Math.max(0, -(Number(n?.adverseBps) || 0)) });
  }
  return out.length ? out : null;
}

// Цепь инструмента против цепи снимка. Снимок снят по ОДНОЙ цепи (`meta.chain`), и глубина рынка
// ETH на Avalanche это НЕ глубина рынка ETH на Arbitrum: подставить одну вместо другой значит
// молча выдать чужой замер за свой. Сравнение по началу строки, потому что отбор кладёт в
// инструмент метку вида `Avalanche`, а снимок пишет `arbitrum`.
function sameChain(instChain, snapChain) {
  const a = String(instChain || "").trim().toLowerCase();
  const b = String(snapChain || "").trim().toLowerCase();
  if (!a || !b) return false;
  return a === b || a.startsWith(b) || b.startsWith(a);
}

// ЧИТАТЕЛЬ КРИВОЙ. Возвращает функцию `(inst, gmxSide) -> { nodes, src, tier }`, и она НИКОГДА не
// возвращает null: строка среза обязана нести имя источника даже тогда, когда узлов нет.
//
// `snapshot` это разобранный объект снимка целиком; из него читаются `meta.chain` и `interp`.
// Негодный снимок (нет `interp`) не выдумывает кривых: все рынки получают `none`, и это видно
// строкой в трассе, а не молча.
export function makeImpactReader(snapshot, { fallback = "tier" } = {}) {
  const interp = snapshot?.interp && typeof snapshot.interp === "object" ? snapshot.interp : null;
  const snapChain = snapshot?.meta?.chain ?? null;
  const mode = IMPACT_FALLBACKS.includes(fallback) ? fallback : "tier";
  const tiers = interp?._tiers ?? null;
  const pooled = interp?._pooled ?? null;

  return function impactOf(inst, gmxSide) {
    const side = gmxSide === "short" ? "short" : "long";
    if (!interp) return { nodes: [], src: "none", tier: null };

    // 1. СВОЯ КРИВАЯ РЫНКА. Только при совпадении цепи: см. `sameChain`.
    if (sameChain(inst?.chain, snapChain)) {
      const own = nodesFrom(interp[inst?.token]?.[side]);
      if (own) return { nodes: own, src: "market", tier: null };
    }
    if (mode === "none") return { nodes: [], src: "none", tier: null };

    // 2. ЯРУС ЛИКВИДНОСТИ. Ёмкость берётся ту же, что читает отбор: обе стороны рынка.
    const tier = tierOfRoom(inst?.roomUsd);
    if (mode === "tier") {
      const byTier = nodesFrom(tiers?.[`${tier}|${side}`]);
      if (byTier) return { nodes: byTier, src: "tier", tier };
    }

    // 3. ОБЩИЙ ПУЛ. Последнее звено цепи снимка (`meta.interpHowTo`).
    const byPool = nodesFrom(pooled?.[side]);
    if (byPool) return { nodes: byPool, src: "pooled", tier };

    return { nodes: [], src: "none", tier };
  };
}
