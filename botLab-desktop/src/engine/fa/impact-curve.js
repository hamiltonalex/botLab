// ДОСТИЖИМОЙ и названной: она нужна замеру и тому, кто решит, что торговать по чужой кривой хуже,
// чем не торговать.
//
// ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ. Не решает и не отбирает: он отдаёт узлы и ИМЯ ИСТОЧНИКА. Кто из этого
// что сделает - дело среза и правила, а правило не тронуто этой правкой ни строкой.

