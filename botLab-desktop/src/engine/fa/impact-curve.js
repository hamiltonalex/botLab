// ─────────────────────────────────────────────────────────────────────────────
//
// ПОЧЕМУ НЕ ОТ ДНЯ СЪЁМКИ. Снимок снят 30.08, но посчитан по истории до 20.06: в день рождения он
// уже отставал от рынка на 71 сутки. Стареет в нём не день съёмки, а то, ПО КАКИМ ДАННЫМ он
// посчитан, поэтому возраст считается от конца периода. Дата съёмки к тому же в файле не лежит
// вовсе (в `meta` только `period`), её пришлось бы вбивать константой и следить, чтобы она не
