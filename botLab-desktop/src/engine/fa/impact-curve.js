// ЧТО ЭТО. Читатель снимка глубины `impact-gmx.json.gz` в той форме, которую принимает правило:
// `{ sizeUsd, bps }`, где `bps` это ИЗДЕРЖКА, то есть неотрицательное число. Снимок передаётся
// РАЗОБРАННЫМ объектом, файл читает вызывающий (`main.js`): держать здесь `fs` значило бы, что срез
