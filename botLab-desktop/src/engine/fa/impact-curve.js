// издержки, а плоская константа `gmxImpact` 0.1% из `costs.js`: пустая кривая выключает ветку
// `hasGmxCurve` в `costAtSize`, и круг считается по константе. Константа берёт 10 базисных
// пунктов, а ИЗМЕРЕННАЯ величина на тикете $2500 это медиана 0.001 бп (ровно ноль у 57 наблюдений
