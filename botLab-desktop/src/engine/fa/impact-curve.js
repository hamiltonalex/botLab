// как есть и названо открытым вопросом, а не переписано задним числом. Цена этого на 63 рынках при капитале $2500: **-$64.46 нетто за год**
// ($840.30 против $775.84), и она растёт с числом рынков, потому что завышенный круг отсекает
// ровно те рынки, где нетто и круг сопоставимы.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗНАК ПРИВОДИТСЯ ЗДЕСЬ И ОДИН РАЗ
// ─────────────────────────────────────────────────────────────────────────────
//
// В первоисточнике `adverseBps` ОТРИЦАТЕЛЕН, когда платит трейдер (`meta.bpsDef`), а правило
// принимает издержку неотрицательным числом. Образец приведения - `exit-lib.mjs` `loadCapacity`,
// и формула здесь та же до буквы: `Math.max(0, -(adverseBps ?? 0))`. Второе место, где знак
// приводится иначе, дало бы ДВЕ РАЗНЫЕ КРИВЫЕ ПОД ОДНИМ ИМЕНЕМ, а такую ошибку не видно ни в одном
// тесте: обе ветки считают правдоподобные числа.
//
// ПОЧЕМУ `bps`, А НЕ `adverseBps` СНИМКА. У снимка два поля на узел: `bps` это средний удар со
// знаком (положительный означает, что GMX ПЛАТИТ трейдеру за сокращение перекоса), `adverseBps`
// это удар в НЕБЛАГОПРИЯТНУЮ сторону. Правило размера считает издержку входа, и рассчитывать на
// премию за сокращение перекоса нельзя: она достаётся тому, кто угадал сторону перекоса, а мы
// выбираем сторону по фандингу. Поэтому берётся `adverseBps`, и это та же величина, на которой
// посчитаны обе книги бота 1.
//
// ─────────────────────────────────────────────────────────────────────────────
// РЫНОК, КОТОРОГО В СНИМКЕ НЕТ: ЗАПАСНОЙ ПУТЬ НАЗВАН, А НЕ ПОДСТАВЛЕН МОЛЧА
// ─────────────────────────────────────────────────────────────────────────────
//
// ЭТО НЕ КРАЕВОЙ СЛУЧАЙ, И ЭТО ЗАМЕР. На живом составе фикстуры 16.09 (51 инструмент) снимок не
// покрывает **16 инструментов, то есть 31%**: четыре рынка Avalanche (снимок снят по Arbitrum,
// `meta.chain`) и двенадцать листингов Arbitrum новее периода снимка (VVV, XMR, ZEC, XPL, SKY,
// AERO, HBAR, MET, PUMP, ICP, LIT, CC). Новые листинги будут появляться и дальше: снимок это год
// истории, а вселенная живая.
//
// ВЕТКИ ЗАМЕРЕНЫ ОБЕ, методом исключения по очереди (`leave-one-out`) на тех 63 рынках, где правда
// известна: у рынка отбирается его собственная кривая, подставляется запасная, и ошибка считается
// против правды. Тикет $2500, 126 наблюдений (63 рынка x 2 стороны), |ошибка| в базисных пунктах
// за круг:
//
//                                          медиана   p95     максимум
//   запасной путь по ЯРУСУ (как здесь)       0.07    2.58      13.22
//   запасной путь по ОБЩЕМУ пулу             0.06    2.61      13.32
//   плоская константа 0.1% (как сегодня)    10.00   10.00      10.00
//   для масштаба, сама правда                0.00    2.63      13.38
//
// То есть запасная ИЗМЕРЕННАЯ кривая ошибается на ДВА ПОРЯДКА меньше плоской константы в медиане.
// Направление ошибки константы названо отдельно: она ПЕРЕОЦЕНИВАЕТ удар в 125 наблюдениях из 126
// (правда выше 10 бп ровно один раз, ANIME long 13.38), и переоценка круга это и есть те -$64.46.
//
// ЧЕСТНАЯ ГРАНИЦА ЗАПАСНОГО ПУТИ, И ОНА В ОПАСНУЮ СТОРОНУ. Запасная кривая это ЦЕНТР яруса, а не
// его хвост, поэтому на тесных рынках она удар НЕДООЦЕНИВАЕТ: в ярусе `D_<200k` 15% наблюдений
// недооценены больше чем на 0.5 бп, худшее 13.22 бп (ANIME). В ярусах A и B недооценки нет вовсе
// (максимум 0.07 и 0.74 бп). Новый листинг почти всегда тесный, то есть попадает ровно в тот ярус,
// где запас слабее всего. Это НЕ повод вернуть константу (она ошибается в 200 раз сильнее и на
// всех ярусах), но это повод пересчитывать снимок, а не считать его вечным.
//
// ЯРУС ВЫБРАН ПЕРВЫМ ЗВЕНОМ, и выбор мелкий: против пула он точнее в 39 наблюдениях, хуже в 28,
// одинаков в 59, а p95 и максимум у них совпадают. Решает не точность, а то, что ярус известен
