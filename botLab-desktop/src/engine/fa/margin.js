// margin.js - СТОРОЖ ЗАЛОГА ОБЕИХ НОГ БОТА 1. PURE: ни сети, ни файлов, ни Date.now.
//
// ЗАМЕР, ИЗ КОТОРОГО СЛЕДУЕТ ВСЁ ОСТАЛЬНОЕ. Ноги стоят на РАЗНЫХ биржах, кросс-маржи между ними
// нет, поэтому прибыль уцелевшей ноги проигрывающую НЕ поддерживает. BERA февраля 2026 прошла
// +127.59%: короткая нога умирает даже при плече 1, депозит $3991 становится $2373, то есть минус
// 41%, что равно 2.30 года чистого дохода стратегии. Один такой эпизод стирает результат двух лет,
// и потому сторож это БЛОКИРУЮЩИЙ компонент автомата, а не украшение отчёта.
//
// ЧЕСТНАЯ ОГОВОРКА, БЕЗ КОТОРОЙ ЧИСЛА НЕЛЬЗЯ УПОТРЕБЛЯТЬ. У бумажного счёта позиции на бирже НЕТ,
// поэтому настоящей цены ликвидации для неё не существует и прочитать её невозможно в принципе.
// ВХОД правила (поддерживающая маржа, плечо, цена) читается полями биржи и никогда не подгоняется;
// расстояние до ликвидации ГИПОТЕТИЧЕСКОЙ позиции считается выражением, сверенным с полем биржи на
// живых счетах. Поэтому каждая посчитанная здесь цена ликвидации едет в запись с ярлыком источника
// "model", а не "venue": число биржи и число модели стоят разного, и различать их обязан архив, а
// не память читателя (закон `fa/record.js`).
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило зовётся из ДВУХ мест автомата: ворота входа и ворота удержания.
// Вторая реализация запрещена, а класс дефекта «две части системы решают одну задачу разными
// правилами» проект ловил четырежды. Не внутри `sizing.js`: там экономика размера, а не выживание.
// Не внутри `exit.js`: сторож блокирует и вход тоже, а правило выхода про открытую сделку.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОТКУДА БЕРУТСЯ ЧИСЛА
//
// ПОДДЕРЖИВАЮЩАЯ МАРЖА НОГИ HYPERLIQUID. `mm = 1/(2 * maxLeverage)`, где `maxLeverage` это ПОЛЕ
// биржи из `metaAndAssetCtxs` (в снимок приложения приезжает как `hlMaxLev`). ЗАМЕР: выведенная
// отсюда поддерживающая маржа сверена с полем `crossMaintenanceMarginUsed` в прогоне 10 до цента
// (`scripts/funding-arb-study/pf-vf-залог.mjs`). На вселенной приложения это `mm = 0.0125` у BTC
// (maxLev 40) и `mm = 0.02` у ETH (maxLev 25).
//
// ПОДДЕРЖИВАЮЩАЯ МАРЖА НОГИ GMX РАВНА НУЛЮ, И ЭТО ДОПУЩЕНИЕ, А НЕ ЗАМЕР. Измеренного
// `minCollateralFactor` в репозитории нет ни одного, поэтому нога GMX считается умирающей только
// когда залог стёрт в ноль. Это ОПТИМИСТИЧНАЯ сторона: настоящий порог биржи выше нуля, значит
// настоящая нога умирает РАНЬШЕ расчётной. Слово «оптимистичная» стоит здесь именно потому, что
// ошибка направлена в опасную сторону, и снимать это допущение надо замером поля, а не подбором.
//
// ХОД, УБИВАЮЩИЙ НОГУ. При плече L и поддерживающей марже mm нога умирает на ходе цены против неё
//   x* = 1/L - mm,
// и счёт ведётся ОТ НОЦИОНАЛА ВХОДА, ровно как в прогоне 10. Точная механика биржи требует
// поддерживающей маржи от ТЕКУЩЕГО ноционала, что даёт `(1/L - mm)/(1 - mm)`, то есть на 1.3%
// относительно больше при mm = 0.0125. Разница названа, а не спрятана, и конвенция выбрана та же,
// в которой мерился риск: сравнивать сторожа с замером, посчитанным иначе, значит сравнивать разные
// величины.
//
// ЗАПАС ДО ЛИКВИДАЦИИ СЧИТАЕТСЯ ОТ ТЕКУЩЕЙ ЦЕНЫ, А НЕ ОТ ЦЕНЫ ВХОДА, и это не мелочь. Цена входа
// задаёт, ГДЕ стоит ликвидация; вопрос сторожа другой: сколько хода осталось СЕЙЧАС. У позиции,
// прошедшей половину пути к ликвидации, запас от входа не изменился бы вовсе, то есть сторож
// молчал бы ровно тогда, когда он нужен. На пустом слоте текущая цена равна цене входа, и обе
// величины совпадают по построению.
//
// ЧИСЛА ВЛАДЕЛЬЦА, ПРИНЯТЫЕ 2026-08-31 И НЕ ПЕРЕОТКРЫВАЕМЫЕ: плечо 1 на КАЖДУЮ ногу, запас до
// ликвидации 50%. Следствие, которое надо знать: при плече 1 запас равен `1 - mm`, то есть 98.75%
// у BTC и 98% у ETH, и порог 50% не связывает НИКОГДА. Он начинает связывать с плеча 2
// (`0.5 - 0.0125 = 48.75% < 50%`). Это не значит, что сторож бесполезен: он блокирует и на
// удержании, где запас съедает движение цены, и именно там сработал бы эпизод BERA.
//
// ЧЕГО МОДУЛЬ НЕ ИМПОРТИРУЕТ: ничего из `src/engine/btcopt/`. У бота 2 есть свой `margin.js`, и он
// про маржу USDC-опционов Deribit, то есть про другой предмет на другой бирже. Замыкания импортов
// двух ботов пересекаются по пустому множеству, у бота 2 идёт живой прогон, и это стережёт тест.

import { legModel } from "../paper.js";

// Поддерживающая маржа ноги GMX. ДОПУЩЕНИЕ, а не замер, и оптимистичное (см. шапку): измеренного
// `minCollateralFactor` в репозитории нет ни одного, поэтому нога считается умирающей только когда
// залог стёрт в ноль.
export const FA_GMX_MAINTENANCE_MARGIN = 0;

// Значения по умолчанию. Оба пришли от владельца, оба заморожены в параметрах автомата в момент
// взвода, и здесь они лежат только как источник этой заморозки.
export const FA_MARGIN_DEFAULTS = Object.freeze({
  leverage: 1, // на КАЖДУЮ ногу
  minRoomFraction: 0.5, // требуемый запас хода до цены ликвидации, доля текущей цены
});

// Отказы сторожа. Реестр здесь, а не в автомате: код заводит тот, кто его порождает, иначе копия
// чужого реестра расходится с оригиналом при первой правке. Автомат включает этот список в свой
// ССЫЛКОЙ, а не строками.
export const FA_MARGIN_REFUSALS = Object.freeze([
  "margin_thin", // запас до ликвидации хотя бы одной ноги меньше требуемого
  "margin_unknown", // посчитать запас нечем: нет цены, плеча или поддерживающей маржи ноги
]);

// Ярлык источника цены ликвидации. У бумажного счёта он может быть только "model", и константа
// заведена, чтобы это утверждение стояло в коде один раз (значения словаря живут в `record.js`).
export const FA_MARGIN_LIQ_SOURCE = "model";

// ЧИСЛО ИЛИ НИЧЕГО. `Number(null)` в JavaScript равен НУЛЮ, и на сторожа залога это ловушка ровно с
// той стороны, с которой ошибаться дороже всего: отсутствующая поддерживающая маржа молча стала бы
// нулевой, то есть «не знаем» превратилось бы в самое ОПТИМИСТИЧНОЕ из возможных допущений и
// сторож отвечал бы «запаса вдоволь» там, где входа у него нет. Поймано тестом, а не рассуждением.
const numOf = (x) => (x === null || x === undefined || x === "" || typeof x === "boolean" ? NaN : Number(x));

// Поддерживающая маржа ноги Hyperliquid из ПОЛЯ БИРЖИ. Возвращает null, когда поля нет: выдуманное
// значение здесь дороже отказа, потому что оно молча превратило бы «не знаем» в «всё в порядке».
export function hlMaintenanceMargin(maxLeverage) {
  const L = numOf(maxLeverage);
  if (!Number.isFinite(L) || L <= 0) return null;
  return 1 / (2 * L);
}

// Ход против ноги, убивающий её. Счёт от ноционала входа (см. шапку). Отрицательный результат
// означает, что нога мертва при любом движении, то есть плечо выше предела биржи.
export function killMoveFraction(leverage, mm) {
  const L = numOf(leverage);
  const m = numOf(mm);
  if (!Number.isFinite(L) || L <= 0 || !Number.isFinite(m) || m < 0) return null;
  return 1 / L - m;
}

// Одна нога: залог, цена ликвидации и ОСТАВШИЙСЯ запас хода от текущей цены.
//
// Форма возврата совпадает с тем, что просит блок ноги строки снимка (`fa/record.js`), и это
// сделано нарочно: паспорт сделки и вход сторожа обязаны быть ОДНИМ наблюдением, иначе архив и
// решение разъедутся, а разъезд заметят через год.
export function legMargin({ venue = null, side, notionalUsd, leverage, entryPx, markPx, mm } = {}) {
  const N = numOf(notionalUsd);
  const L = numOf(leverage);
  const p0 = numOf(entryPx);
  const p = numOf(markPx);
  const x = killMoveFraction(L, mm);
  const out = {
    venue,
    side: side === "long" || side === "short" ? side : null,
    notionalUsd: Number.isFinite(N) ? N : null,
    collateralUsd: Number.isFinite(N) && Number.isFinite(L) && L > 0 ? N / L : null,
    entryPx: Number.isFinite(p0) ? p0 : null,
    markPx: Number.isFinite(p) ? p : null,
    mm: Number.isFinite(numOf(mm)) ? numOf(mm) : null,
    moveFrac: x,
    liquidationPx: null,
    liqSource: FA_MARGIN_LIQ_SOURCE,
    roomFrac: null,
  };
  if (!out.side || out.notionalUsd == null || out.collateralUsd == null || x == null) return out;
  if (out.entryPx == null || out.entryPx <= 0 || out.markPx == null || out.markPx <= 0) return out;
  // Цена ликвидации стоит на ходе x* ОТ ЦЕНЫ ВХОДА: именно там залог входа оказывается стёрт до
  // поддерживающей маржи. Длинная нога умирает вниз, короткая вверх.
  out.liquidationPx = out.side === "long" ? out.entryPx * (1 - x) : out.entryPx * (1 + x);
  // А запас считается от ТЕКУЩЕЙ цены: вопрос сторожа «сколько хода осталось», а не «сколько его
  // было при входе». Отрицательный запас означает, что цена ликвидации уже пройдена.
  out.roomFrac = out.side === "long"
    ? (out.markPx - out.liquidationPx) / out.markPx
    : (out.liquidationPx - out.markPx) / out.markPx;
  return out;
}

// Разбор сделки на ноги. Стороны берутся у `legModel` леджера, а не назначаются здесь: какая нога
// длинная при конфигурации A и какая при B, знает ровно одно место в проекте, и второе такое место
// разошлось бы с первым при первой правке схемы.
//
// У ОДНУНОГОЙ СХЕМЫ НОГА ОДНА, и это не особый случай сторожа: биржевой ноги Hyperliquid там нет
// вовсе, поэтому и маржи её не существует. Признак берётся у того же `legModel`
// (`hlPerHourSign === 0`), а не по строке стратегии.
//
// ЦЕНА У ОБЕИХ НОГ ОДНА. Приложение наблюдает одну марку на инструмент (марка Hyperliquid), и
// раздельной цены ноги GMX у него нет. Для расстояния до ликвидации это допустимо: ноги стоят на
// одном базовом активе, а расхождение марок бирж на порядки меньше запаса. Названо, чтобы позже
// никто не принял общую цену за наблюдение двух.
export function positionLegs({ strategy = "two", config = null, sizeUsd, leverage, entryPx, markPx, hlMaxLev } = {}) {
  const { gmxSide, hlPerHourSign } = legModel(strategy, config);
  const legs = [{
    venue: "gmx", side: gmxSide, notionalUsd: sizeUsd, leverage, entryPx, markPx, mm: FA_GMX_MAINTENANCE_MARGIN,
  }];
  if (hlPerHourSign !== 0) {
    legs.push({
      venue: "hl", side: gmxSide === "short" ? "long" : "short", notionalUsd: sizeUsd, leverage,
      entryPx, markPx, mm: hlMaintenanceMargin(hlMaxLev),
    });
  }
  return legs;
}

// СТОРОЖ. Одно решение по ОБЕИМ ногам: слабейшая нога решает за всю сделку, потому что кросс-маржи
// между биржами нет и прибыль уцелевшей ноги проигрывающую не поддерживает.
//
// `legs` это массив входов `legMargin`; у однуногой схемы он из одного элемента, и это не особый
// случай, а тот же максимум по пустому дополнению. Неизвестный запас хотя бы у одной ноги даёт
// `margin_unknown`, а не пропуск: «не знаем» и «в порядке» это разные состояния, и сливать их
// значит выдавать отказ снабжения за вывод правила.
export function marginGuard({ legs = [], minRoomFraction = FA_MARGIN_DEFAULTS.minRoomFraction } = {}) {
  const need = numOf(minRoomFraction);
  const evaluated = (legs || []).map((l) => legMargin(l));
  if (!evaluated.length || !Number.isFinite(need)) {
    return { ok: false, code: "margin_unknown", roomFrac: null, need: Number.isFinite(need) ? need : null, worst: null, legs: evaluated };
  }
  let worst = null;
  for (const l of evaluated) {
    if (!Number.isFinite(l.roomFrac)) {
      return { ok: false, code: "margin_unknown", roomFrac: null, need, worst: l, legs: evaluated };
    }
    if (!worst || l.roomFrac < worst.roomFrac) worst = l;
  }
  const ok = worst.roomFrac >= need;
  return { ok, code: ok ? null : "margin_thin", roomFrac: worst.roomFrac, need, worst, legs: evaluated };
}

// Одна строка на вердикт. Существует потому, что решение, которого нельзя объяснить оператору, в
// журнале неотличимо от произвольного числа.
export function explainMargin(verdict) {
  if (!verdict) return "сторож залога не считался";
  if (verdict.code === "margin_unknown") {
    return `запас до ликвидации НЕ ПОСЧИТАН: не хватает цены, плеча или поддерживающей маржи ноги (margin_unknown)`;
  }
  const pct = (x) => `${(x * 100).toFixed(2)}%`;
  const w = verdict.worst;
  const name = `${w?.venue === "hl" ? "Hyperliquid" : "GMX"} ${w?.side === "long" ? "лонг" : "шорт"}`;
  if (verdict.code === "margin_thin") {
    return `запас ноги ${name} ${pct(verdict.roomFrac)} меньше требуемых ${pct(verdict.need)} (margin_thin)`;
  }
  return `запас слабейшей ноги (${name}) ${pct(verdict.roomFrac)} при требуемых ${pct(verdict.need)}`;
}
