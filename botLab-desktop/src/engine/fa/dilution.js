// dilution.js - РАЗБАВЛЕНИЕ ВХОДА СОБСТВЕННЫМ РАЗМЕРОМ. PURE: ни сети, ни файлов, ни Date.now.
//
// ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. До этого модуля бумажный леджер начислял фандинг по КОТИРУЕМОЙ ставке и
// не спрашивал, есть ли на встречной стороне деньги, чтобы её заплатить. Счёт показывал прибыль,
// которой не существует: на 25 рынках из 63 модель книжила себе больше, чем рынок выплатил ВСЕМ
// участникам за год (MOODENG $651 526 против выплаченных рынком $6 812). Четыре прогона
// исследования подряд строились на этом фантоме.
//
// ОТКУДА БЕРЁТСЯ ФОРМУЛА. У GMX держится тождество
//     |f_long| * B_long = |f_short| * B_short = pot        [доллар в секунду]
// где B это база фандинга стороны (`longFundingBalanceOiUsd` / `shortFundingBalanceOiUsd`), а pot
// это ВЕСЬ поток фандинга рынка в этот час. Проверено на 245 308 часах: медиана относительной
// невязки 1.3e-14%, p99 равен 4.3e-14%; на трёх фикстурах репозитория (APT, BTC, ETH, 8761 час
// каждая) медиана 1.31e-14 .. 1.39e-14% и p99 до 4.31e-14%.
//
// Поток плательщика pot от нашего появления не растёт. Значит наш вход размера S в ПРИНИМАЮЩУЮ
// сторону увеличивает её базу, и на доллар достаётся pot/(B+S) вместо pot/B, то есть к котируемой
// ставке применяется множитель
//     B / (B + S)
// Модуль считает именно `f * B/(B+S)`, а не `pot/(B+S)`: по тождеству это одно и то же число, но
// первая форма требует ОДНУ величину (базу нашей стороны) вместо трёх, а лишняя величина это
// лишний способ ошибиться. `potOf` остаётся отдельно и служит ПРОВЕРКОЙ тождества, а не путём
// вычисления.
//
// ТРИ ПРАВИЛА ПРИМЕНЕНИЯ, И КАЖДОЕ КУПЛЕНО ОШИБКОЙ:
//   1. ПОЧАСОВО, а не средним множителем по окну. Считалось `E[w] * Sx` вместо `Sw * x`, а деньги
//      сидят в часах с самой малой базой, то есть с наибольшим весом. Здесь правило вызывается на
//      каждом начислении, среднего не существует нигде.
//   2. ТОЛЬКО к принимающей ноге GMX. Разбавлялись заодно борроу (реальная издержка) и нога
//      Hyperliquid, которая от нашего входа в базу GMX не зависит вовсе. Здесь модуль возвращает
//      ставку ОДНОЙ ноги и про остальные не знает.
//   3. ЧАСЫ, КОГДА ПЛАТИМ МЫ, НЕ МАСШТАБИРУЮТСЯ. Умножение убытка на 0.033 стирало 97% собственных
//      убытков в нашу пользу. Здесь `f <= 0` возвращает множитель ровно 1.
//
// ЧЕГО ЗДЕСЬ НЕТ, И ЭТО ГРАНИЦА, А НЕ ЗАБЫТАЯ ДЕТАЛЬ. Второй порядок эффекта (наш вход сокращает
// перекос и снижает ставку самого плательщика) НЕ измерен и в формулу не входит; верхняя оценка
// его величины больше самого разбавления. Поэтому `B/(B+S)` это ВЕРХНЯЯ оценка того, что нам
// достанется, и называть её «замером» нельзя: наблюдать поведение GMX с нашей позицией внутри
// рынка невозможно в принципе.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ВНУТРИ paper.js И НЕ ВНУТРИ БУДУЩЕГО fa/sizing.js. Формулу зовут
// двое: леджер (`paper.js`) сейчас и правило размера входа (`fa/sizing.js`) потом. Правило размера
// по спецификации САМО зовёт леджер, чтобы оценить доход, поэтому положить формулу туда значит
// завести цикл импортов; положить её в леджер значит спрятать правило внутрь начисления. Лист
// дерева, который зовут оба, это единственная раскладка, в которой формула существует в одном
// экземпляре, а проект уже четырежды ловил дефект «две части системы решают одну задачу разными
// правилами».

import { GMX_OI_SCALE } from "../signs.js";

