  "we_pay", // платим мы, правило 3
  "no_base", // базы на этот час нет: доход обнулён, издержки ноги остаются
  "base_identity_broken", // база пришла НЕ ТА: тождество не сошлось, доход обнулён
  "diluted", // применён множитель B/(B+S)
