// dilution.js - РАЗБАВЛЕНИЕ ВХОДА СОБСТВЕННЫМ РАЗМЕРОМ. PURE: ни сети, ни файлов, ни Date.now.
//
// ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. До этого модуля бумажный леджер начислял фандинг по КОТИРУЕМОЙ ставке и
// не спрашивал, есть ли на встречной стороне деньги, чтобы её заплатить. Счёт показывал прибыль,
// которой не существует: на 25 рынках из 63 модель книжила себе больше, чем рынок выплатил ВСЕМ
// участникам за год (MOODENG $651 526 против выплаченных рынком $6 812). Четыре прогона
// исследования подряд строились на этом фантоме.
//
// ОТКУДА БЕРЁТСЯ ФОРМУЛА. У GMX держится тождество
//     |f_long| * B_long = |f_short| * B_short = pot        [доллар в секунду]
// где B это база фандинга стороны (`longFundingBalanceOiUsd` / `shortFundingBalanceOiUsd`), а pot
// это ВЕСЬ поток фандинга рынка в этот час. Проверено на 245 308 часах: медиана относительной
// невязки 1.3e-14%, p99 равен 4.3e-14%; на трёх фикстурах репозитория (APT, BTC, ETH, 8761 час
// каждая) медиана 1.31e-14 .. 1.39e-14% и p99 до 4.31e-14%.
//
// Поток плательщика pot от нашего появления не растёт. Значит наш вход размера S в ПРИНИМАЮЩУЮ
// сторону увеличивает её базу, и на доллар достаётся pot/(B+S) вместо pot/B, то есть к котируемой
// ставке применяется множитель
//     B / (B + S)
// Модуль считает именно `f * B/(B+S)`, а не `pot/(B+S)`: по тождеству это одно и то же число, но
// первая форма требует ОДНУ величину (базу нашей стороны) вместо трёх, а лишняя величина это
// лишний способ ошибиться. `potOf` остаётся отдельно и служит ПРОВЕРКОЙ тождества, а не путём
// вычисления.
//
// ТРИ ПРАВИЛА ПРИМЕНЕНИЯ, И КАЖДОЕ КУПЛЕНО ОШИБКОЙ:
//   1. ПОЧАСОВО, а не средним множителем по окну. Считалось `E[w] * Sx` вместо `Sw * x`, а деньги
//      сидят в часах с самой малой базой, то есть с наибольшим весом. Здесь правило вызывается на
//      каждом начислении, среднего не существует нигде.
//   2. ТОЛЬКО к принимающей ноге GMX. Разбавлялись заодно борроу (реальная издержка) и нога
//      Hyperliquid, которая от нашего входа в базу GMX не зависит вовсе. Здесь модуль возвращает
//      ставку ОДНОЙ ноги и про остальные не знает.
//   3. ЧАСЫ, КОГДА ПЛАТИМ МЫ, НЕ МАСШТАБИРУЮТСЯ. Умножение убытка на 0.033 стирало 97% собственных
//      убытков в нашу пользу. Здесь `f <= 0` возвращает множитель ровно 1.
//
// ЧЕГО ЗДЕСЬ НЕТ, И ЭТО ГРАНИЦА, А НЕ ЗАБЫТАЯ ДЕТАЛЬ. Второй порядок эффекта (наш вход сокращает
// перекос и снижает ставку самого плательщика) НЕ измерен и в формулу не входит; верхняя оценка
// его величины больше самого разбавления. Поэтому `B/(B+S)` это ВЕРХНЯЯ оценка того, что нам
// достанется, и называть её «замером» нельзя: наблюдать поведение GMX с нашей позицией внутри
// рынка невозможно в принципе.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ВНУТРИ paper.js И НЕ ВНУТРИ БУДУЩЕГО fa/sizing.js. Формулу зовут
// двое: леджер (`paper.js`) сейчас и правило размера входа (`fa/sizing.js`) потом. Правило размера
// по спецификации САМО зовёт леджер, чтобы оценить доход, поэтому положить формулу туда значит
// завести цикл импортов; положить её в леджер значит спрятать правило внутрь начисления. Лист
// дерева, который зовут оба, это единственная раскладка, в которой формула существует в одном
// экземпляре, а проект уже четырежды ловил дефект «две части системы решают одну задачу разными
// правилами».

import { GMX_OI_SCALE } from "../signs.js";

// Причины, по которым множитель получился таким, какой он есть. Причина едет в журнал начисления и
// дальше в интерфейс: разбавление, которое случилось молча, ничем не отличается от фантома.
export const FA_DILUTION_REASONS = Object.freeze([
  "off", // разбавление у этой позиции выключено
  "no_size", // размер нулевой: рынок нас не заметил
  "we_pay", // платим мы, правило 3
  "no_base", // базы на этот час нет: доход обнулён, издержки ноги остаются
  "diluted", // применён множитель B/(B+S)
]);

// Нейтральный результат. Отдельная замороженная константа, а не литерал на месте: вызывающий
// сравнивает `factor === 1` и обязан получать в этой ветке ровно ту же арифметику, что до правки.
export const NO_DILUTION = Object.freeze({ rate: null, factor: 1, reason: "off" });

// Порог сходимости тождества. 1e-6 это запас в восемь порядков к наблюдённому p99 (4.3e-16 в
// долях), то есть срабатывает он не на шуме плавающей точки, а только когда база пришла не та.
export const FA_IDENTITY_MAX_REL_ERR = 1e-6;

// База фандинга приходит из первоисточника строкой в той же неподвижной точке 1e30, что и открытый
// интерес в `markets/info`, поэтому масштаб берётся оттуда, а не заводится второй константой.
export function baseUsd(raw) {
  const x = Number(raw);
  return Number.isFinite(x) ? x / GMX_OI_SCALE : NaN;
}

// Множитель к котируемой ставке. Строго убывает по S, равен 1 при S = 0 и 0.5 при S = B.
//
// НУЛЕВАЯ БАЗА ДАЁТ НОЛЬ, А НЕ ЕДИНИЦУ, и это не мелочь: в опровергнутом расчёте выражение
// `Math.max(b, 0) + size` при нулевой базе давало множитель 1, то есть полное удержание там, где
// верное удержание равно нулю. Если платить некому, не достаётся ничего.
export function dilutionFactor(bOwnUsd, sizeUsd) {
  if (!Number.isFinite(sizeUsd) || sizeUsd <= 0) return 1;
  if (!Number.isFinite(bOwnUsd) || bOwnUsd <= 0) return 0;
  return bOwnUsd / (bOwnUsd + sizeUsd);
}

// Проверка тождества GMX и величина потока рынка. НЕ используется для вычисления ставки (см. шапку):
// нужна там, где надо убедиться, что база пришла та самая, а не соседнее поле с похожим именем.
// Возвращает поток в долларах за секунду, относительную невязку и вердикт.
export function potOf(fLong, bLongUsd, fShort, bShortUsd) {
  const a = Math.abs(fLong) * bLongUsd;
  const b = Math.abs(fShort) * bShortUsd;
  if (!Number.isFinite(a) || !Number.isFinite(b)) return { pot: NaN, relErr: NaN, ok: false };
  const den = Math.max(a, b);
  if (!(den > 0)) return { pot: 0, relErr: 0, ok: true }; // поток нулевой: делить нечего и нечего сверять
  const relErr = Math.abs(a - b) / den;
  return { pot: den, relErr, ok: relErr <= FA_IDENTITY_MAX_REL_ERR };
}

// База НАШЕЙ стороны из часовой строки или живого снимка. Поля названы `fbase_*`, а не `b_*`,
// нарочно: `b_long` / `b_short` в этом коде уже означают БОРРОУ, и вся история прогонов состоит из
// путаницы «какая величина какая». Отсутствие поля это не ошибка формата, а обычное состояние
// строки без баз, поэтому возвращается причина, а не исключение.
export function resolveBase(rowOrSnapshot, gmxSide) {
  const r = rowOrSnapshot || {};
  const bOwnUsd = gmxSide === "short" ? r.fbase_short : r.fbase_long;
  const bOtherUsd = gmxSide === "short" ? r.fbase_long : r.fbase_short;
  const ok = Number.isFinite(bOwnUsd) && bOwnUsd > 0;
  return { bOwnUsd, bOtherUsd, ok, reason: ok ? null : "no_base" };
}

// ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЖИВУТ ВСЕ ТРИ ПРАВИЛА ПРИМЕНЕНИЯ. Возвращает ставку после разбавления,
// множитель и причину.
//
// ПЛАТЕЛЬЩИКА ОПРЕДЕЛЯЕТ ЗНАК СТАВКИ, А НЕ ВЕЛИЧИНА БАЗЫ. Сравнение баз тавтологично тождеству из
// шапки и не проверяет ничего: в 23.05% часов (56 540 из 245 308 по 28 именам) платит МЕНЬШАЯ
// сторона. На этой подмене погорели три агента исследования из пяти.
//
// БАЗЫ НЕТ ЗНАЧИТ ДОХОД НОЛЬ, а не «начислим как раньше». Это консервативный выбор: на годовой
// выборке таких часов 288 из 551 943, то есть 0.052%, и цена выбора мала, а цена обратного выбора
// это молчаливый возврат к фантому ровно в тот момент, когда данные пропали.
export function dilutedFundingRate(f, bOwnUsd, sizeUsd) {
  if (!Number.isFinite(f)) return { rate: f, factor: 1, reason: "off" };
  if (!Number.isFinite(sizeUsd) || sizeUsd <= 0) return { rate: f, factor: 1, reason: "no_size" };
  if (!(f > 0)) return { rate: f, factor: 1, reason: "we_pay" }; // правило 3
  if (!Number.isFinite(bOwnUsd) || bOwnUsd <= 0) return { rate: 0, factor: 0, reason: "no_base" };
  const factor = dilutionFactor(bOwnUsd, sizeUsd);
  return { rate: f * factor, factor, reason: "diluted" };
}
