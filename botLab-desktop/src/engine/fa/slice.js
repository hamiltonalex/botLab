// slice.js - СРЕЗ ВСЕЛЕННОЙ ДЛЯ ПРАВИЛ. PURE: ни сети, ни файлов, ни Date.now.
//
// ЧТО ЭТО. Форма, которую принимают `sizeUniverse` (правило входа) и `decideExit` (правило выхода):
// одна строка на инструмент, с окном истории, живым снимком баз, стаканом и кривыми удара. Главный
// процесс складывает её из своего состояния (`faAutoMarkets`), а здесь лежит САМА СКЛАДКА, без
// единого обращения к состоянию.
//
// ПОЧЕМУ СКЛАДКА ПЕРЕЕХАЛА В ДВИЖОК. Фаза 3 расширения вселенной меняет ровно одно: ОТКУДА берётся
// список инструментов для этой складки (пять имён запаса или живой отбор). Приёмка фазы требует
// проверить, что срез НА ПОЛУСОТНЕ ИНСТРУМЕНТОВ правило принимает, а такая проверка, написанная по
// копии складки, проверяла бы копию. Второй реализации одной задачи проект уже стоил четырёх
// дефектов, поэтому складка одна и лежит там, где её видит тест.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЭТОТ СРЕЗ И СРЕЗ СТЕНДА РАЗЛИЧАЮТСЯ ПО ПОСТРОЕНИЮ, И ОБА РАЗЛИЧИЯ НАДО ЗНАТЬ
// ─────────────────────────────────────────────────────────────────────────────
//
// Числа расширения вселенной ($559.11 нетто за год на 32 именах при капитале $2500) сняты стендом
// `gate5-subset-grid.mjs`, и его срез (`sliceAt`) ОТЛИЧАЕТСЯ от этого двумя полями:
//
//   1. ВОРОТА СТАКАНА. У стенда полей `bookMissing` и `bookAgeSec` в срезе НЕТ ВОВСЕ, значит
//      `dataGate` их не проверяет и ни один рынок не отсеивается кодами `no_book` и `stale_book`.
//      Здесь стакан живой и обязательный. СОВПАДЕНИЕ ЧИСЕЛ С ЧИСЛАМИ СТЕНДА ОЗНАЧАЛО БЫ, ЧТО ЭТОТ
//      СРЕЗ ПОТЕРЯЛ ВОРОТА СТАКАНА, то есть совпадения надо не добиваться, а бояться.
//   2. КРИВАЯ УДАРА GMX. У стенда она есть (снимок глубины 30.08), здесь `gmxNodes` пуст: живого
//      источника глубины GMX у приложения нет. Это открытый риск, названный отчётом фазы 3, а не
//      недосмотр складки.
//
// Отсюда предмет проверки: не «те же числа», а ПАРИТЕТ ФОРМЫ - что правило этот срез принимает и
// что живые ворота стакана остаются ЕДИНСТВЕННЫМ, чем он отличается от среза без них.
//
// ЧТО СКЛАДКА НЕ ДЕЛАЕТ. Не отбирает: какие инструменты пришли, те и легли строками. Отбор живёт в
// `universe-scan.js`, ворота истории в `auto.js`, ворота данных в `sizing.js`. Не считает экономику
// ни одним числом.

import { legModel } from "../paper.js";
import { schemeOf } from "./universe-scan.js";

// ОДНА СТРОКА СРЕЗА. Аргументы это уже добытые главным процессом куски состояния, а не способ их
// добыть: складка не знает ни про кэш кадров, ни про карту стаканов, ни про ключи снимков.
//
//   inst   - инструмент списка (ключ, цепь, монета биржи, предельное плечо запаса);
//   snap   - снимок рынка этого опроса либо null;
//   book   - стакан монеты биржи (`{ at, slip }`) либо null;
//   rows   - кадр истории инструмента (может быть пустым: рынок без кадра для правила не
//            существует, и отсеет его ворота покрытия в `auto.js`, а не складка);
//   nowMs  - момент складки, им меряется возраст стакана;
//   gmxAt  - момент последнего ответа GMX, им меряется возраст баз.
export function faSliceRow({ inst, snap = null, book = null, rows = [], nowMs, gmxAt = null }) {
  const strategy = schemeOf(inst);
  const raw = snap?.raw || {};
  // Конфигурацию (какая нога GMX) выбирает тот же расчёт, что и панель: у одноногой её нет.
  const config = strategy === "two" ? (snap?.chosen ?? "A") : null;
  const { gmxSide } = legModel(strategy, config);
  return {
    token: inst.key,
    config,
    strategy,
    chain: inst.chain,
    directionKnown: strategy === "one" || !!(snap?.dataComplete && snap?.gateOk !== false),
    rows: rows || [],
    markPx: Number.isFinite(snap?.price) ? snap.price : null,
    hlMaxLev: snap?.hlMaxLev ?? inst.hlMaxLev ?? null,
    live: {
      bOwnUsd: gmxSide === "short" ? raw.fbase_short : raw.fbase_long,
      bOtherUsd: gmxSide === "short" ? raw.fbase_long : raw.fbase_short,
      baseAgeSec: gmxAt ? (nowMs - gmxAt) / 1000 : undefined,
      baseIdentityOk: snap ? snap.gateOk !== false : undefined,
      bookMissing: !book,
      bookAgeSec: book ? (nowMs - book.at) / 1000 : undefined,
      gmxAvailOwnUsd: gmxSide === "short" ? snap?.avail?.shortUsd : snap?.avail?.longUsd,
      hlVisibleNtl: book?.slip?.visibleNtl,
      hlExhaustedFrom: book?.slip?.exhaustedFrom ?? undefined,
    },
    // Кривая удара GMX в приложении отсутствует (см. шапку); стакан Hyperliquid живой.
    impact: { gmxNodes: [], hlNodes: book?.slip?.nodes || [] },
    // ЖИВЫЕ ФАКТОРЫ НОГ, как их отдал источник. Правило размера их не читает: ему нужны базы и
    // стакан. Их читает сводка оценки (`legSpreadApr`), чтобы назвать котируемую ставку схемы одним
    // числом - и считает его ДВИЖОК, потому что разбор схемы на ноги живёт там.
    rates: { f_long: raw.f_long, f_short: raw.f_short, b_long: raw.b_long, b_short: raw.b_short, hl_rate: raw.hl_rate },
  };
}

// ВЕСЬ СРЕЗ. Порядок строк это порядок списка инструментов и другим быть не может: правило
// сравнивает нетто, а не позиции в списке, но запись решения читается глазами, и переставленный
// список выглядел бы как смена состава.
//
// Доступ к состоянию идёт ТРЕМЯ ЧИТАТЕЛЯМИ, а не тремя картами: ключ кадра (`cacheKeyFor`) и ключ
// стакана (монета биржи, а не ключ инструмента) живут в главном процессе, и тащить их сюда значило
// бы завести здесь вторую копию обеих схем ключей.
export function buildFaSlice({ instruments, nowMs, gmxAt = null, snapshotOf, bookOf, rowsOf }) {
  const out = [];
  for (const inst of instruments || []) {
    out.push(faSliceRow({
      inst,
      snap: snapshotOf ? snapshotOf(inst) : null,
      book: bookOf ? bookOf(inst) : null,
      rows: rowsOf ? rowsOf(inst, schemeOf(inst)) : [],
      nowMs,
      gmxAt,
    }));
  }
  return out;
}
