// slice.js - СРЕЗ ВСЕЛЕННОЙ ДЛЯ ПРАВИЛ. PURE: ни сети, ни файлов, ни Date.now.
//
// ЧТО ЭТО. Форма, которую принимают `sizeUniverse` (правило входа) и `decideExit` (правило выхода):
// одна строка на инструмент, с окном истории, живым снимком баз, стаканом и кривыми удара. Главный
// процесс складывает её из своего состояния (`faAutoMarkets`), а здесь лежит САМА СКЛАДКА, без
// единого обращения к состоянию.
//
// ПОЧЕМУ СКЛАДКА ПЕРЕЕХАЛА В ДВИЖОК. Фаза 3 расширения вселенной меняет ровно одно: ОТКУДА берётся
// список инструментов для этой складки (пять имён запаса или живой отбор). Приёмка фазы требует
// проверить, что срез НА ПОЛУСОТНЕ ИНСТРУМЕНТОВ правило принимает, а такая проверка, написанная по
// копии складки, проверяла бы копию. Второй реализации одной задачи проект уже стоил четырёх
// дефектов, поэтому складка одна и лежит там, где её видит тест.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЭТОТ СРЕЗ И СРЕЗ СТЕНДА РАЗЛИЧАЮТСЯ ПО ПОСТРОЕНИЮ, И ОБА РАЗЛИЧИЯ НАДО ЗНАТЬ
// ─────────────────────────────────────────────────────────────────────────────
//
// Числа расширения вселенной ($559.11 нетто за год на 32 именах при капитале $2500) сняты стендом
// `gate5-subset-grid.mjs`, и его срез (`sliceAt`) ОТЛИЧАЕТСЯ от этого двумя полями:
//
//   1. ВОРОТА СТАКАНА. У стенда полей `bookMissing` и `bookAgeSec` в срезе НЕТ ВОВСЕ, значит
//      `dataGate` их не проверяет и ни один рынок не отсеивается кодами `no_book` и `stale_book`.
//      Здесь стакан живой и обязательный. СОВПАДЕНИЕ ЧИСЕЛ С ЧИСЛАМИ СТЕНДА ОЗНАЧАЛО БЫ, ЧТО ЭТОТ
//      СРЕЗ ПОТЕРЯЛ ВОРОТА СТАКАНА, то есть совпадения надо не добиваться, а бояться.
//   2. КРИВАЯ УДАРА GMX. РАЗЛИЧИЕ СНЯТО 18.09, и это предмет отдельной правки. До неё здесь стояло
//      `gmxNodes: []`, и пустые узлы означали НЕ ноль издержки, а плоскую константу `gmxImpact`
//      0.1% из `costs.js`: пустая кривая выключает ветку `hasGmxCurve` в `costAtSize`. Константа
//      берёт 10 базисных пунктов, а измеренная величина на тикете $2500 это медиана 0.001 бп
//      (ровно ноль у 57 наблюдений из 126) при максимуме 13.38, то есть константа завышала круг
//      издержек почти везде; цена на 63 рынках при $2500 - **-$64.46 нетто за год** ($840.30 против
//      $775.84), и она росла с числом рынков. Теперь узлы приносит читатель `impactOf`
//      (`impact-curve.js`), а рынок, которого в снимке нет, получает НАЗВАННЫЙ запасной путь, а не
//      молчаливую подстановку: источник каждой строки едет в `live.gmxCurveSrc`.
//
// Отсюда предмет проверки: не «те же числа», а ПАРИТЕТ ФОРМЫ - что правило этот срез принимает и
// что живые ворота стакана остаются ЕДИНСТВЕННЫМ, чем он отличается от среза без них.
//
// ТРЕТЬЕ РАЗЛИЧИЕ БЫЛО И СНЯТО 18.09: СТОРОНА НОГИ. Стенд и обе книги выбирают её `scanTwoLeg` по
// окну оценки, а этот срез брал её из мгновенной строки опроса, то есть живой бот исполнял не то
// правило, которое стерегут книги (цена -$15.33 нетто за год и минус 27% профинансированных рынков
// на срез). Различие было НЕ НАЗВАНО ни здесь, ни в шапке ниже, и это главный урок находки: оба
// расчёта называли сторону одним словом `chosen`, и именно этим расхождение было спрятано.
//
// ЧТО СКЛАДКА НЕ ДЕЛАЕТ. Не отбирает: какие инструменты пришли, те и легли строками. Отбор живёт в
// `universe-scan.js`, ворота истории в `auto.js`, ворота данных в `sizing.js`. Не считает экономику
// ни одним числом.

import { legModel } from "../paper.js";
import { scanTwoLeg } from "../math.js";
import { resolveBase } from "./dilution.js";
import { schemeOf } from "./universe-scan.js";

// ─────────────────────────────────────────────────────────────────────────────
// СТОРОНА НОГИ ВЫБИРАЕТСЯ ПО ОКНУ ОЦЕНКИ, А НЕ ПО МГНОВЕННОЙ СТРОКЕ ОПРОСА
// ─────────────────────────────────────────────────────────────────────────────
//
// Это тот самый выбиратель, которым пользуются обе замороженные книги бота 1
// (`replay-funding-size.mjs`, `replay-funding-exit.mjs`), стенды фазы 5 и панель входа интерфейса
// (`buildTwoLegEntry`), и он же назван в `SPEC-bot1-sizing.md` 1.2: «конфигурацию выбирает
// `scanTwoLeg` по ОБУЧАЮЩЕМУ ОКНУ, и правило размера её принимает как данность».
//
// ЧТО БЫЛО ДО 18.09. Здесь стояло `snap?.chosen`, а это ОДНА мгновенная строка опроса
// (`assemble.js`, `a.net_A >= a.net_B`). Живой бот исполнял не то правило, которое стерегут книги, и
// увидеть это не могла ни одна проверка проекта: книги этот код не трогают вовсе. Цена, замеренная
// аудитом на 63 рынках при капитале $2500: **-$15.33 нетто за год** и минус 27% профинансированных
// рынков на срез (26.04 против 35.70). Критерии расходятся на 33.1% часов, а живьём сторона снимка
// переворачивается 3.8 раза в сутки у BTC против нуля переворотов у средней по 720 часам.
//
// ЧЕГО ЗДЕСЬ НАРОЧНО НЕ СДЕЛАНО: перебора обеих сторон полным правилом с выбором лучшей по нетто.
// Это выглядит как принцип владельца «перебирать все варианты и брать лучший», но ИЗМЕРЕНО И ХУЖЕ:
// $812.53 против $840.30 у оконного критерия, потому что нетто на трейлинге это оценка ВНУТРИ
// ВЫБОРКИ, и сторона, выигравшая по ней, чаще разворачивается (29 перекладок против 27). Принцип
// при этом не нарушен: перебор относится к РАЗМЕРУ и РЫНКУ, где он полон, а сторона это свойство
// рынка, оценённое на том же окне, на котором считается всё остальное.
//
// ОКНО ПРИХОДИТ СНАРУЖИ И СВОЕГО ЗДЕСЬ НЕТ. Кадр в срезе длиной до года (`WINDOW_DAYS`), а правило
// считает по окну оценки (`windowH`, сегодня 720 ч), и нарезка кадра живёт в `auto.js`. Своё число
// окна здесь было бы вторым источником истины, и первая же правка пресета развела бы сторону с
// брутто, посчитанным на другом окне. Поэтому окно передаёт тот, кто его знает, а без него сторона
// выбирается запасным путём и это ВИДНО полем `directionKnown`.
function windowConfig(rows, windowH) {
  if (!Number.isFinite(windowH) || windowH <= 0) return null;
  const all = rows || [];
  if (all.length < windowH) return null;
  return scanTwoLeg(all.slice(all.length - windowH))?.chosen ?? null;
}

// ОДНА СТРОКА СРЕЗА. Аргументы это уже добытые главным процессом куски состояния, а не способ их
// добыть: складка не знает ни про кэш кадров, ни про карту стаканов, ни про ключи снимков.
//
//   inst   - инструмент списка (ключ, цепь, монета биржи, предельное плечо запаса);
//   snap   - снимок рынка этого опроса либо null;
//   book   - стакан монеты биржи (`{ at, slip }`) либо null;
//   rows   - кадр истории инструмента (может быть пустым: рынок без кадра для правила не
//            существует, и отсеет его ворота покрытия в `auto.js`, а не складка);
//   nowMs  - момент складки, им меряется возраст стакана;
//   gmxAt  - момент последнего ответа GMX, им меряется возраст баз;
//   windowH - окно оценки в часах, по нему выбирается сторона ноги (см. блок выше). Без него
//            сторона падает на мгновенную строку снимка, и это видно полем `directionKnown`.
export function faSliceRow({ inst, snap = null, book = null, rows = [], nowMs, gmxAt = null, windowH = null, impactOf = null }) {
  const strategy = schemeOf(inst);
  const raw = snap?.raw || {};
  // Конфигурацию (какая нога GMX) выбирает `scanTwoLeg` на окне оценки: тот же расчёт, что у книг,
  // стендов и панели входа. У одноногой схемы конфигурации нет вовсе.
  const windowSide = strategy === "two" ? windowConfig(rows, windowH) : null;
  const config = strategy === "two" ? (windowSide ?? snap?.chosen ?? "A") : null;
  const { gmxSide } = legModel(strategy, config);
  // ТОЖДЕСТВО БАЗ СТОРОН СЧИТАЕТСЯ ЖИВЬЁМ, И ЭТО ТО САМОЕ, ЧТО ОБЕЩАЕТ SPEC 3.3. До 18.09 в поле
  // `baseIdentityOk` ехал `snap.gateOk`, то есть СОВСЕМ ДРУГАЯ проверка: тождество `netRate ==
  // funding + borrow` внутри ответа `markets/info` (находка 6.8 аудита механики). Следствий было
  // два, и оба неприятные. Оператору при сбое знаков говорили «база пришла не та», то есть
  // указывали чинить не то место. И защита от переключения флага GMX
  // `useOpenInterestInTokensForBalance` на уровне рынка отсутствовала вовсе, хотя шапка
  // `assemble.js` ссылается на неё как на действующую.
  //
  // ПОРОГ СТРОГИЙ, И ЭТО ЗАМЕР, А НЕ СМЕЛОСТЬ. Живой снимок несёт базы и ставки ОДНОГО ответа
  // источника, поэтому им незачем расходиться (слабый допуск 5% заведён для строк кадра, где базы
  // живые, а ставки индексаторские). Замер по копии живой записи mb12 (18 110 наблюдений, 3627
  // снимков за 12.6 суток, пять инструментов): медиана невязки 2.9e-10, у ETH-Avax 3.2e-8,
  // максимум 1.3e-7, и НИ ОДНОГО наблюдения выше строгого порога 1e-6. То есть ворота, включённые
  // этой правкой, живьём не отказывают ни одному рынку, а подмену базы ловят: та же подмена
  // интереса в токенах даёт невязку 0.92% у BTC и 20.6% у ETH.
  const baseId = snap ? resolveBase(raw, gmxSide) : null;
  // КРИВАЯ УДАРА БЕРЁТСЯ У ЧИТАТЕЛЯ, а не читается здесь: срез чистый, файлов он не открывает.
  // Не переданный читатель это `none`, то есть ПРЕЖНЕЕ поведение (пустые узлы) - и оно остаётся
  // достижимым намеренно, иначе тест среза пришлось бы снабжать снимком ради чужого предмета.
  const gmxCurve = (impactOf ? impactOf(inst, gmxSide) : null) || { nodes: [], src: "none" };
  return {
    token: inst.key,
    config,
    strategy,
    chain: inst.chain,
    // СТОРОНА ПОДТВЕРЖДЕНА ОКНОМ. Поле читает только трасса входа, и вопрос у неё один: на чём
    // стоит выбор A/B. До 18.09 здесь стояла полнота ЖИВОГО СНИМКА, потому что по снимку сторона и
    // выбиралась; теперь её выбирает окно, и полнота снимка на выбор не влияет никак (рынок с
    // неполным снимком отказывает своими кодами `no_base` и `base_identity_broken`, и это другой
    // разговор). Ложь здесь дороже обычного: трасса это свидетель замысла для следующего аудита.
    directionKnown: strategy === "one" || windowSide != null,
    rows: rows || [],
    markPx: Number.isFinite(snap?.price) ? snap.price : null,
    hlMaxLev: snap?.hlMaxLev ?? inst.hlMaxLev ?? null,
    live: {
      bOwnUsd: gmxSide === "short" ? raw.fbase_short : raw.fbase_long,
      bOtherUsd: gmxSide === "short" ? raw.fbase_long : raw.fbase_short,
      baseAgeSec: gmxAt ? (nowMs - gmxAt) / 1000 : undefined,
      // Только про тождество баз: отсутствие базы это `no_base`, и мешать их нельзя.
      baseIdentityOk: baseId ? baseId.reason !== "base_identity_broken" : undefined,
      // ЧИСЛА ИСТОЧНИКА СХОДЯТСЯ САМИ С СОБОЙ. Отдельное поле и отдельный код отказа: источник
      // ответил, но его тождество нетто ноги против фандинга и борроу не сошлось либо ставка
      // Hyperliquid вне разумной полосы. Раньше это ехало под кодом тождества баз.
      srcPlausible: snap ? snap.gateOk !== false : undefined,
      bookMissing: !book,
      bookAgeSec: book ? (nowMs - book.at) / 1000 : undefined,
      gmxAvailOwnUsd: gmxSide === "short" ? snap?.avail?.shortUsd : snap?.avail?.longUsd,
      hlVisibleNtl: book?.slip?.visibleNtl,
      hlExhaustedFrom: book?.slip?.exhaustedFrom ?? undefined,
      // ОТКУДА ВЗЯЛАСЬ КРИВАЯ УДАРА. Читает только трасса: правило этого поля не видит и видеть не
      // должно. `market` это своя измеренная кривая рынка, `tier` и `pooled` это запасной путь
      // (рынка в снимке нет либо он на другой цепи), `none` это отсутствие узлов вовсе. Поле
      // существует ровно затем, чтобы подстановка чужой кривой НИКОГДА не была молчаливой.
      gmxCurveSrc: gmxCurve.src,
    },
    // КРИВАЯ УДАРА GMX ИЗМЕРЕННАЯ, а не пустая (18.09). Пустая здесь означала НЕ ноль издержки, а
    // плоскую константу 0.1% в `costAtSize`, и это -$64.46 нетто за год на 63 рынках при $2500.
    // Узлы приносит `impactOf`, знак приведён в `impact-curve.js` и только там; источник назван
    // строкой ниже, потому что молчаливой подстановки у этой правки быть не должно.
    impact: { gmxNodes: gmxCurve.nodes, hlNodes: book?.slip?.nodes || [] },
    // ЖИВЫЕ ФАКТОРЫ НОГ, как их отдал источник. Правило размера их не читает: ему нужны базы и
    // стакан. Их читает сводка оценки (`legSpreadApr`), чтобы назвать котируемую ставку схемы одним
    // числом - и считает его ДВИЖОК, потому что разбор схемы на ноги живёт там.
    rates: { f_long: raw.f_long, f_short: raw.f_short, b_long: raw.b_long, b_short: raw.b_short, hl_rate: raw.hl_rate },
  };
}

// ВЕСЬ СРЕЗ. Порядок строк это порядок списка инструментов и другим быть не может: правило
// сравнивает нетто, а не позиции в списке, но запись решения читается глазами, и переставленный
// список выглядел бы как смена состава.
//
// Доступ к состоянию идёт ТРЕМЯ ЧИТАТЕЛЯМИ, а не тремя картами: ключ кадра (`cacheKeyFor`) и ключ
// стакана (монета биржи, а не ключ инструмента) живут в главном процессе, и тащить их сюда значило
// бы завести здесь вторую копию обеих схем ключей.
export function buildFaSlice({ instruments, nowMs, gmxAt = null, windowH = null, snapshotOf, bookOf, rowsOf, impactOf = null }) {
  const out = [];
  for (const inst of instruments || []) {
    out.push(faSliceRow({
      inst,
      snap: snapshotOf ? snapshotOf(inst) : null,
      book: bookOf ? bookOf(inst) : null,
      rows: rowsOf ? rowsOf(inst, schemeOf(inst)) : [],
      nowMs,
      gmxAt,
      windowH,
      impactOf,
    }));
  }
  return out;
}
