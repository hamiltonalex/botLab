//
// ЧТО ЗДЕСЬ РЕШАЕТСЯ. Держать открытую сделку, закрыть её в кэш или переложиться в лучшую доступную
// альтернативу. Не «когда убыток случился»: решение принимается по ОЦЕНКЕ вперёд, а реализованный
// итог позиции в него не входит ни разу, потому что он утоплен и на выбор ветки влиять не может.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОТКУДА БЕРЁТСЯ КРИТЕРИЙ. Считаем ценность каждой ветки на общем горизонте H от момента решения, с
// рыночной переоценкой в конце: открытая позиция в конце стоит МИНУС собственную стоимость закрытия.
//
//   ДЕРЖАТЬ    = брутто_тек(H) - выход(S_тек)
//   В КЭШ      =                - выход(S_тек)
//   ПЕРЕЛОЖИТЬ =                - выход(S_тек) - вход(S_нов) + брутто_нов(H) - выход(S_нов)
//
// Вычитаем «держать»:
//   В КЭШ    минус ДЕРЖАТЬ = -брутто_тек(H)
//   ПЕРЕЛОЖИТЬ минус ДЕРЖАТЬ = брутто_нов(H) - круг(S_нов) - брутто_тек(H)
//
// `выход(S_тек)` СОКРАТИЛСЯ В ОБЕИХ РАЗНОСТЯХ, и это не приём, а свойство задачи: стоимость закрытия
// текущей позиции платится в любой ветке, значит на выбор ветки влиять не может.
//
// СЛЕДСТВИЕ КРУПНЕЕ, ЧЕМ ВЫГЛЯДИТ: правилу выхода НИКОГДА не нужно знать, как круг делится на
// половину входа и половину выхода. Деления этого измеренная модель издержек и не даёт: `gmxGas` $1
// берётся один раз за круг, хотя платится и на открытии, и на закрытии, и та же претензия у
// `gmxImpact`; честные варианты двигают круг с $7.20 на $8.20 и $10.20 при $2000. Конструкция,
// построенная на «стоимости выхода» отдельно, требовала бы числа, которого у нас нет. Не чинить
// деление ради выхода: выходу оно не нужно.
//
// А `брутто_нов(H) - круг(S_нов)` это РОВНО то, что правило входа уже возвращает полем `netUsd`
// (`sizing.js`: `net = gross - cost`, где `cost = costAtSize(S)` есть полный круг). Поэтому весь
// критерий это максимум трёх чисел В ОДНИХ ЕДИНИЦАХ:
//
//   держать = брутто текущей позиции, в кэш = 0, переложить = нетто лучшей альтернативы.
//
// КЭШ ЭТО АЛЬТЕРНАТИВА С НЕТТО НОЛЬ, а не отдельная ветка со своей семантикой. Из-за этого у правила
// нет ПОРЯДКА проверок, который можно перепутать: у максимума порядка нет. Урок фазы 2 («ограничения
// перекрываются, и первое сработавшее прячет остальные») здесь не воспроизводится по построению.
//
// СООТВЕТСТВИЕ ИЗМЕРЕННОМУ КРИТЕРИЮ ТОЧНОЕ. Прогон 3: «перекладка окупается, если поднимает годовое
// брутто больше чем на $7.20 за каждое решение на $2000 номинала», то есть
// `брутто_нов - брутто_тек > круг(S_нов)`. Это та же строка, перенесённая через круг.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ВЫХОДИТ ИЗ КОНСТРУКЦИИ ДАРОМ, БЕЗ ЕДИНОГО НОВОГО ЧИСЛА.
//
// 1. БЮДЖЕТ РЕШЕНИЙ СОБЛЮДАЕТСЯ КОНСТРУКЦИЕЙ, А НЕ КВОТОЙ. Измерено (прогон 3, разбор скептика):
//    бюджет равен кэрри, делённому на 0.36% номинала, отсюда 8.39 круга в год у BTC two-B на $2000,
//    но 2.31 на $100, 9.72 на $100k и 148.3 у APT. Восемь это не константа стратегии, а частное от
//    той же дроби. Правило, требующее от каждой перекладки полного круга сверху, не может потратить
//    больше, чем поднимет. Счётчик «не более восьми в год» был бы ВТОРЫМ механизмом на ту же цель, с
//    собственным незамеренным числом, и на APT он запрещал бы окупающиеся решения.
//
// 2. ГИСТЕРЕЗИС УЖЕ ЕСТЬ И НУЖНОЙ ШИРИНЫ. Стоим в A; уйти в B требует `брутто_B - круг_B > брутто_A`.
//    Стоя в B, вернуться в A требует `брутто_A - круг_A > брутто_B`. Оба сразу дают
//    `брутто_B - круг_B > брутто_A > брутто_B + круг_A`, что невозможно. НА НЕИЗМЕНИВШИХСЯ ДАННЫХ
//    ПРАВИЛО КОЛЕБАТЬСЯ НЕ МОЖЕТ, и ширина полосы равна кругу, то есть ровно тому, во что колебание
//    обходится. Свойство проверяется тестом, а не обещается.
//
// 3. НИЧЬИ РЕШАЮТСЯ В ПОЛЬЗУ БЕЗДЕЙСТВИЯ. Сравнения строгие: бездействие бесплатно, действие стоит
//    круга. Заводится знак, а не число.
//
// 4. ВЕРШИНА РЕЙТИНГА ЕСТЬ НЕПОДВИЖНАЯ ТОЧКА КРИТЕРИЯ, И ЭТО ТОЖДЕСТВО, А НЕ НАБЛЮДЕНИЕ. Стоя на
//    рынке ранга 1, мы сравниваем брутто удержания с нетто ЛУЧШЕЙ альтернативы, а лучшая
//    альтернатива это та же позиция, чьё нетто равно её же брутто минус круг. Значит критерий не
//    может сработать НИКОГДА. Замер согласен и добавляет градиент: 0 срабатываний из 336 на ранге 1,
//    60.7% на ранге 2, 87.2% на ранге 3, 98.5% на ранге 5, 100% на ранге 10. Причина узости
//    гистерезиса тут же: медианный разрыв нетто до вершины $20.60 против медианного круга $15.46.
//
//    ОГОВОРКА К ЭТОЙ ТАБЛИЦЕ: она идеализирована, потому что брутто удержания берётся при ТЕКУЩЕМ
//    оптимальном размере рынка. В живой траектории размер зафиксирован моментом входа и с
//    оптимальным расходится, и это расхождение есть храповик из раздела границ. Неподвижность
//    вершины и храповик складывать в одно число нельзя: первое про критерий, второе про размер.
//
//    ЗАМЕРЕНО, ЧТО ПРАВИЛО ЖИВЁТ ИМЕННО НА ВЕРШИНЕ: действующая позиция занимает ранг 1 в 224
//    решениях из 268 (83.6%) и ранг не ниже 3 в 97.8%, при медиане 37 годных кандидатов; ещё в 38
//    точках из 306 позиция ВЫПАЛА из годных вовсе, и это другое состояние, а не плохой ранг.
//    Отсюда прямое объяснение того, почему края у ветки перекладки не измерено: она сравнивает верх
//    рейтинга с верхом. Парно ранг 1 против ранга 2 выигрывает 51.0% точек при медиане разности
//    $2.77, то есть у верхушки рейтинг неразличим.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГОРИЗОНТ. СВОЕГО У ПРАВИЛА ВЫХОДА НЕТ, берётся `cfg.horizonH` правила входа (720 ч).
//
// Две величины, склеенные в правиле входа по построению, для выхода надо развести: ОКНО ОЦЕНКИ
// (сколько прошлых часов берём) и ГОРИЗОНТ РЕШЕНИЯ (за сколько часов накапливаем выгоду до сравнения
// с разовой издержкой).
//
// Ветка кэша горизонта НЕ ТРЕБУЕТ: `брутто_тек` пропорционально длине окна, а условие «меньше нуля»
// инвариантно к положительному множителю. Ветка перекладки требует и чувствительна прямо: брутто
// растёт с горизонтом линейно, круг не растёт вовсе, поэтому вдвое больший горизонт делает
// перекладку вдвое охотнее. Но выбирать не из чего: `нетто_альт` посчитано правилом входа НА ЕГО
// горизонте и круг вычтен там же, поэтому сравнение при другом горизонте есть сравнение разных
// ЕДИНИЦ. Свой горизонт сделал бы рынок достойным финансирования при входе и недостойным при
// удержании из-за выбора одного числа.
//
// НЕПРЕРЫВНОСТЬ РЕШЕНИЙ ГОРИЗОНТ НЕ УКОРАЧИВАЕТ. Она двигает окно, а не его длину, и меняет ЧИСЛО
// ПОПЫТОК. Соседние часовые оценки делят 719 строк из 720, то есть 99.86% данных; окно обновляется
// целиком за 720 часов, значит независимых взглядов в году около 8760/720 = 12.2, тот же порядок,
// что бюджет 8.39-9.72 круга.
//
// УКОРОЧЕНИЕ ОКНА У ВЕТКИ КЭША ПРОВЕРЕНО И ОПРОВЕРГНУТО. Хотя знак инвариантен к длине окна и
// укоротить его формально законно, замер на 63 рынках и 76 923 точках даёт (окно назад: точность
// выходов / доля эпизодов, пойманных заблаговременно / доля часов с выходом):
//   72 ч - 64.6% / 20.9% / 38.8%;  168 ч - 67.1% / 23.5% / 36.2%;
//   336 ч - 69.4% / 29.7% / 33.6%; 720 ч - 69.8% / 40.4% / 30.0%.
// Короткое окно хуже по точности и по своевременности, а выходов делает на треть больше, и каждый
// стоит круга. Второго окна нет: у правила выхода ОДНО окно, то же, что у входа.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЭТО ПРАВИЛО НЕ УМЕЕТ, И ЭТО ГРАНИЦЫ, А НЕ ЗАБЫТЫЕ ДЕТАЛИ.
//
// ВЫХОД РАНЬШЕ СЧЁТА, НО ПОЗЖЕ РЫНКА. Замер на 63 рынках: сигнал информативен (точность выходов
// 69.8% против 47.8% у случайного выхода той же частоты), но ОПАЗДЫВАЕТ - медианное упреждение минус
// 54 часа, заблаговременно поймано 40.4% эпизодов. Иначе и быть не может: усреднение по окну не
// может опережать изменение в принципе. Честная формулировка ровно такая: правило выходит РАНЬШЕ,
// чем убыток дойдёт до счёта, и ПОЗЖЕ, чем испортился рынок; запаздывание около 7.5% горизонта.
//
// ОСТАЁТСЯ ОТКРЫТЫМ, А НЕ ОПРОВЕРГНУТ: наблюдение за ПОТОКОМ РЫНКА `pot` напрямую. Опровергнуто
// выше УКОРОЧЕНИЕ ОКНА У ТОЙ ЖЕ СТАТИСТИКИ, и на `pot` это не переносится: он наблюдаем мгновенно
// и средним не является, поэтому довод про предел усреднения к нему не применяется. Считается он
// из тех же снимков по тождеству `pot = |f| * B`. Опасны два события разной природы: `pot`
// схлопывается (платить перестали) и `pot` меняет знак (платить начали мы). Будущий замер обязан
// мерить ПРИРОСТ поверх уже работающего сигнала, а не способность в одиночку.
//
// И начинать его надо со СХЛОПЫВАНИЯ, а не со смены знака, потому что на смене знака действующий
// сигнал уже силён и вдобавок СМЕЩЁН в её сторону конструкцией правила 3 фазы 1: час получения
// входит в брутто уценённым множителем `B/(B+S)`, а час уплаты входит НЕУЦЕНЁННЫМ, потому что не
// масштабируется вовсе. Плохие часы весят полным номиналом, хорошие уценены, и при удержании 2%
// асимметрия веса пятидесятикратная. Прирост нового прибора на смене знака предсказуемо близок к
// нулю; искать его надо там, где трейлинг видит просто медленно убывающие положительные часы и
// уценивает их вдобавок.
//
// НИЗКОЕ УДЕРЖАНИЕ НЕ ЕСТЬ ПРИЗНАК УБЫТОЧНОСТИ, и охраны по нему здесь нет намеренно. При
// сохранённом потоке рынка `f = pot/B`, поэтому доход равен `pot * S/(B+S)` и УБЫВАЕТ по B: при
// pot = $0.001/с и S = $5000 база $10M даёт удержание 99.95% и доход 5.0e-7, а база $100 даёт
// удержание 1.96% и доход 9.8e-4, то есть в 2000 раз БОЛЬШЕ. Охрана вида «удержание упало ниже
// половины, закрываемся» закрывала бы позиции, которые зарабатывают больше всего. Ограничение О2
// правила входа этим НЕ задето: там S выбирается при данной B, доход по S насыщается на `pot`, а
// издержки растут линейно, поэтому потолок нужен; здесь B меняется при уже выбранном S, и знак
// зависимости обратный. Это РАЗНЫЕ переменные, и путать их нельзя.
//
// ИЗМЕНЕНИЕ РАЗМЕРА НА МЕСТЕ моделируется как ПОЛНЫЙ КРУГ, то есть как перекладка в тот же рынок
// другим размером, и ветка перекладки это видит. Дешёвая доразмещающая операция (долить $1000 к
// позиции $2000 стоит входную половину на $1000, а не круг на $3000) НЕ моделируется, потому что её
// цена требует деления круга на половины, которого измеренная модель не даёт.
//
// ХРАПОВИК ПО РАЗМЕРУ: ЗАМЕРЕННЫЙ ДЕФЕКТ, А НЕ ТЕОРИЯ. Прежняя запись здесь гласила «смещение
// одностороннее: пропускаем окупающиеся изменения размера, ошибочных не делаем», и она НЕПОЛНА.
// Одиночные решения действительно корректны, а вот их последовательность жжёт деньги. Выдержка из
// прогона при кадансе 1 ч:
//   ANIME/A $1364.65 в $1400.23: брутто $251.16 против нетто $251.82
//   ANIME/A $1400.23 в $1436.47: брутто $257.79 против нетто $258.40
//   ANIME/A $1436.47 в $1472.50: брутто $264.85 против нетто $265.27   ... и так восемь шагов подряд.
// Потолок разбавления медленно ползёт вверх вместе со взвешенной базой, S* ползёт за ним, и правило
// каждый час платит ПОЛНЫЙ круг ($5.34 при $1400) ради прибавки размера в 2.5%, честно окупающей
// круг на $0.66. Восемь шагов стоили $46.07 там, где один шаг с $1364 сразу на $1689 стоил бы $6.24.
//
// Это МИОПИЯ критерия: он сравнивает «держать» с «лучшим размером СЕЙЧАС» и не рассматривает
// «держать сейчас, изменить размер позже».
//
// ЛЕЧЕНИЙ У ХРАПОВИКА ДВА, И ОНИ НЕЗАВИСИМЫ. Путать их дорого: позже кто-нибудь возьмётся строить
// динамическое программирование там, где дешевле починить исполнение.
//   1. РЕШЕНИЕ чинится динамическим программированием: критерий обязан сравнивать не с «лучшим
//      сейчас», а с «лучшим по траектории». Это не порог и в правило выхода не входит.
//   2. ЦЕНА чинится ИСПОЛНИТЕЛЕМ: одношаговое доразмещение торгует ДЕЛЬТУ, а не позицию целиком.
//      Восемь шагов по +2.61% стоят $46.07 полными кругами и $8.97 дельтами, то есть полный круг
//      раздувает цену храповика в 5.1 раза. Живёт это в исполнителе, а не в правиле, но требует
//      деления круга на половины, которого измеренная модель не даёт.
// В фазу 3 не входит НИ ОДНО. Доступное здесь средство без новых чисел одно, и оно применено:
// КАДАНС. Храповиковых шагов 25 из 46 при кадансе 1 ч, 6 из 29 при 24 ч, 1 из 19 при 168 ч.
//
// ОКНО ОЦЕНКИ ВСЕГДА ТРЕЙЛИНГ `horizonH`, независимо от того, сколько позиция уже открыта.
// Оценивается будущее, а не пережитое, и по ста часам удержания оно оценивается хуже, чем по 720.
//
// НАСЛЕДОВАННАЯ ОШИБКА ОЦЕНКИ. `брутто_тек` считается по трейлингу и употребляется как прогноз
// вперёд, значит выход наследует ошибку переноса правила входа. Переносимость РАЗМЕРА измерена и
// умеренная (p90 x10.00 на первом годе, x4.08 на втором), переносимость СТАВКИ, от которой зависит
// именно выход, отдельно НЕ мерилась.
//
// КРАЙ РЕЙТИНГА ЭТО СВОЙСТВО УРОВНЯ, А НЕ МОМЕНТА, и это ограничивает то, что от правила вообще
// можно ждать. Трейлинговый рейтинг обходит случайный годный рынок (медиана брутто вперёд $84.05
// против $25.85, парно выигрывает 70.3% точек), но весь этот край объясняется тем, КАКИЕ рынки он
// выбирает, а не КОГДА. Два замера порознь:
//   вычитание собственного годового уровня каждой руки убивает край целиком: ранг 1 против
//     случайного выигрывает 44.8% при медиане -$2.07 (уровень считается задним числом, поэтому это
//     декомпозиция, а не исполнимая стратегия);
//   рейтинг МЕСЯЧНОЙ ДАВНОСТИ, чей трейлинг с окном вперёд не пересекается вовсе, сохраняет 72%
//     силы по медиане.
// Значит рейтинг работает как медленный фильтр качества рынка. Ждать от правила своевременной
// реакции на порчу конкретного рынка нельзя, и запаздывание в 54 часа из раздела выше это не
// недоделка, а та же самая природа сигнала, увиденная с другой стороны.
//
// И ОГОВОРКА К САМОМУ КРАЮ: часть его РАЗМЕРНАЯ. На потолке тикета стоят 90.5% выборов ранга 1
// против 67.3% случайного, поэтому на равном ноционале разрыв сжимается с 3.25 до 2.38 раза.
// Сравнивать в абсолютных долларах руку «худший годный» с остальными нельзя вовсе: у неё медиана
// размера $870 против $5000, это другой масштаб.
//
