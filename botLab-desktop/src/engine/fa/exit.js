//
// КРИВЫЕ УДАРА СЮДА НЕ ПЕРЕДАЮТСЯ, И ЭТО НЕ ЭКОНОМИЯ. Брутто от них не зависит ПОБИТОВО (проверено:
// -17.017663366 и с кривыми, и без; меняется только круг, $7.20 против $8.97 при $2000), потому что
// удар это издержка сделки, а не начисление. Значит ВЕТКЕ УДЕРЖАНИЯ стакан не нужен.
//
// ЧИТАТЬ ЭТО ШИРЕ НЕЛЬЗЯ, И ВОТ ГДЕ ГРАНЬ. Ворота данных МОДУЛЯ кривые удара требуют, потому что
// ветка перекладки считает `нетто_альт = брутто_альт - круг(S_альт)`, а круг от кривых зависит на
// те самые 25% ($7.20 против $8.97). Без кривых перекладка молча сравнивала бы разные вещи. Ворота
// у входа и у выхода ОДНИ И ТЕ ЖЕ: ослабленные ворота выхода означали бы, что выход работает там,
// где вход не вошёл бы, а это ровно та асимметрия, которой в проекте уже стоил целый вывод.
// Отсутствие стакана отсеивает альтернативу кодами `no_book` и `stale_book` правила входа, и это
// происходит В НЁМ, а не здесь.
//
// ВОЗВРАЩАЕТСЯ ИМЕННО БРУТТО, А НЕ НЕТТО, и это главная ловушка конструкции. `netAtSize().net` уже
// вычло полный круг; подставив его в ветку удержания, мы вычли бы круг, который в этой ветке НЕ
// платится, то есть вычли бы его дважды в сравнении с альтернативой. Контроль `sunk-in` книги
// выхода воспроизводит ровно эту ошибку и обязан книгу сломать.
// ─────────────────────────────────────────────────────────────────────────────
export function holdGross({ position, rows, costs = DEFAULT_COSTS, cfg = FA_SIZING_DEFAULTS }) {
  const c = { ...FA_SIZING_DEFAULTS, ...cfg };
  if (!position || !(position.sizeUsd > 0)) return null;
  const W = windowHours(c);
  if (!(W > 0) || !rows || rows.length < W) return null;
  // Берутся ПОСЛЕДНИЕ `windowH` часов, окно оценки назад. Более длинный трейлинг дал бы брутто в
  // других единицах, чем нетто альтернативы, а сравнение разных единиц это и есть тот дефект, ради
  // которого окно у системы одно. На горизонт вперёд брутто переводит `netAtSize` тем же
  // множителем `horizonH / windowH`, что и у альтернатив: единицы совпадают по построению.
  const seg = rows.slice(rows.length - W);
  const r = netAtSize({
    rows: seg, config: position.config, strategy: position.strategy || "two",
    sizeUsd: position.sizeUsd, costs, impact: null, cfg: c, token: position.token,
  });
  return r ? r.gross : null;
}

// ─────────────────────────────────────────────────────────────────────────────
// ЛУЧШАЯ ГОДНАЯ АЛЬТЕРНАТИВА СРЕДИ КРИВЫХ ПРАВИЛА ВХОДА.
//
// Годная это та, которую правило входа ПРОФИНАНСИРОВАЛО и которая ВЛЕЗАЕТ в доступный капитал.
// Второе условие проверяется здесь, а не в распределителе, потому что решается ОДНА сделка:
// портфель распределителя не исполняется ни на выходе, ни у автомата (слот один).
//
// ВЫНЕСЕНО В ЭКСПОРТ РАДИ АВТОМАТА ФАЗЫ 4, а не ради красоты. Автомат выбирает рынок ВХОДА тем же
// вопросом, каким выход выбирает альтернативу, и вторая копия четырёх строк отбора рассталась бы с
// этой на первой правке. Класс дефекта «две части системы решают одну задачу разными правилами»
// проект ловил четырежды, и здесь он стоил бы того, что вход садился бы не на тот рынок, который
// выход считает лучшим, то есть бот платил бы круг сам себе.
// ─────────────────────────────────────────────────────────────────────────────
export function bestAlternative(curves, capitalUsd) {
  let best = null;
  for (const cur of curves || []) {
    if (!cur || cur.refusal || !(cur.sizeUsd > 0) || cur.sizeUsd > capitalUsd) continue;
    if (!best || cur.netUsd > best.netUsd) best = cur;
  }
  return best;
}

// ─────────────────────────────────────────────────────────────────────────────
// ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ПРИНИМАЕТСЯ РЕШЕНИЕ ПО ОТКРЫТОЙ СДЕЛКЕ.
//
// `markets` это вселенная альтернатив в той же форме, что принимает `sizeUniverse`, И ТЕКУЩИЙ РЫНОК
// ОБЯЗАН В НЕЁ ВХОДИТЬ. Исключать его нельзя: перекладка в тот же рынок ДРУГИМ размером законна и
// именно так выражается изменение размера. Соблазн оптимизации «лучшая альтернатива это текущий
// рынок, значит менять нечего» убивает ровно этот случай, поэтому здесь его нет, а в тестах стоит
// проверка, которая его поймает.
// ─────────────────────────────────────────────────────────────────────────────
export function decideExit({
  position, rows, markets = [], capitalAvailableUsd = null,
  costs = DEFAULT_COSTS, cfg = FA_SIZING_DEFAULTS, sources = null,
}) {
  const c = { ...FA_SIZING_DEFAULTS, ...cfg };
  if (!Number.isFinite(c.horizonH) || c.horizonH <= 0) return defer("horizon_missing");
  if (!windowValid(c)) return defer("window_missing");
  if (!position || !(position.sizeUsd > 0)) return defer("no_position");
  // ОТКАЗ ИСТОЧНИКА ОСТАНАВЛИВАЕТ РЕШЕНИЕ ЦЕЛИКОМ, а не только ветку перекладки. Без источника
  // альтернатив не видно НИ ОДНОЙ, и «альтернатив нет» превратилось бы в «держим», то есть отказ
  // снабжения выглядел бы как вывод правила.
  if (sources && sources.gmxDown) return defer("src_gmx_down");
  if (sources && sources.hlDown) return defer("src_hl_down");
  if (!rows || rows.length < windowHours(c)) return defer("short_history");

  const holdGrossUsd = holdGross({ position, rows, costs, cfg: c });
  if (!Number.isFinite(holdGrossUsd)) return defer("short_history");

  // ПРАВИЛО ВХОДА ЗОВЁТСЯ ЦЕЛИКОМ. Капитал передаётся ему же: рынок, на который денег не хватает,
  // обязан получить свой код отказа от распределителя, а не выпасть молча.
  const capital = Number.isFinite(capitalAvailableUsd) && capitalAvailableUsd > 0 ? capitalAvailableUsd : position.sizeUsd;
  const uni = markets.length
    ? sizeUniverse({ markets, costs, capitalTotal: capital, cfg: c, sources })
    : { curves: [], refusals: [], alloc: new Map() };

  const best = bestAlternative(uni.curves, capital);
  const switchNetUsd = best ? best.netUsd : null;

  // МАКСИМУМ ТРЁХ ЧИСЕЛ В ОДНИХ ЕДИНИЦАХ. Порядок сравнений на исход не влияет (у максимума порядка
  // нет), а строгие знаки отдают ничьи бездействию: бездействие бесплатно, действие стоит круга.
  let action = "hold";
  let reason = "hold_best";
  let bestValue = holdGrossUsd;
  if (0 > bestValue) { action = "close"; reason = "gross_negative"; bestValue = 0; }
  if (Number.isFinite(switchNetUsd) && switchNetUsd > bestValue) { action = "switch"; reason = "alt_beats_hold"; bestValue = switchNetUsd; }

  return {
    action, reason,
    holdGrossUsd,
    cashUsd: 0,
    switchNetUsd,
    // НА СКОЛЬКО перекладка лучше удержания. Величина печатается всегда, в том числе когда она
    // отрицательна: «переложились бы, но не хватило $0.40» и «альтернативы нет вовсе» это разные
    // состояния, и в журнале они обязаны выглядеть по-разному.
    gainUsd: Number.isFinite(switchNetUsd) ? switchNetUsd - holdGrossUsd : null,
    best,
    curves: uni.curves,
    refusals: uni.refusals,
    cfg: c,
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// ЖУРНАЛ РЕШЕНИЯ. Одна строка, образец `explainSize` в `sizing.js`.
// ─────────────────────────────────────────────────────────────────────────────
export function explainExit(decision, position = null) {
  if (!decision) return "решения нет";
  const t = position?.token ?? "?";
  const why = REASON_TEXT[decision.reason] || decision.reason;
  if (decision.action === "defer") return `${t}: не решаем, ${why} (${decision.reason})`;
  const hold = `брутто удержания $${decision.holdGrossUsd.toFixed(2)}`;
  if (decision.action === "hold") {
    const alt = Number.isFinite(decision.switchNetUsd)
      ? `лучшая альтернатива ${decision.best.token} нетто $${decision.switchNetUsd.toFixed(2)}`
      : `годных альтернатив нет`;
    return `${t}: ДЕРЖИМ, ${hold}, ${alt}`;
  }
  if (decision.action === "close") return `${t}: В КЭШ, ${hold} (${decision.reason})`;
  const b = decision.best;
  return `${t}: ПЕРЕКЛАДКА в ${b.token}/${b.config} $${b.sizeUsd.toFixed(0)}, ${hold} против нетто $${b.netUsd.toFixed(2)}, `
    + `прибавка $${decision.gainUsd.toFixed(2)} сверх круга $${b.costUsd.toFixed(2)}`;
}
