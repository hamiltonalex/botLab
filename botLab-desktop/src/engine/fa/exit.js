// ─────────────────────────────────────────────────────────────────────────────
// КАДАНС РЕШЕНИЙ. Чистый гейт, идиома `reopenAfterMs` бота 2. Автомат, который его зовёт, это
// фаза 4; здесь только предикат, и он юнит-тестируется отдельно от критерия.
//
// ПЕРВОЕ РЕШЕНИЕ РАЗРЕШЕНО ВСЕГДА: `lastAtMs` без значения означает «ещё не решали», а не «решали в
// нулевой момент эпохи». Разница видна на первом же тике после запуска.
// ─────────────────────────────────────────────────────────────────────────────
export function shouldDecideNow(lastAtMs, nowMs, intervalH = FA_EXIT_DEFAULTS.decisionIntervalHours) {
  if (!Number.isFinite(nowMs)) return false;
  if (!Number.isFinite(lastAtMs)) return true;
  const h = Number.isFinite(intervalH) && intervalH >= 0 ? intervalH : FA_EXIT_DEFAULTS.decisionIntervalHours;
  return nowMs - lastAtMs >= h * 3600 * 1000;
}

