// Hyperliquid), а поле "side" в каждой строке каждого опроса это те же 26 байт на опрос ни за что.
function legBlock(leg, missing, present = true) {
  // НОГИ, КОТОРОЙ У СХЕМЫ НЕТ, не существует, и это НЕ «данных по ней не пришло». Признак берётся
  // у `legModel` леджера, а не назначается здесь: разбор схемы на ноги знает он один.
  //
  // Без развилки одноногая схема помечала бы КАЖДУЮ свою строку четырьмя кодами `leg_*`, то есть
  // канал честности говорил бы «наблюдение неполное» на всех записях подряд, а автомат входит
  // одной ногой чаще, чем двумя. Сигнал, который горит всегда, не сигнал.
  if (!present) return null;
  const out = {
    ntl: usd(leg?.notionalUsd),
    col: usd(leg?.collateralUsd),
    px: px(leg?.markPx),
    liq: px(leg?.liquidationPx),
    ls: FA_LIQ_SOURCES.includes(leg?.liqSource) ? leg.liqSource : null,
  };
  if (out.ntl == null) push(missing, "leg_notional");
  if (out.col == null) push(missing, "leg_collateral");
  if (out.px == null) push(missing, "leg_mark");
  if (out.liq == null) push(missing, "leg_liq");
  else if (out.ls == null) push(missing, "leg_liq_src");
  return out;
}

// buildFaSnapRecord({ t, source, gmxAgeSec, hlAgeSec, markets, position }) - строка снимка либо
// null (без метки времени писать нечего, закон записи бота 2).
//
//   markets  - массив наблюдений по рынкам В СЫРОМ ВИДЕ, как их отдали `signs.js` и `l2Book`;
//   position - открытая позиция со всеми ногами СВОЕЙ схемы либо null. Пусто когда сделки нет, и
//              это НЕ пропуск наблюдения: кодов `leg_*` в такой строке не появляется. У одноногой
//              схемы ноги `h` не существует, и в строке она null по той же причине.
export function buildFaSnapRecord({ t, source = "live", gmxAgeSec, hlAgeSec, markets = [], position = null } = {}) {
  if (!fin(t)) return null;
  const m = {};
  for (const o of markets || []) {
    const token = o?.token;
    if (!token) continue;
    const x = [];
    const f = o.factors || null;
    const cell = {
      c: trim(o.chain, 16),
      // Тождество `netRate = funding + borrow` внутри markets/info. Рынок с несошедшимся
      // тождеством это ДРУГОЕ наблюдение, а не то же самое с оговоркой.
      gt: o.gateOk === true ? 1 : o.gateOk === false ? 0 : null,
      fl: rate(f?.f_long), fs: rate(f?.f_short), bl: rate(f?.b_long), bs: rate(f?.b_short),
      hr: rate(o.hlRate), hp: rate(o.hlPremium),
      // БАЗЫ ФАНДИНГА ОБЕИХ СТОРОН, отдельно от кадра трейлинга. Без них правило входа отказывает
      // каждому рынку кодом `no_base`, и это не гипотеза: замер даёт фактор 0 на старом кадре
      // против 0.995 на новом.
      bL: usd(o.fbaseLongUsd), bS: usd(o.fbaseShortUsd),
      aL: usd(o.availLongUsd), aS: usd(o.availShortUsd),
      mk: px(o.markPx), op: px(o.oraclePx), ml: int(o.maxLev),
      bk: null,
    };
    if (![cell.fl, cell.fs, cell.bl, cell.bs].every((v) => v != null)) push(x, "gmx_rates");
    if (cell.bL == null || cell.bS == null) push(x, "gmx_base");
    if (cell.aL == null || cell.aS == null) push(x, "gmx_avail");
    if (cell.hr == null || cell.hp == null || cell.mk == null) push(x, "hl_ctx");
    // МЕСТО В СТАКАНЕ И ЁМКОСТЬ НА МОМЕНТ СНИМКА. Узлы кривой круга пишутся парами
    // [размер, базисные пункты] как их посчитал `bookSlippageNodes` из живых уровней; `v` это
    // видимый ноционал меньшей стороны, `x` это размер, с которого стакан кончается (null значит
    // не кончился на измеренных узлах).
    const b = o.book;
    if (b && Array.isArray(b.nodes)) {
      cell.bk = {
        v: usd(b.visibleNtl),
        x: fin(b.exhaustedFrom) ? usd(b.exhaustedFrom) : null,
        n: b.nodes.filter((k) => fin(k?.sizeUsd) && fin(k?.bps)).map((k) => [usd(k.sizeUsd), bps(k.bps)]),
        a: sec(o.bookAgeSec),
      };
      if (cell.bk.a == null) push(x, "age");
    } else {
      push(x, "hl_book");
    }
    if (x.length) cell.x = x;
    m[token] = cell;
  }
  const row = {
    v: FA_RECORD_VERSION,
    k: "snap",
    t,
    s: FA_RECORD_SOURCES.includes(source) ? source : "live",
    // ВОЗРАСТ ДАННЫХ. Два источника опрашиваются независимо и стареют независимо, поэтому возраста
    // два, а не один: срез со свежим GMX и получасовым Hyperliquid это не «срез возрастом
    // полчаса», это два разных наблюдения в одной строке.
    ga: sec(gmxAgeSec),
    ha: sec(hlAgeSec),
    m,
  };
  const xp = [];
  if (position) {
    row.p = {
      t: position.token ?? null,
      c: position.config ?? null,
      st: position.strategy ?? null,
      g: legBlock(position.gmx, xp),
      h: legBlock(position.hl, xp, legModel(position.strategy, position.config).hlPerHourSign !== 0),
    };
  } else {
    row.p = null;
  }
  if (xp.length) row.xp = xp;
  if (row.ga == null && row.ha == null) {
    // Возраст ни одного источника не назван: свежесть среза не установлена вовсе, и это надо
    // сказать в строке, а не оставить читателю два null на догадку.
    row.x = ["age"];
  }
  return row;
}

// ─────────────────────────────────────────────────────────────────────────────
// ПРОПУСК. Час без данных это СОБЫТИЕ, а не отсутствие строки.
// ─────────────────────────────────────────────────────────────────────────────

// Причина перерыва по хинтам вызывающего. PURE: ни одна причина не выдумывается, не покрыл ни один
// хинт - значит "unknown". Порядок проверки это точность сигнала: сон задан ТОЧНЫМ ОКНОМ (внутри
// него возможны тики тёмных пробуждений, поэтому окно, а не длительность), затем рестарт
// приложения по метке бута, затем молчание источника.
export function classifyFaGap({ fromMs, toMs, hints = {} } = {}) {
  const h = hints ?? {};
  // ВЫКЛЮЧЕННЫЙ АВТОМАТ ПРОВЕРЯЕТСЯ ПЕРВЫМ, и это не вкусовщина порядка. Он причина ДОСТАТОЧНАЯ:
  // на бодрствующей машине с отвечающими источниками выключенный автомат всё равно не пишет ни
  // строки. Он же и самая точная метка: окно останова известно с точностью до тика, тогда как сон
  // и молчание источника это наблюдения со стороны.
  if (h.offWindow && fin(h.offWindow.start) && fin(h.offWindow.end)
    && fromMs <= h.offWindow.end && h.offWindow.start <= toMs) return "off";
  if (h.sleepWindow && fin(h.sleepWindow.start) && fin(h.sleepWindow.end)
    && fromMs <= h.sleepWindow.end && h.sleepWindow.start <= toMs) return "sleep";
  if (fin(h.bootAt) && fromMs < h.bootAt && h.bootAt <= toMs) return "app-down";
  if (fin(h.sourceErrorSince) && h.sourceErrorSince <= toMs) return "no-response";
  return "unknown";
}

// buildFaGapRecord({ fromMs, toMs, nominalSec, hints, source }) - строка пропуска либо null, когда
// пропуска НЕТ (перерыв не превысил порога). null здесь означает «событие не наступило», а не
// «писать не стали»: разница видна тем, что строка пропуска обязана появляться на каждом перерыве
// сверх порога, и её отсутствие ловится `faCoverage().unexplained`.
export function buildFaGapRecord({ fromMs, toMs, nominalSec, hints = {}, source = "live" } = {}) {
  if (!fin(fromMs) || !fin(toMs) || !(toMs > fromMs)) return null;
  const nom = fin(nominalSec) && nominalSec > 0 ? nominalSec : null;
  if (nom == null) return null;
  const ms = toMs - fromMs;
  if (!(ms > nom * 1000 * FA_GAP_SLOTS)) return null;
  return {
    v: FA_RECORD_VERSION,
    k: "gap",
    t: toMs, // метка строки это КОНЕЦ перерыва: в ленте она стоит там, где опрос возобновился
    f: fromMs,
    ms,
    // Сколько слотов опроса потеряно. Минус один: интервал между двумя соседними опросами это ноль
    // потерянных слотов, а не один, и на коротких окнах эта единица даёт ложные проценты.
    lost: Math.max(0, Math.round(ms / (nom * 1000)) - 1),
    c: classifyFaGap({ fromMs, toMs, hints }),
    nom,
    s: FA_RECORD_SOURCES.includes(source) ? source : "live",
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// РАСЧЁТ РЕШЕНИЯ. Не «что решили», а ИЗ ЧЕГО РЕШАЛИ.
// ─────────────────────────────────────────────────────────────────────────────

// Отличия конфигурации от значений по умолчанию. Пишется РАЗНИЦА, а не весь блок: он одинаков в
// каждой строке, а различие это то единственное, чего нельзя восстановить из имени пресета.
function cfgDiff(cfg) {
  const out = {};
  if (!cfg) return out;
  for (const [k, v] of Object.entries(FA_SIZING_DEFAULTS)) {
    const got = cfg[k];
    if (got === undefined) continue;
    if (got !== v && !(Number.isNaN(got) && Number.isNaN(v))) out[k] = got === Infinity ? "inf" : got;
  }
  return out;
}

// Кривая профинансированного рынка. Здесь только то, что ВЕРНУЛО правило: сырьё решения (ставки,
// базы, стакан) лежит в строке снимка того же момента и не дублируется.
function curveCell(c) {
  return {
    t: c.token ?? null,
    c: c.config ?? null,
    s: usd(c.sizeUsd), // размер, которым входим
    st: usd(c.starUsd), // внутренний оптимум ДО потолков: расхождение с `s` и есть цена потолка
    n: usd(c.netUsd), g: usd(c.grossUsd), k: usd(c.costUsd),
    r: rate(c.ratio), rs: rate(c.ratioAtStar),
    cl: usd(c.ceilingUsd),
    // Связывающее пишется КАК ПРИШЛО, даже если оно вне реестра: терять наблюдение нельзя.
    // Что оно вне реестра, говорит поле `xc` строки, а не подмена значения здесь.
    b: c.binding ?? null,
    wb: usd(c.flowWeightedBaseUsd),
    dr: rate(c.dilutionRetained),
  };
}

// buildFaDecisionRecord(...) - строка точки решения либо null без метки времени.
//
//   universe - результат `sizeUniverse()` как есть (кривые, отказы, распределение);
//   exit     - результат `decideExit()` как есть либо null, когда открытой сделки нет;
//   hold     - токен занятой позиции либо null. Ранг НЕ ПИШЕТСЯ: он считается читателем из `mk`
//              (`faHeldRank`), потому что записанный ранг нельзя перепроверить, а список можно;
//   window   - { firstTsHour, lastTsHour, rows } трейлинга, поданного правилу. Сам трейлинг не
//              дублируется: он и есть накопленный поток снимков, а эти три числа пришпиливают,
//              какие именно часы участвовали.
//
//   gate - объект ворот снабжения тика (`autoTick().gate`) либо null. Пишутся счётчики окна баз
//          ЛУЧШЕГО рынка с разбивкой по происхождению: без неё задним числом нельзя отличить решение
//          на наблюдённых базах от решения на долитых из индексатора, а это разные наблюдения.
//   trigger - повод решения из `FA_DECISION_TRIGGERS` (`events.js`): каданс, сторож или событие.
//          Без него цену внеочередных решений в кругах снять по записи нельзя, а она не замерена.
export function buildFaDecisionRecord({
  t, source = "live", ageSec, capitalUsd, presetId = null, cfg = null,
  universe = null, exit = null, hold = null, window: win = null, gate = null, trigger = null,
} = {}) {
  if (!fin(t)) return null;
  const xc = [];
  if (trigger != null && !FA_DECISION_TRIGGERS.includes(trigger)) push(xc, `trig:${trigger}`);
  const curves = (universe?.curves || []).filter((c) => c && !c.refusal && fin(c.sizeUsd));
  for (const c of universe?.curves || []) {
    if (c?.binding != null && !FA_SIZING_BINDINGS.includes(c.binding)) push(xc, `bind:${c.binding}`);
  }
  const rf = [];
  for (const r of universe?.refusals || []) {
    if (!r) continue;
    const code = r.refusal ?? null;
    if (code != null && !FA_SIZING_REFUSALS.includes(code)) push(xc, `refuse:${code}`);
    rf.push({ t: r.token ?? null, c: r.config ?? null, x: code });
  }
  const row = {
    v: FA_RECORD_VERSION,
    k: "dec",
    t,
    s: FA_RECORD_SOURCES.includes(source) ? source : "live",
    // ВОЗРАСТ ДАННЫХ, ПО КОТОРЫМ ПРИНЯТО РЕШЕНИЕ. Обязателен: без него задним числом нельзя
    // отличить плохое решение от решения по протухшим данным, а цена этого замерена (24 ч снимают
    // 6.6% годового нетто, 240 ч снимают 35%).
    age: sec(ageSec),
    cap: usd(capitalUsd),
    pre: trim(presetId, 64),
    cfgd: cfgDiff(cfg ?? universe?.cfg),
    hz: int((cfg ?? universe?.cfg)?.horizonH),
    // ОКНО ОЦЕНКИ НАЗАД отдельно от горизонта вперёд (2026-09-02): при равных значениях запись
    // повторяет число, и это нарочно: читатель не имеет права выводить одно из другого.
    wn: int(windowHours(cfg ?? universe?.cfg)),
    // ПОВОД РЕШЕНИЯ. Строка записи, а не код отказа: неизвестный повод виден полем `xc`.
    tr: trigger == null ? null : trim(trigger, 32),
    hw: win ? [int(win.firstTsHour), int(win.lastTsHour), int(win.rows)] : null,
    // ВОРОТА СНАБЖЕНИЯ на момент решения: рынков в обходе, прошло ворота, покрытых часов лучшего
    // рынка против порога, и те же часы по происхождению (живьём, долито, без метки).
    gt: gate ? {
      m: int(gate.markets), u: int(gate.usable), cb: int(gate.covBestH), cn: int(gate.covNeedH),
      cl: int(gate.covLiveH), ci: int(gate.covIndexerH), cu: int(gate.covUnknownH),
    } : null,
    hold: hold ?? null,
    mk: curves.map(curveCell),
    rf,
    al: [...(universe?.alloc instanceof Map ? universe.alloc : new Map())].map(([k, v]) => [k, usd(v)]),
    us: usd(universe?.usedUsd),
    nt: usd(universe?.netTotal),
    ex: null,
  };
  if (exit) {
    const a = exit.action ?? null;
    const w = exit.reason ?? null;
    if (a != null && !FA_EXIT_ACTIONS.includes(a)) push(xc, `act:${a}`);
    if (w != null && !FA_EXIT_REASONS.includes(w)) push(xc, `exit:${w}`);
    const b = exit.best || null;
    row.ex = {
      a, w,
      hg: usd(exit.holdGrossUsd),
      sn: usd(exit.switchNetUsd),
      gn: usd(exit.gainUsd),
      bt: b?.token ?? null, bc: b?.config ?? null, bs: usd(b?.sizeUsd), bn: usd(b?.netUsd),
    };
  }
  if (xc.length) row.xc = xc;
  return row;
}

// ─────────────────────────────────────────────────────────────────────────────
// ИСТОРИЯ СДЕЛОК. Полный паспорт: рынок, конфигурация ноги, ОБА размера, издержки по статьям,
// причина решения, обе ноги с залогом и ценой ликвидации.
// ─────────────────────────────────────────────────────────────────────────────

function tradeSide(p) {
  if (!p) return null;
  const missing = [];
  const out = {
    t: p.token ?? null,
    c: p.config ?? null,
    st: p.strategy ?? null,
    // ДВА РАЗМЕРА, И ОНИ РАСХОДЯТСЯ. `want` это то, что заявлено (капитал либо запрошенный
    // размер), `got` это узел сетки, на который легли на самом деле. Соседние достижимые размеры
    // отличаются на 26%, поэтому $2500 работают как $1995.26.
    want: usd(p.wantUsd),
    got: usd(p.gotUsd),
    lev: rate(p.leverage),
    g: legBlock(p.gmx, missing),
    h: legBlock(p.hl, missing, legModel(p.strategy, p.config).hlPerHourSign !== 0),
  };
  if (fin(p.realizedUsd)) out.real = usd(p.realizedUsd);
  if (missing.length) out.x = missing;
  return out;
}

// buildFaTradeRecord({ t, source, event, why, ageSec, decisionAt, opened, closed, costs })
//
//   event      - "open" | "close" | "switch". Перекладка это ОДНА строка с обеими сторонами:
//                разложенная на две, она теряет то, что круг заплачен ради этой альтернативы;
//   why        - причина из `FA_EXIT_REASONS` для выхода и перекладки; у входа причина живёт в
//                строке решения, на которую указывает `d`, и здесь она null;
//   decisionAt - метка строки решения. Пришивает паспорт к расчёту, из которого он вырос.
export function buildFaTradeRecord({
  t, source = "live", event, why = null, ageSec, decisionAt = null,
  opened = null, closed = null, costs = null,
} = {}) {
  if (!fin(t)) return null;
  if (!FA_TRADE_EVENTS.includes(event)) return null;
  const xc = [];
  if (why != null && !FA_EXIT_REASONS.includes(why)) push(xc, `exit:${why}`);
  const row = {
    v: FA_RECORD_VERSION,
    k: "trade",
    t,
    s: FA_RECORD_SOURCES.includes(source) ? source : "live",
    ev: event,
    why,
    age: sec(ageSec),
    d: fin(decisionAt) ? decisionAt : null,
    pos: tradeSide(opened),
    prev: tradeSide(closed),
    // ИЗДЕРЖКИ ПО СТАТЬЯМ, а не одним числом: статьи растут по-разному (плоский газ против
    // процента ноционала), и круг, записанный скаляром, не даёт разобрать, что подорожало.
    cost: costs ? {
      o: usd(costs.gmxOpenUsd), cl: usd(costs.gmxCloseUsd), i: usd(costs.gmxImpactUsd),
      gas: usd(costs.gmxGasUsd), hl: usd(costs.hlTakerUsd),
    } : null,
  };
  if (xc.length) row.xc = xc;
  return row;
}

// ─────────────────────────────────────────────────────────────────────────────
// ЧТЕНИЕ АРХИВА КОДОМ. Интерфейс это следующая фаза; здесь только то, чем запись проверяется и
// чем из неё считаются ответы.
// ─────────────────────────────────────────────────────────────────────────────

// Ранг занятой позиции среди ГОДНЫХ кандидатов по нетто. Считается ИЗ СПИСКА, а не читается полем:
// записанный ранг нельзя перепроверить. Возвращает 1 для вершины, null когда позиции нет или она
// выпала из годных вовсе (это ДРУГОЕ состояние, чем плохой ранг, и путать их нельзя).
export function faHeldRank(decRow) {
  const hold = decRow?.hold;
  if (!hold || !Array.isArray(decRow.mk)) return null;
  const sorted = [...decRow.mk].filter((c) => fin(c?.n)).sort((a, b) => b.n - a.n || String(a.t).localeCompare(String(b.t)));
  const i = sorted.findIndex((c) => c.t === hold);
  return i < 0 ? null : i + 1;
}

// Запас до ликвидации КАЖДОЙ ноги, в долях цены. Считается из записанного сырья `px` и `liq`, а не
// хранится: хранить надо наблюдение. Возвращает null у ноги, чьих чисел в строке нет, и это
// молчаливо не проглатывается - в строке уже стоит код `leg_liq` либо `leg_mark`.
export function faLiqRoom(snapRow) {
  const p = snapRow?.p;
  if (!p) return null;
  const room = (leg) => (fin(leg?.px) && fin(leg?.liq) && leg.px > 0 ? Math.abs(leg.liq / leg.px - 1) : null);
  return { gmx: room(p.g), hl: room(p.h), src: { gmx: p.g?.ls ?? null, hl: p.h?.ls ?? null } };
}

// НЕПРЕРЫВНОСТЬ ПОТОКА СНИМКОВ. Главный контроль записи: перерыв, не объяснённый строкой пропуска,
// попадает в `unexplained` и ловится тестом. Молчаливая дыра в ленте неотличима от рынка, которого
// не было, а именно этим вопросом запись и заводится.
//
// ОЖИДАЕМЫЕ СЛОТЫ СЧИТАЮТСЯ ВКЛЮЧИТЕЛЬНО ПО ОБОИМ КОНЦАМ (`span/шаг + 1`): без единицы на коротких
// окнах выходят проценты выше ста, на чём проект уже обжигался при замере покрытия сканера.
export function faCoverage(rows, { nominalSec } = {}) {
  const nom = fin(nominalSec) && nominalSec > 0 ? nominalSec : null;
  const snaps = (rows || []).filter((r) => r?.k === "snap" && fin(r.t)).sort((a, b) => a.t - b.t);
  const gaps = (rows || []).filter((r) => r?.k === "gap" && fin(r.t) && fin(r.f));
  if (!snaps.length || nom == null) {
    return { polls: snaps.length, expected: 0, coveragePct: null, lostSlots: 0, byCause: {}, explained: [], unexplained: [] };
  }
  const nomMs = nom * 1000;
  const spanMs = snaps[snaps.length - 1].t - snaps[0].t;
  const explained = [];
  const unexplained = [];
  for (let i = 1; i < snaps.length; i += 1) {
    const from = snaps[i - 1].t;
    const to = snaps[i].t;
    if (!(to - from > nomMs * FA_GAP_SLOTS)) continue;
    // Перерыв объяснён, когда есть строка пропуска, накрывающая ЭТОТ интервал. Накрытие проверяется
    // пересечением, а не равенством меток: писатель ставит `f` по последнему опросу, но перерыв мог
    // быть записан и с чуть иными краями (например при восстановлении после сна).
    const g = gaps.find((x) => x.f <= to && x.t >= from);
    (g ? explained : unexplained).push({ from, to, ms: to - from, cause: g?.c ?? null });
  }
  const byCause = {};
  let lostSlots = 0;
  for (const g of gaps) {
    byCause[g.c] = (byCause[g.c] || 0) + 1;
    lostSlots += fin(g.lost) ? g.lost : 0;
  }
  const expected = Math.floor(spanMs / nomMs) + 1;
  return {
    polls: snaps.length,
    expected,
    coveragePct: expected > 0 ? Math.min(100, (snaps.length / expected) * 100) : null,
    lostSlots,
    byCause,
    explained,
    unexplained,
  };
}

// Рынки, ПЕРЕСТАВШИЕ наблюдаться. Это и есть подступ к смертности: рынок, который живой опрос
// видел и перестал видеть, отличается от рынка, которого не было, только этим счётом. Возвращает
// имена, наблюдавшиеся в первых `warmupRows` строках и не наблюдавшиеся ни в одной из последних
// `tailRows`. Это НЕ доказательство делистинга: рынок мог выпасть из вселенной опроса, и различить
// это можно только настройкой опроса того же прогона.
export function faVanishedMarkets(rows, { warmupRows = 1, tailRows = 1 } = {}) {
  const snaps = (rows || []).filter((r) => r?.k === "snap" && r.m).sort((a, b) => a.t - b.t);
  if (snaps.length < warmupRows + tailRows) return [];
  const seen = new Set();
  for (const r of snaps.slice(0, warmupRows)) for (const k of Object.keys(r.m)) seen.add(k);
  const tail = new Set();
  for (const r of snaps.slice(-tailRows)) for (const k of Object.keys(r.m)) tail.add(k);
  return [...seen].filter((k) => !tail.has(k)).sort();
}

// Коды строки, которых нет ни в одном реестре. Пустой массив это норма; непустой означает, что
// где-то завелась строковая константа мимо словарей, и увидеть это надо на тесте, а не через год.
export function faUnknownCodes(row) {
  const out = [];
  if (!row) return out;
  if (!FA_RECORD_KINDS.includes(row.k)) push(out, `kind:${row.k}`);
  if (row.s != null && !FA_RECORD_SOURCES.includes(row.s)) push(out, `src:${row.s}`);
  if (row.k === "gap" && !FA_GAP_CAUSES.includes(row.c)) push(out, `gap:${row.c}`);
  if (row.k === "trade" && !FA_TRADE_EVENTS.includes(row.ev)) push(out, `ev:${row.ev}`);
  for (const c of row.x || []) if (!FA_SNAP_MISSING.includes(c)) push(out, `miss:${c}`);
  for (const c of row.xp || []) if (!FA_POS_MISSING.includes(c)) push(out, `pos:${c}`);
  for (const cell of Object.values(row.m || {})) {
    for (const c of cell?.x || []) if (!FA_SNAP_MISSING.includes(c)) push(out, `miss:${c}`);
  }
  for (const leg of [row.p?.g, row.p?.h, row.pos?.g, row.pos?.h, row.prev?.g, row.prev?.h]) {
    if (leg && leg.ls != null && !FA_LIQ_SOURCES.includes(leg.ls)) push(out, `liq:${leg.ls}`);
  }
  for (const c of row.xc || []) push(out, c);
  return out;
}

