const fin = (x) => Number.isFinite(x);
const num = (x) => (typeof x === "string" ? Number(x) : x);
// Посекундные факторы и часовые ставки: 12 значащих цифр.
const rate = (x) => { const n = num(x); return fin(n) ? (n === 0 ? 0 : Number(n.toPrecision(12))) : null; };
// Доллары: цент.
const usd = (x) => { const n = num(x); return fin(n) ? Number(n.toFixed(2)) : null; };
// Цена: как пришла. Строка биржи приводится к числу, но не огрубляется.
const px = (x) => { const n = num(x); return fin(n) ? n : null; };
// Базисные пункты: 4 знака.
const bps = (x) => { const n = num(x); return fin(n) ? Number(n.toFixed(4)) : null; };
// Возраст: десятая доля секунды.
const sec = (x) => { const n = num(x); return fin(n) ? Number(n.toFixed(1)) : null; };
const int = (x) => { const n = num(x); return fin(n) ? Math.round(n) : null; };

const push = (arr, code) => { if (!arr.includes(code)) arr.push(code); };
const trim = (s, n) => (s == null ? null : String(s).slice(0, n));

// Ключ суток UTC. Тот же ключ, что у вёдер телеметрии и у записи бота 2, поэтому потоки
