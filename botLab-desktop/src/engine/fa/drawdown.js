// ЧТО ЭТО. Единственное место, где РЕАЛИЗОВАННЫЙ результат сделки участвует в поведении автомата.
// Правило выхода (`exit.js`) его не видит по конструкции 31.08: оно сравнивает брутто окна назад,
// нетто альтернативы и ноль кэша, и утопленные издержки в это сравнение не входят. Сторож стоит
// РЯДОМ с правилом, а не внутри него: он закрывает сделку, накопленный брутто которой отдал от
// своего пика `drawdownStopRounds` кругов издержек, и делает это на любом тике, не дожидаясь
// каданса. Книга правила выхода (`base-fa-exit.tsv`) от него не зависит ни на бит.
//
// ЗАМЕР, РАДИ КОТОРОГО ОН СУЩЕСТВУЕТ (З6, 2026-09-04, `scripts/funding-arb-study/exit-6-loss.mjs`,
// капитал $2500, потолок тикета $2500, каданс 24 ч, три периода: год 1 из 63 рынков, второй
// период из 22, длинное окно из 14). Из семи кандидатов поведения в убыточной сделке у текущего
// правила на ВСЕХ периодах выигрывает только стоп по просадке в два круга: парная разность нетто с
// правилом на одном старте +$4.4, +$12.5 и +$10.8 при 40 победах из 40 стартов на каждом периоде,
// число кругов то же (28.0 против 28.0 на годе 1), джекнайф по именам 58 из 63; при капитале $5000
// +$70. Стоп в ОДИН круг лучший на годе 1 (+$23) и проигрывает вне выборки (−$48 и −$44 при
// 0 из 40): порог с года 1 не переносится, выживает только два круга. Стоп в полкруга, полоса
// отрицательных часов короче двух суток, экспоненциальное окно и схлопывание потока за шесть часов
// теряют от $34 до $1290 кругами. Срабатывает стоп 1..3 раза в год и режет хвост эпизодов, где
// правило держит позицию 100..200 часов после пика её результата (LINK октябрь 2025: правило отдало
// $17, стоп закрыл при $13.70 через 68 часов).
//
// ПОЧЕМУ ИМЕННО КРУГИ, А НЕ ДОЛЛАРЫ И НЕ ДОЛЯ ПИКА. Круг это цена действия в той же бухгалтерии, в
// которой правило входа окупает сделку (`netUsd = gross - cost`): стоп в два круга означает «сделка
// отдала рынку вдвое больше, чем стоил бы выход и новый вход». Доля пика (кандидат K3) в замере
// ничего не дала, потому что у только что открытой сделки пик близок к нулю и доля от него это шум.
//
// ГРАНИЦА. Порог выбран до прогона из трёх значений, не откалиброван по сетке, и подбирать его
// дальше нельзя: сетка 1.5..3 кругов дала бы число, подогнанное под те же три периода. После стопа
// следующее решение приходит через каданс, как в замере (стенд ждал сутки): немедленный перезаход
// в тот же рынок по тому же трейлингу это ровно тот спор сторожа с правилом входа, за который
// отклонён кандидат «полоса 48 часов».
//
// НЕИЗВЕСТНЫЕ ЧИСЛА ЛЕДЖЕРА СТОП НЕ ЗОВУТ. Накопленное, пик и круг приходят из бумажного леджера
// самой сделки; их отсутствие это дефект снабжения автомата, а не признак просадки, и платить
// круг за него нельзя. Вердикт в этом случае несёт `known: false`, и это видно в записи.
//
// ЧЕГО МОДУЛЬ НЕ ИМПОРТИРУЕТ: ничего. Замыкания импортов ботов 1 и 2 пересекаются по пустому
// множеству, и это стережёт тест.

export const FA_DRAWDOWN_DEFAULTS = Object.freeze({
  // Порог стопа в кругах издержек сделки. ЗАМЕР З6 (см. шапку): два круга единственное значение,
  // выигравшее у правила на всех трёх периодах. Ноль или пусто выключает сторож.
  drawdownStopRounds: 2,
});

// Реестр кодов сторожа. Один код: «не посчитали» кодом не является (см. шапку), а «посчитали и
// в порядке» это отсутствие кода.
export const FA_DRAWDOWN_REFUSALS = Object.freeze(["drawdown_stop"]);

// Пусто это пусто, а не ноль: `Number(null)` дал бы 0, и пустое накопленное читалось бы как
// нулевая просадка, то есть как порядок. Строка с числом читается: параметры приезжают из JSON.
const numOf = (x) => (x == null || x === "" ? NaN : (typeof x === "number" ? x : Number(x)));

// Вердикт по одной сделке. `cumUsd` это накопленный брутто сделки с входа, `peakUsd` его пик,
// `roundTripUsd` круг издержек, списанный при входе (все три из леджера, `paper.js`).
//   enabled  - сторож включён параметром;
//   known    - числа леджера пригодны, вердикт содержателен;
//   ok       - просадка ниже порога (при выключенном или неизвестном сторож не мешает: ok = true);
//   code     - `drawdown_stop`, когда просадка достигла порога, иначе null.
// Порог ВКЛЮЧИТЕЛЬНО: просадка, равная порогу, закрывает, как в стенде З6.
// `rounds`, НЕ ПЕРЕДАННЫЙ вовсе, читается умолчанием (два круга); переданный null, ноль или
// отрицательное число выключают сторож.
export function drawdownGuard({ cumUsd, peakUsd, roundTripUsd, rounds = FA_DRAWDOWN_DEFAULTS.drawdownStopRounds } = {}) {
  const k = numOf(rounds);
  const enabled = Number.isFinite(k) && k > 0;
  const base = {
    enabled, rounds: enabled ? k : null, known: false, ok: true, code: null,
    drawdownUsd: null, thresholdUsd: null, peakUsd: null, cumUsd: null,
  };
  if (!enabled) return base;
  const c = numOf(cumUsd);
  const p = numOf(peakUsd);
  const r = numOf(roundTripUsd);
  if (!Number.isFinite(c) || !Number.isFinite(p) || !Number.isFinite(r) || r <= 0) return base;
  // Пик не ниже накопленного по построению леджера (`applyDelta`); отрицательная разность здесь
  // возможна только у чужой записи, и она читается как нулевая просадка, а не как ошибка.
  const drawdownUsd = Math.max(0, p - c);
  const thresholdUsd = k * r;
  const ok = drawdownUsd < thresholdUsd;
  return { ...base, known: true, ok, code: ok ? null : "drawdown_stop", drawdownUsd, thresholdUsd, peakUsd: p, cumUsd: c };
}

// Строка для журнала. Образец `explainMargin`.
export function explainDrawdown(verdict) {
  if (!verdict || !verdict.enabled) return "стоп по просадке выключен";
  if (!verdict.known) return "стоп по просадке: чисел леджера нет";
  const dd = `$${verdict.drawdownUsd.toFixed(2)}`;
  const thr = `$${verdict.thresholdUsd.toFixed(2)}`;
  if (!verdict.ok) return `отдано ${dd} от пика при пороге ${thr} (${verdict.rounds} круга): стоп (drawdown_stop)`;
  return `отдано ${dd} от пика при пороге ${thr} (${verdict.rounds} круга)`;
}
