// ЗАЧЕМ МОДУЛЬ, И ПОЧЕМУ ОН НЕ ВНУТРИ sellhedge.js. Это ветка исследования «Ускорение оборота»
// (Ф3, 2026-08-26): даёт ли вторая проданная нога на том же счёте больше дохода на единицу
// хвостового риска, или это та же ставка дважды. С переносом стрэнгла в бот 2 схема боевая:
// пару строит buildSellStrangleStructure (btcopt/structure.js) вызовом этих правил, сверка книг
// пары 84/84 (эталон против живого движка) проведена. Правила потому и жили в движке, а не в
// скрипте-оценщике: иначе перенос в бой означал бы написать их заново, а это ровно тот класс
// дефекта («две части системы решают одну задачу разными правилами»), который проект ловил уже
// четырежды.
//
// ГЛАВНОЕ РЕШЕНИЕ: СВОЕЙ ПРОТЯЖКИ У СТРЭНГЛА НЕТ. `walkSellTrade` уже общий по знаку и по числу
// ног, если скормить ему СОСТАВНУЮ цену: сумма марков двух ног это марк позиции, сумма дельт -
// её дельта, и та же полоса начинает работать по НЕТТО-дельте, а выход в экспирацию отдаёт сумму
// внутренних стоимостей. Порядок арифметики шага, правило «цена не вышла - сделка не засчитана»,
// наблюдатель шага - всё наследуется, а не переписывается. Здесь лежат только три правила, которых
// у одной ноги нет:
//   1. `pickStranglePair`   - какую пару продаём: коллы перебираются базовым правилом схемы (по
//                             близости |дельты|), берётся первый, у чьей экспирации есть пут в
//                             допуске; нет ни одной пары - входа нет вовсе;
//   2. `openStrangleTrade`  - вход: премии и издержки ног складываются, начальный хедж равен
//                             НЕТТО-дельте пары (у симметричного стрэнгла он около нуля);
//   3. `stranglePrice`      - составная цена шага для walkSellTrade.
// Итог считает `settleSellTrade` (премии, выкуп, хедж, издержки, фандинг - конвенция та же),
// МтМ шага - `stepMtm`; залог обеих ног - `legMargin` (стандартная маржа Deribit короткие ноги НЕ
// неттингует, сумма требований - консервативная верхняя граница, как всюду в проекте).
//
// ПОЧЕМУ КОЛЛ ВЫБИРАЕТСЯ ПЕРВЫМ, А НЕ ПАРА СОВМЕСТНО. Колл-нога обязана совпадать с ногой базовой
// схемы на том же снимке: сравнение «одна нога против двух» при РАЗНЫХ коллах мерило бы заодно и
// смену колла, то есть две величины одним числом. Пут подбирается к уже выбранной экспирации.

import { rankSellLegs, openSellTrade } from "./sellhedge.js";

const fin = (x) => Number.isFinite(x);

// ── 1. Пара ног. `rows` обязан быть МАССИВОМ (обходится дважды), а не итератором снимка:
// вызывающий материализует строки сам, здесь это проверяется, а не чинится молча.
//
// rankStranglePairs - те же правила, но до `limit` пар в порядке близости КОЛЛА к целевой дельте.
// Нужен санитарии живого тракта (дизайн §1.8: вето переключает контракт, а не останавливает
// цепочку): вызывающему требуется очередь запасных пар.
//
// КОЛЛ-КАНДИДАТ БЕЗ ПУТА СВОЕЙ ЭКСПИРАЦИИ ПРОПУСКАЕТСЯ, и это часть ПРАВИЛА, а не деталь очереди:
// структурное отсутствие пары не повод замораживать цепочку, когда почти столь же близкий колл
// пару имеет. Правило обязано быть одним на эталон и живой тракт (иначе сверка книг сравнивала бы
// два разных правила), поэтому pickStranglePair это ровно первая пара очереди - делегирование, а
// не второе написание. На пятилетней записи случай «лучший колл без пута в допуске» не встретился
// ни разу (счётчик «колл без пары» нулевой), то есть уточнение ничего в замере не сдвинуло.
export function rankStranglePairs(rows, cfg, limit = 1) {
  if (!Array.isArray(rows)) return [];
  const want = Math.max(1, limit | 0);
  const calls = rankSellLegs(rows, { ...cfg, legType: "C" }, rows.length || 1);
  const out = [];
  for (const call of calls) {
    const put = rankSellLegs(rows.filter((r) => r?.e === call.e), { ...cfg, legType: "P" }, 1)[0] ?? null;
    if (put) out.push({ call, put });
    if (out.length >= want) break;
  }
  return out;
}

export function pickStranglePair(rows, cfg) {
  return rankStranglePairs(rows, cfg, 1)[0] ?? null;
}

// ── 2. Вход. Каждая нога проходит через openSellTrade (премия за вычетом ivHaircut, половина
// СВОЕГО круга издержек), затем статьи складываются. Начальный хедж - НЕТТО-дельта пары: дельта
// пута отрицательна, поэтому у симметричного стрэнгла qPerp близок к нулю, и комиссия хеджа
// берётся с нетто-оборота, а не с суммы модулей (перп входит одной сделкой).
export function openStrangleTrade({ pair, spotUsd, costsCall, costsPut, imUsd, cfg } = {}) {
  if (!pair?.call || !pair?.put) return null;
  const a = openSellTrade({ leg: pair.call, spotUsd, costs: costsCall, imUsd: 0, cfg });
  const b = openSellTrade({ leg: pair.put, spotUsd, costs: costsPut, imUsd: 0, cfg });
  if (!a || !b) return null;
  const qPerp = a.qPerp + b.qPerp;
  return {
    premSold: a.premSold + b.premSold,
    optCost: a.optCost + b.optCost,
    imUsd,
    qPerp,
    hedgeFee: Math.abs(qPerp) * spotUsd * cfg.perpFee,
    premCall: a.premSold,
    premPut: b.premSold,
  };
}

// ── 3. Составная цена шага. Обе ноги обязаны оцениться: пропала хотя бы одна - шаг не оценён,
// и walkSellTrade по своему правилу не засчитывает всю сделку (вызывающий это СЧИТАЕТ). Дельта
// пары складывается только из ИЗВЕСТНЫХ дельт: неизвестная нога делает неизвестной всю позицию
// (null), и wantHedge прочтёт это нулём - та же конвенция, что у одной ноги, а не догадка
// «хеджируем то, что знаем».
export function stranglePrice(priceCall, pricePut) {
  if (!priceCall || !pricePut) return null;
  const delta = fin(priceCall.delta) && fin(pricePut.delta) ? priceCall.delta + pricePut.delta : null;
  return { markUsd: priceCall.markUsd + pricePut.markUsd, delta };
}
