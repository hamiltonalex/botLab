// stats.js - размер выборки при перекрывающихся наблюдениях. PURE.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Число сделок в отчёте это НЕ число наблюдений. Замер по записи прогона 5:
// корреляция доходностей двух покупок, открытых с разрывом в полчаса, равна 0.90, а за всю
// трёхсуточную запись независимых наблюдений набирается 5.9-14.3 при 543-720 строках. Делить
// стандартное отклонение на корень из ЧИСЛА СТРОК значит завысить уверенность в разы, и проект уже
// однажды выдал из-за этого вымышленные «100% положительных» на 242 окнах, которые были примерно
// полутора независимыми точками.
//
// ФОРМУЛА. n_eff = n / (1 + 2·Σ ρ_k), где ρ_k это автокорреляция ряда на лаге k, а сумма берётся до
// первого неположительного члена и взвешивается поправкой Бартлетта (1 − k/n). Это стандартная
// оценка эффективного размера выборки для коррелированного ряда.
//
// ПОЧЕМУ В ОДНОМ ФАЙЛЕ. Оценку эффективного размера считают три офлайн-скрипта (eval:toll,
// hist:backtest, hist:sell). Три копии одной формулы это ровно тот класс дефекта, который проект
// ловил трижды: две части системы решают формально одну задачу разными правилами, расхождение
// молча искажает результат. Здесь правило одно, и оно под тестами.
//
// ГРАНИЦЫ, которые обязан печатать каждый потребитель: автокорреляция меряется по ОДНОЙ траектории
// длиной в выборку, поэтому n_eff это порядок величины, а не точность.

const fin = (x) => Number.isFinite(x);

export const mean = (a) => {
  const s = (a ?? []).filter(fin);
  return s.length ? s.reduce((x, y) => x + y, 0) / s.length : null;
};

export const sd = (a) => {
  const s = (a ?? []).filter(fin);
  if (s.length < 2) return null;
  const m = mean(s);
  return Math.sqrt(s.reduce((x, y) => x + (y - m) ** 2, 0) / (s.length - 1));
};

// Автокорреляция ряда на лаге. null, когда пар меньше десяти или ряд вырожден (нулевая дисперсия):
// корреляция константы не «ноль», а неопределённость, и путать их нельзя.
export function acf(xs, lag) {
  const arr = xs ?? [];
  const n = arr.length - lag;
  if (!Number.isInteger(lag) || lag < 1 || n < 10) return null;
  const a = arr.slice(0, n), b = arr.slice(lag);
  const ma = mean(a), mb = mean(b);
  if (ma == null || mb == null) return null;
  let sab = 0, saa = 0, sbb = 0;
  for (let i = 0; i < n; i++) {
    const u = a[i] - ma, v = b[i] - mb;
    sab += u * v; saa += u * u; sbb += v * v;
  }
  return saa > 0 && sbb > 0 ? sab / Math.sqrt(saa * sbb) : null;
}

// Эффективный размер выборки. Ряды короче 12 точек возвращают свою длину: оценивать автокорреляцию
// по ним нечем, и честнее сказать «наблюдений столько, сколько строк», чем выдумать поправку.
// Результат никогда не больше длины ряда.
export function nEff(xs) {
  const arr = (xs ?? []).filter(fin);
  if (arr.length < 12) return arr.length || null;
  let sum = 0;
  for (let k = 1; k < arr.length; k++) {
    const c = acf(arr, k);
    if (c == null || c <= 0) break;
    sum += (1 - k / arr.length) * c;
  }
  const v = arr.length / (1 + 2 * sum);
  return fin(v) && v > 0 ? Math.min(v, arr.length) : null;
}

// Полуширина 95% полосы вокруг СРЕДНЕГО, посчитанная по n_eff, а не по числу строк.
// null, когда независимых наблюдений меньше двух: полоса по одной точке это не полоса.
export function ci95(xs) {
  const s = sd(xs), ne = nEff(xs);
  if (!fin(s) || !fin(ne) || ne <= 1) return null;
  return (1.96 * s) / Math.sqrt(ne);
}
