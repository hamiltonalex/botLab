// exits.js - правила выхода из купленной позиции (Е1-Е7 плана, поля `exits` пресета). PURE.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. До сих пор эти правила существовали в проекте дважды и оба раза не там,
// где надо: числами в `presets.js` и реализацией внутри `scripts/eval-buy.mjs`. Живой движок их не
// исполняет вовсе - фаза S4 («передача боту 2, вход и выходы») не начата, и поэтому вопрос «сколько
// заработал бы движок» до сих пор считался только при ФИКСИРОВАННОМ удержании, а не по правилам,
// которые в пресете написаны. Здесь правило одно и лежит в одном месте: его используют и офлайн-
// оценщики, и S4, когда до неё дойдут руки. Это ровно тот класс дефекта («две части системы решают
// одну задачу разными правилами»), который проект ловил уже четырежды.
//
// В модуле ДВЕ функции, и вторая появилась по той же причине, что первая. `evaluateExit` отвечает
// «закрываемся ли мы В ЭТОТ момент», `walkExit` отвечает «чем позиция кончилась» и владеет
// решением, которого в первой нет: что делать, когда правило не сработало ни разу. Пока это
// решение жило в цикле офлайн-скрипта, оно молча означало «позиции не было», см. комментарий
// у `walkExit`.
//
// ПОРЯДОК ПРОВЕРОК ЗНАЧИМ И ЗАФИКСИРОВАН. Он взят из `eval-buy.mjs` без изменений, потому что при
// одновременном срабатывании двух правил отчёт обязан называть одну и ту же причину:
//   Е6 тейк-профит → Е2 стоп по премии → Е1 vega-стоп → Е4 тайм-стоп → Е7 преэкспирация.
// Е3 (полфиксация) и Е5 (сдвиг скоса) здесь не реализованы: первая меняет РАЗМЕР, а не факт выхода,
// вторая выключена в пресете (`skewShiftOn: false`). Обе оставлены за модулем осознанно, чтобы он
// отвечал ровно на один вопрос: закрываемся ли мы сейчас целиком и почему.
//
// ТРИГГЕР СЧИТАЕТСЯ ПО MARK, А НЕ ПО СТОРОНЕ КНИГИ, и это тоже перенесено дословно. Пресет говорит
// «mark ≥ entry·(1+x/100)», и сравнивать бид с аском нельзя: на спреде 4.3% премии «тейк +10%»
// превратился бы в требование роста марка на 14.3%, то есть проверялось бы не то правило, которое
// поедет в бой. Исполняется выход по стороне книги, но решает о нём марк.
//
// TRI-STATE. Недостающие данные не выдумываются: если IV или движение неизвестны, соответствующее
// правило просто не срабатывает, а не считается сработавшим или несработавшим по умолчанию.

const fin = (x) => Number.isFinite(x);
const posNum = (x) => fin(x) && x > 0;

export const EXIT_REASONS = Object.freeze({
  TAKE: "тейк",
  STOP: "стоп",
  IV_DROP: "падение воли",
  TIME: "тайм-стоп",
  PRE_EXPIRY: "преэкспирация",
  END_OF_RECORD: "конец записи",
  VANISHED: "инструмент пропал",
});

// evaluateExit(...) даёт { exit: boolean, reason: string|null }.
//   markUsd       - текущий марк инструмента;
//   entryMarkUsd  - марк в момент входа (база тейка и стопа);
//   ivPct/entryIvPct - подразумеваемая волатильность сейчас и на входе (Е1);
//   heldH         - возраст позиции в часах (Е4);
//   hoursToExpiry - сколько часов до экспирации (Е7);
//   moveSigma     - |движение базового актива от входа| в единицах σ1d (Е4); null = неизвестно;
//   exits         - объект `exits` пресета; переопределения кладутся вызывающим поверх.
export function evaluateExit({
  markUsd, entryMarkUsd, ivPct, entryIvPct, heldH, hoursToExpiry, moveSigma, exits,
} = {}) {
  const none = { exit: false, reason: null };
  const X = exits;
  if (!X || !posNum(markUsd) || !posNum(entryMarkUsd)) return none;

  if (posNum(X.takeProfitPct) && markUsd >= entryMarkUsd * (1 + X.takeProfitPct / 100)) {
    return { exit: true, reason: EXIT_REASONS.TAKE };
  }
  if (posNum(X.stopLossPctPrem) && markUsd <= entryMarkUsd * (1 - X.stopLossPctPrem / 100)) {
    return { exit: true, reason: EXIT_REASONS.STOP };
  }
  if (posNum(X.ivDropExitPts) && fin(entryIvPct) && fin(ivPct) && entryIvPct - ivPct >= X.ivDropExitPts) {
    return { exit: true, reason: EXIT_REASONS.IV_DROP };
  }
  // Тайм-стоп закрывает позицию, ПРОСТОЯВШУЮ без движения: возраст выше порога И базовый актив
  // ушёл меньше чем на minMoveSigma. Неизвестное движение (moveSigma == null) считается отсутствием
  // движения - так же, как в eval-buy: позиция, про которую нечего сказать, не заслуживает времени.
  if (posNum(X.timeStopH) && fin(heldH) && heldH >= X.timeStopH
      && (!fin(moveSigma) || moveSigma < X.minMoveSigma)) {
    return { exit: true, reason: EXIT_REASONS.TIME };
  }
  if (posNum(X.preExpiryCloseH) && fin(hoursToExpiry) && hoursToExpiry <= X.preExpiryCloseH) {
    return { exit: true, reason: EXIT_REASONS.PRE_EXPIRY };
  }
  return none;
}

// ── ПРОТЯЖКА ПОЗИЦИИ ДО ВЫХОДА. Правило одно и живёт здесь же, где и сами выходы.
//
// ПОЧЕМУ ЭТО ЗДЕСЬ, А НЕ В ОФЛАЙН-СКРИПТЕ, ГДЕ ЖИЛО РАНЬШЕ. Протяжка выглядит плумбингом («идём
// по снимкам, спрашиваем evaluateExit»), но в ней спрятано РЕШЕНИЕ, которого нет в evaluateExit:
// что считать выходом, когда правило не сработало ни разу. Пока это решение лежало в цикле
// `hist-backtest.mjs`, оно молча звучало как «такой позиции не было вовсе», и в этом был дефект,
// стоивший проекту знака результата (проверка 2026-08-12): цикл возвращал null, вызывающий делал
// `.filter(Boolean)`, и позиция исчезала из ВСЕХ таблиц отчёта разом.
//
// ПОЧЕМУ ИСЧЕЗНОВЕНИЕ БЫЛО НЕ СЛУЧАЙНЫМ, а тем самым отбором по исходу, который убивает любую
// оценку. Главная причина пропажи: спот ушёл от страйка, и правило П3 в hist-surface.js запрещает
// продолжать смайл за наблюдённые страйки. То есть строка исчезала РОВНО ПОТОМУ, что позиция
// проиграла. Замер на годе (57 позиций из 1113 при выигравшей конфигурации): страйк вне
// наблюдённого диапазона у 49 из 57, у остальных 8 инструмента нет при страйке ВНУТРИ диапазона,
// то есть на подгонку не хватило сделок. Вторая причина смешана с первой и её надо назвать:
// 14 из 57 пропадают в последние сутки жизни контракта, когда экспирация прореживает сетку
// (медиана инструментов в экспирации падает с 15 за 48 ч до 3 за час). Средний результат по
// последнему марку −95.3%, прибыльных среди 57 НОЛЬ, а отгруженная конфигурация не теряла ни одной
// (её стоп и тайм-стоп 12ч закрывают раньше). Отсюда сравнение конфигураций сравнивало полную
// выборку с выборкой выживших.
//
// ГРАНИЦА, которую надо знать: ни один пропавший инструмент не доживает до окна Е7 (минимум
// 7 часов до экспирации против порога 6), поэтому в восстановленной записи преэкспирационное
// закрытие практически недостижимо, и живой бот на этих 14 позициях вышел бы по Е7, а не «пропал».
//
// ЧТО ДЕЛАЕТСЯ ВМЕСТО ЭТОГО. Позиция закрывается по ПОСЛЕДНЕМУ снимку, где инструмент ещё был,
// с отдельной причиной `VANISHED`. Это САМАЯ ЩЕДРАЯ из честных трактовок: удержание до экспирации
// дало бы примерно −100%, а не последний марк. Причина отделена от END_OF_RECORD намеренно, потому
// что это разные события: там кончилась ЗАПИСЬ (позиция была жива), здесь кончился ИНСТРУМЕНТ.
// Обе обязаны быть видны в разбивке по причинам, иначе дефект вернётся незаметно.
//
// null возвращается ровно в одном случае: инструмента нет НИ В ОДНОМ снимке после входа, то есть
// оценивать нечего в принципе. Вызывающий обязан такие позиции пересчитать и напечатать, а не
// отфильтровать молча.
//
// ЛЕНИВЫЙ ДОСТУП К СНИМКАМ (`at(k)`), а не массив наблюдений: перебор правил выхода гоняет
// протяжку сотни раз по одной и той же записи, и материализация наблюдений на каждую клетку
// стоила бы дороже самой протяжки.
//   count        - сколько шагов после входа доступно (k = 0..count−1, строго ПОСЛЕ входа);
//   at(k)        - наблюдение { tsMs, markUsd, ivPct, hoursToExpiry, moveSigma } либо null,
//                  если в этот момент инструмента в записи нет;
//   entryTsMs    - метка снимка входа (от неё считается возраст позиции);
//   entryMarkUsd/entryIvPct - база тейка, стопа и vega-стопа;
//   exits        - объект `exits` пресета.
// Возвращает { index, tsMs, markUsd, heldH, reason } либо null.
export function walkExit({ count, at, entryTsMs, entryMarkUsd, entryIvPct, exits } = {}) {
  if (!Number.isInteger(count) || count <= 0 || typeof at !== "function" || !posNum(entryMarkUsd)) {
    return null;
  }
  const held = (tsMs) => (fin(tsMs) && fin(entryTsMs) ? (tsMs - entryTsMs) / 3600000 : null);
  const close = (k, tsMs, markUsd, reason) => ({ index: k, tsMs, markUsd, heldH: held(tsMs), reason });
  // Запоминаются ПОЛЯ последнего живого снимка, а не сам объект: `at` вправе переиспользовать одну
  // структуру между вызовами, и сохранённая ссылка к моменту закрытия указывала бы уже на другой
  // снимок. Заодно в горячем цикле не появляется аллокации на шаг.
  let seenAt = -1, seenTs = null, seenMark = null;
  for (let k = 0; k < count; k++) {
    const o = at(k);
    if (!o || !posNum(o.markUsd)) continue;
    seenAt = k; seenTs = o.tsMs; seenMark = o.markUsd;
    const ev = evaluateExit({ markUsd: o.markUsd, entryMarkUsd, ivPct: o.ivPct, entryIvPct,
      heldH: held(o.tsMs), hoursToExpiry: o.hoursToExpiry, moveSigma: o.moveSigma, exits });
    if (ev.exit) return close(k, o.tsMs, o.markUsd, ev.reason);
    // Запись кончилась, а позиция жива: это НЕ пропажа инструмента, и путать их нельзя.
    if (k === count - 1) return close(k, o.tsMs, o.markUsd, EXIT_REASONS.END_OF_RECORD);
  }
  return seenAt >= 0 ? close(seenAt, seenTs, seenMark, EXIT_REASONS.VANISHED) : null;
}
