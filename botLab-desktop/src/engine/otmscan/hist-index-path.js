// hist-index-path.js - ЧТЕНИЕ таблицы мелкого пути индекса. PURE: ни сети, ни Date.now.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Таблицу пишет офлайн-шаг `scripts/hist-index-path.mjs` (разбирает 568 МБ
// поштучных сделок в компактный путь), а ЧИТАЮТ её два стенда: эталон одной ноги
// `hist-sellhedge.mjs` и оценщик стрэнгла `eval-accel.mjs`. Два разбора одного двоичного формата
// расходятся молча и самым скверным образом: разъехавшийся разбор не падает, он выдаёт другие
// цены, и прогон печатает не ту частоту перекладок без единой ошибки. Здесь разбор один.
//
// ФОРМАТ. Заголовок: метка `BTCP` (uint32 LE) и число шагов (uint32 LE). Дальше по шагу: секунда
// метки (uint32 LE) и цена (float32 LE), восемь байт на шаг.
//
// ПОЧЕМУ float32 ХВАТАЕТ, и это посчитано, а не принято на веру: относительная точность float32
// около 1.2e-7, на цене 80 000 это 0.01 USD. Полосу 0.03 BTC на контракт стрэнгл пересекает
// движением около 245 USD, то есть ошибка представления в двадцать тысяч раз мельче решаемого.
// Секунды в uint32 хватает до 2106 года.
//
// ОКНА БЕЗ ПРИНТА В ТАБЛИЦУ НЕ ПОПАДАЮТ ВОВСЕ и предыдущим значением не протягиваются: протяжка
// выдумала бы движение, которого никто не наблюдал. Поэтому шаги НЕ равноотстоящие, и вызывающий
// обязан ходить по ним метками времени, а не арифметикой индекса.

export const INDEX_PATH_MAGIC = 0x42544350; // "BTCP"

// readIndexPath(buf, label) → { ts: Float64Array (мс), px: Float64Array, n }.
// `label` попадает в текст ошибки: таблицу подают путём из командной строки, и «не тот формат» без
// имени файла означает молча посчитанный не тот прогон.
export function readIndexPath(buf, label = "таблица пути") {
  if (!buf || buf.length < 8 || buf.readUInt32LE(0) !== INDEX_PATH_MAGIC) {
    return { path: null, error: `${label}: это не таблица пути индекса (нет метки BTCP)` };
  }
  const n = buf.readUInt32LE(4);
  if (buf.length < 8 + n * 8) {
    return { path: null, error: `${label}: заголовок обещает ${n} шагов, а байт хватает на ${Math.floor((buf.length - 8) / 8)}` };
  }
  const ts = new Float64Array(n), px = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    ts[i] = buf.readUInt32LE(8 + i * 8) * 1000;
    px[i] = buf.readFloatLE(8 + i * 8 + 4);
  }
  return { path: { ts, px, n }, error: null };
}

// Первый шаг таблицы СТРОГО ПОЗЖЕ метки `t`. Двоичный поиск, потому что шаги не равноотстоящие:
// окна без принта в таблице отсутствуют, и арифметика по индексу дала бы не тот шаг.
export function stepAfter(path, t) {
  let lo = 0, hi = (path?.n ?? 0) - 1, res = path?.n ?? 0;
  while (lo <= hi) { const m = (lo + hi) >> 1; if (path.ts[m] > t) { res = m; hi = m - 1; } else lo = m + 1; }
  return res;
}
