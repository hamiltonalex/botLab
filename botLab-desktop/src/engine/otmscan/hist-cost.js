export const COST_MODEL_PROVENANCE = Object.freeze({
  source: "запись прогона 5, research/otm-scanner/run5-2026-08-07/records.tar.gz",
  windowUtc: "2026-08-04T16:48Z .. 2026-08-07T17:37Z",
  snapshots: 809,
  instruments: 428,
  statistic: "медиана по клетке, клетки с n < 30 не заполнялись",
  isAssumption: true,
  caveat: "спокойный режим рынка; проскальзывание и глубина не моделируются",
});

const bucket = (edges, v) => {
  for (let i = 0; i < edges.length - 1; i++) if (v >= edges[i] && v < edges[i + 1]) return i;
  return -1;
};

// modelledSpread({ deltaAbs, daysToExpiry, markUsd, vegaUsd, invariant, scale })
//   → { spreadUsd, spreadPctPremium, spreadIvPoints, cell } | null
// invariant: "ivPoints" (по умолчанию) | "pctPremium"; scale — множитель чувствительности.
export function modelledSpread({ deltaAbs, daysToExpiry, markUsd, vegaUsd, invariant = "ivPoints", scale = 1 } = {}) {
  if (!posNum(markUsd) || !fin(daysToExpiry) || daysToExpiry < 0 || !fin(deltaAbs) || !posNum(scale)) return null;
  const ad = Math.abs(deltaAbs);
  const ei = bucket(COST_EXPIRY_EDGES_DAYS, daysToExpiry);
  const di = bucket(COST_DELTA_EDGES, ad);
  if (ei < 0 || di < 0) return null; // вне измеренной сетки — молчим, а не додумываем

  let spreadUsd = null;
  if (invariant === "pctPremium") {
    const pct = SPREAD_PCT_PREMIUM[ei]?.[di];
    if (!posNum(pct)) return null;
    spreadUsd = (markUsd * pct * scale) / 100;
  } else {
    const pts = SPREAD_IV_POINTS[ei]?.[di];
    if (!posNum(pts) || !posNum(vegaUsd)) return null; // без веги пункты воли в доллары не перевести
    spreadUsd = pts * vegaUsd * scale;
  }
  if (!posNum(spreadUsd)) return null;
  // Ширина не может съесть премию целиком: бид ушёл бы в ноль или ниже. Потолок 180% премии
  // оставляет бид на уровне 10% марка — это уже неторгуемо, но арифметически корректно.
  spreadUsd = Math.min(spreadUsd, markUsd * 1.8);
  return {
    spreadUsd,
    spreadPctPremium: (spreadUsd / markUsd) * 100,
    spreadIvPoints: posNum(vegaUsd) ? spreadUsd / vegaUsd : null,
    cell: { expiryBucket: ei, deltaBucket: di, invariant, scale },
  };
}

// quotesFromMark(...) → { bid, ask, mid } или null.
// Марк принимается за СЕРЕДИНУ рынка, а спред раскладывается симметрично вокруг него. Это тоже
// допущение: у живых котировок марк бывает вне книги (замер по записи прогона 5: у нас 11.8% строк,
// у самой биржи 13.3% — марк модельный и у неликвидных законно лежит вне bid/ask). Симметрия
// выбрана потому, что систематическую асимметрию по записи измерить не удалось бы: она зависит от
// стороны потока, которой в истории нет.
export function quotesFromMark(args) {
  const s = modelledSpread(args);
  if (!s) return null;
  const { markUsd } = args;
  const half = s.spreadUsd / 2;
  const bid = markUsd - half;
  const ask = markUsd + half;
  if (!(bid > 0) || !(ask > bid)) return null;
  return { bid, ask, mid: markUsd, ...s };
}
