// ЭТО ДОПУЩЕНИЕ, А НЕ ИЗМЕРЕНИЕ ИСТОРИИ, и так оно подписано везде, где всплывает в отчётах.
// Deribit не хранит исторических bid/ask и глубины стакана — ни на www, ни на архивном хосте, ни
// платно. Проверено прямыми вызовами. Значит бектест на истории умеет ответить на вопрос «был ли
// сигнал и куда пошла волатильность», но НЕ умеет ответить «пережила бы сделка исполнение», пока
// спред не привнесён извне.
//
// ПОЧЕМУ ЭТО ВАЖНЕЕ ВСЕГО ОСТАЛЬНОГО. Аудит 2026-08-08 установил числом, что связывающее
// ограничение стратегии — именно круг издержек: 6.49% премии на сроке 7-14 дней и 2.03% на 28-56,
// то есть 1.52 пункта волатильности против реализовавшегося запаса −0.53 пункта. Бектест, считающий
// по одним маркам, покажет сигнал там, где сделка не выжила бы. Поэтому спред моделируется явно,
// а вывод обязан предъявляться с чувствительностью к этой модели.
//
// ОТКУДА ЧИСЛА. Из НАШЕЙ СОБСТВЕННОЙ записи прогона 5 (2026-08-04..07, 72.7 ч, 809 снимков всей
// поверхности BTC_USDC, каждые 5 минут, bid/ask/mark/вега по 428 инструментам). Медиана по клетке
// (срок × |дельта|), клетки с выборкой меньше 30 строк оставлены пустыми. Тот же материал печатает
// `npm run eval:toll`, здесь он разложен по обеим осям, а не по одной полосе дельты.
//
// ДВЕ ЕДИНИЦЫ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ МОДУЛЯ. Спред можно переносить на год двумя способами, и они
// дают разный ответ:
//   "ivPoints"   — константой держится ШИРИНА В ПУНКТАХ ВОЛАТИЛЬНОСТИ (bid−ask, делённое на вегу);
//   "pctPremium" — константой держится доля премии.
// Замер по записи показывает, что маркет-мейкеры котируют в воле: по дельте 0.3→0.5 на сроке 8-16
// дней спред в пунктах IV идёт 0.86 · 0.98 · 1.48 (почти плоско), а в процентах премии 4.62 · 3.86 ·
// 4.11 при том же материале, и разброс по срокам в процентах премии втрое шире. Поэтому дефолт —
// "ivPoints", а вторая шкала оставлена как ОСЬ ЧУВСТВИТЕЛЬНОСТИ: если вывод бектеста переворачивается
// при смене инварианта, значит он держится на модели издержек, а не на данных, и это надо знать.
//
// ЧЕГО МОДЕЛЬ НЕ ДЕЛАЕТ. Не знает режима рынка: таблица снята в спокойные августовские сутки, а в
// стрессе спреды разъезжаются. Не знает проскальзывания и частичного исполнения. Не знает глубины
// (У12 в историческом прогоне поэтому не гейт). Всё это двигает результат в ОДНУ сторону — против
// стратегии, — поэтому исторический бектест на этих числах оптимистичен, и множитель ×2 в
// чувствительности существует именно для этого.
//
// TRI-STATE. За границами измеренной сетки (|дельта| вне 0.05..0.8) возвращается null, а не
// ближайшая клетка: край сетки — это граница знания, и продолжать её догадкой нельзя.

const fin = (x) => Number.isFinite(x);
const posNum = (x) => fin(x) && x > 0;

// Границы клеток. Дельта берётся по модулю, поэтому колл и пут ложатся в одну сетку.
