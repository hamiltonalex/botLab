// В БОЙ ЭТО НЕ ЕДЕТ, И ЭТО РАТИФИЦИРОВАНО. У живой схемы входных гейтов НЕТ. Поэтому модуль не
// импортируется ни движком бота 2, ни main.js: он существует для офлайн-отчёта. И это не
// осторожность, а свойство измеряемого: единственное, что гейт умеет со сделкой, - ОТЛОЖИТЬ её.
// Ногу он не улучшает, её выбирает правило «срок 336-672 ч, |дельта| у 0.45» в момент открытия,
// поэтому цена гейта это ПРОСТОЙ, а не качество контракта.
