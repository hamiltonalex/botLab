// ЗНАЧЕНИЯ ОСЕЙ МОДУЛЬ НЕ СЧИТАЕТ, и это граница. Их подаёт вызывающий, потому что берутся они из
// разных мест записи: rv7 и импульс лежат в строке тика (их посчитал `computeRvBundle` при сборке
// записи), а скос считается из снимка поверхности. Считать их здесь значило бы завести второе
// определение рядом с движком - тот самый класс дефекта, который проект ловил четырежды.
//
// «НЕТ ДАННЫХ» - ВЕТО, НО ОТДЕЛЬНЫМ СТОЛБЦОМ. Идиома проекта одна (sanity.js): fail и unknown оба
// являются вето. Но у ИЗМЕРЕНИЯ смешивать их нельзя: «гейт отклонил 300 входов» и «у гейта не было
// данных на 300 входах» - разные факты, и второй означает дефект записи, а не свойство рынка.

const fin = (x) => Number.isFinite(x);

// Оси гейта - ровно те, что названы в выводе прогона (разрыв IV-RV, скос, моментум). label и unit
// нужны отчёту: строка таблицы обязана называть, ЧТО сравнивается и в чём, иначе порог «5» читается
// как угодно. ВЕРТИКАЛЬНОЙ ЧЕРТЫ В ПОДПИСИ БЫТЬ НЕ МОЖЕТ: отчёты печатаются markdown-таблицами, и
// «|ΔP24h|» разрезало бы строку на лишние ячейки (поймано сквозным прогоном, закреплено тестом).
export const GATE_AXES = Object.freeze({
  ivrv: Object.freeze({ label: "IV ноги − RV7d", unit: "п.в." }),
  imp: Object.freeze({ label: "импульс движения за сутки", unit: "σ" }),
  skew: Object.freeze({ label: "скос ±1σ (пут−колл)", unit: "п.в." }),
});

// Сравнения. Строгие и нестрогие ОБА: попадание ровно на порог - отдельный вопрос, и решать его за
// оператора молча нельзя. Знаки печатаются типографскими, а читаются машинными.
const CMP = Object.freeze({
  ">=": (a, b) => a >= b,
  "<=": (a, b) => a <= b,
  ">": (a, b) => a > b,
  "<": (a, b) => a < b,
});
const SIGN = Object.freeze({ ">=": "≥", "<=": "≤", ">": ">", "<": "<" });
// Двухсимвольные знаки ищутся ПЕРВЫМИ: в строке "ivrv>=5" есть и ">=", и ">", и порядок решает,
// какой из них будет разобран.
const OPS = Object.keys(CMP).sort((a, b) => b.length - a.length);

const axisList = () => Object.keys(GATE_AXES).join(", ");

// parseGateSpec("ivrv>=5,imp<=3") → { terms: [{ axis, op, thr }], error: null }.
// Ошибка НАЗЫВАЕТ виновника и перечисляет допустимое: спецификация приходит из командной строки,
// и «не разобралось» без адреса означает молча посчитанный не тот прогон.
export function parseGateSpec(spec) {
  const src = typeof spec === "string" ? spec.trim() : "";
  if (!src) return { terms: null, error: "пустая спецификация (пример: ivrv>=5,imp<=3)" };
  const terms = [];
  for (const part of src.split(",")) {
    const s = part.trim();
    if (!s) continue;
    const op = OPS.find((o) => s.includes(o));
    if (!op) return { terms: null, error: `в «${s}» нет знака сравнения (${OPS.join(" ")})` };
    const at = s.indexOf(op);
    const axis = s.slice(0, at).trim();
    const raw = s.slice(at + op.length).trim();
    if (!Object.hasOwn(GATE_AXES, axis)) return { terms: null, error: `ось «${axis}» неизвестна (есть: ${axisList()})` };
    const thr = Number(raw);
    if (!fin(thr)) return { terms: null, error: `порог «${raw}» не число (ось ${axis})` };
    terms.push({ axis, op, thr });
  }
  if (!terms.length) return { terms: null, error: "спецификация не содержит ни одного условия" };
  return { terms, error: null };
}

// Подпись гейта для таблицы и шапки отчёта.
export function formatGateTerms(terms) {
  return (terms ?? [])
    .map((t) => `${GATE_AXES[t.axis]?.label ?? t.axis} ${SIGN[t.op] ?? t.op} ${t.thr} ${GATE_AXES[t.axis]?.unit ?? ""}`.trim())
    .join(" · ");
}

// Счётчик отклонённых входов. checked - сколько раз гейт вообще спрашивали (кандидат уже найден
// правилом схемы), passed - сколько раз пустил, blocked/noData - две причины отказа, byAxis - та же
// пара по осям.
export function makeGateCounter() {
  return { checked: 0, passed: 0, blocked: 0, noData: 0, byAxis: {} };
}

const bump = (counter, axis, key) => {
  if (!counter) return;
  counter[key] += 1;
  const b = counter.byAxis[axis] ?? (counter.byAxis[axis] = { blocked: 0, noData: 0 });
  b[key] += 1;
};

// testGate(terms, measures, counter) → пускать ли вход. measures = { ivrv, imp, skew }; ось без
// конечного значения - вето (см. шапку).
//
// СЧЁТЧИК ИМЕНУЕТ ПЕРВУЮ НЕ ПРОШЕДШУЮ ОСЬ И НА НЕЙ ОСТАНАВЛИВАЕТСЯ. Иначе сумма по осям превысила
// бы число отклонённых входов, и таблица врала бы о том, какая ось решает. Порядок осей - порядок
// условий в спецификации, то есть выбор оператора, а не наш.
export function testGate(terms, measures, counter = null) {
  if (counter) counter.checked += 1;
  for (const t of terms ?? []) {
    const v = measures?.[t.axis];
    if (!fin(v)) {
      bump(counter, t.axis, "noData");
      return false;
    }
    if (!CMP[t.op](v, t.thr)) {
      bump(counter, t.axis, "blocked");
      return false;
    }
  }
  if (counter) counter.passed += 1;
  return true;
}
