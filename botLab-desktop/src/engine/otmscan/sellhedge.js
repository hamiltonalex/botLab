// sellhedge.js - ПРАВИЛА продажи опциона с дельта-хеджем. PURE: ни сети, ни файлов, ни Date.now.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, И ЭТО НЕ УДОБСТВО. До сих пор единственная прибыльная конфигурация
// проекта существовала ТОЛЬКО внутри офлайн-скрипта `scripts/hist-sellhedge.mjs`. Живой движок её
// не исполняет и исполнить не может: сканер рождает сигналы на ПОКУПКУ по чеклисту У1-У14, и ни
// одной из шести частей этой схемы у него нет целиком (замер 2026-08-13):
//   - окно экспираций активного пресета 672-1344ч содержит ногу схемы в 0.04% снимков;
//   - `side` во всём коде сканера означает ТИП опциона, а не направление сделки;
//   - вердикт при пустом чеклисте структурно `none` (`applicable.length > 0` в aggregateVerdict),
//     то есть «схема без условий входа» через перевод У1-У14 в off НЕДОСТИЖИМА;
//   - `computeSizing` меряет риск уплаченной премией, а продавца связывает МАРЖА (замер: залог за
//     лот $92 против премии $21.91, то есть покупательский гейт разрешил бы вчетверо больше);
//   - `btcopt/hedge.js` импортируется только ботом 2 и в сканерный тракт не заходит;
//   - выхода «дожить до экспирации» нет вовсе: EXIT_REASONS его не содержит.
// Пока правило живёт в скрипте, перенос в бой означает НАПИСАТЬ ЕГО ЗАНОВО, а это ровно тот класс
// дефекта («две части системы решают одну задачу разными правилами»), который проект ловил уже
// четырежды. Поэтому правило переезжает сюда целиком, а скрипт становится его вызывающим.
//
// ЧТО ЗДЕСЬ ЛЕЖИТ, по шагам схемы:
//   1. `pickSellLeg`   - какой контракт продаём: нога legType (колл по умолчанию) в окне срока,
//                        |дельта| ближайшая к целевой;
//   2. `openSellTrade` - премия, издержки входа, начальный хедж, требование залога;
//   3. `wantHedge`     - нужный размер перпа сейчас (дельта позиции);
//   4. `shouldRehedge` - перекладываемся ли: |нужный − текущий| за полосой;
//   5. `walkSellTrade` - протяжка до экспирации. Боевой выход один - экспирация;
//   6. `lotsByMargin`  - сколько лотов позволяет залог;
//   7. `shouldStopOut` / `makeStopGate` - ЗАМЕРЯЕМЫЙ досрочный выход, по умолчанию выключен.
//
// ПОЧЕМУ ПРОТЯЖКА ЗДЕСЬ, А НЕ У ВЫЗЫВАЮЩЕГО - тот же довод, что у `walkExit` в exits.js: в цикле
// спрятано РЕШЕНИЕ, которого нет в отдельных правилах. Здесь их два. Первое: досрочных выходов НЕТ
// ни одного, и это не пропуск, а суть схемы (перебор 630 конфигураций выхода для покупки не дал ни
// одной прибыльной клетки). Второе: что делать, когда лестница цены не выдала цену вовсе. Ответ -
// сделка не засчитывается, и вызывающий обязан такие случаи СЧИТАТЬ и печатать, а не отбрасывать
// молча: пропажа строки коррелирует с большим движением, и молчаливое отбрасывание есть отбор по
// исходу (цена ошибки измерена в hist-price.js - около ста процентных пунктов).
//
// ПОРЯДОК АРИФМЕТИКИ В ПРОТЯЖКЕ ЗНАЧИМ И ЗАФИКСИРОВАН. Накопители складываются в том же порядке,
// что и раньше в скрипте (сначала P&L хеджа, потом фандинг, потом сдвиг `prev`, потом цена), иначе
// плавающая точка даёт другой последний разряд и сверка «побайтово то же» перестаёт быть проверкой.
//
// ЛЕНИВЫЙ ДОСТУП К ЗАПИСИ (`spotAt` / `priceAt` / `tsAt`), а не массив наблюдений: цена считается
// лестницей и стоит дорого, а снимки без спота её не должны вызывать вовсе - иначе счётчик ступеней
// лестницы у вызывающего насчитает оценки, которых не было.

import { computeTradeCosts } from "./economics.js";

const fin = (x) => Number.isFinite(x);
const posNum = (x) => fin(x) && x > 0;

// Настройки схемы. Числа НЕ выбраны на глаз: срок и дельта проверены перебором (0.30 даёт просадку
// 36% против 13.5%, 0.60 даёт ×1.43 против ×2.03; окно 7-14 суток даёт ×1.99 при просадке 18.6%,
// 28-56 суток ×1.51 при 20.7%), полоса выбрана сеткой против стоимости перекладки и её оптимум от
// этой стоимости ЗАВИСИТ (мейкер: теснее всегда лучше; 10 б.п.: шире лучше, а 0.01 даёт ×0.98).
// Поэтому полоса обязана выбираться под ФАКТИЧЕСКОЕ исполнение, а не копироваться из бектеста.
export const SELLHEDGE_DEFAULTS = Object.freeze({
  expiryMinH: 336, // окно срока, часы (14-28 суток)
  expiryMaxH: 672,
  deltaTarget: 0.45, // целевая |дельта| проданной ноги
  deltaTol: 0.10, // допуск: нога дальше этого от цели не берётся вовсе
  legType: "C", // тип ноги: колл (боевая схема); "P" существует для офлайн-замеров, живой тракт его не передаёт
  bandBtc: 0.03, // полоса хеджа, BTC на 1.0 контракта
  perpFee: 0, // доля от оборота перпа (0 мейкер, 0.0005 тейкер)
  spreadScale: 1.10, // множитель модельного спреда (замер по живой записи)
  ivHaircut: 0, // продавать на x пунктов воли ниже марка (проверка смещения подгонки)
  chainAdj: 1, // множитель итога сделки (0.69 приводит обратную цепочку к линейной)
  lot: 0.01, // минимальный лот BTC_USDC-опциона
  deployPct: 0.70, // доля счёта, которую разрешено держать в залоге (правило "deploy")
  // Правило размера. "deploy" - лоты от доли IM на входе (исторический замер, книги сверок);
  // "stress" - АВТОНОМНОЕ: лоты от двухсторонней стресс-маржи (lotsByStressMargin в btcopt/margin),
  // движок считает размер сам на каждом входе. Константы X/cap НЕ выбраны на глаз: сетка
  // eval-accel --size-rule stress на пяти годах (2026-08-26) дала X=45 как наименьший запас, при
  // котором пик MM-утилизации записи не превышает 0.8 у ОБЕИХ боевых схем (колл 336-672: 76.6%,
  // стрэнгл: 73.9%) при нуле ликвидаций и росте, равном внутривыборочной калибровке deployPct
  // (×2.48 против ×2.59 и ×4.12 против ×4.09); cap 1.0 даёт ликвидации почти во всех клетках.
  // ±45% читается как «переживи повтор худшего наблюдённого хода» (январь 2023: +47% внутри
  // сделки). Дефолт остаётся "deploy": книги сверок сняты им, а живое вооружение цепочки передаёт
  // "stress" явным sellCfg - там, где размер прежде решало операторское число.
  sizeRule: "deploy",
  stressXPct: 45,
  stressCapFrac: 0.8,
  // Правило ДОСРОЧНОГО выхода. null = выхода нет, и это боевой дефолт: пятилетние книги сняты
  // схемой, у которой единственный выход - экспирация. Поле существует ради ЗАМЕРА предложения
  // заказчика («оптимизировать SL»), предрегистрация 2026-08-28. Форма:
  //   { metric, level, action, hyst, fill }
  //   metric: premx | im | eq | mny | mmu (см. shouldStopOut), level: число оси,
  //   action: exit | halve | none, hyst: oneshot | band | rearm, fill: same | next.
  // Пока значение null, ни одна ветка ниже не исполняется и арифметика протяжки прежняя ДО БИТА.
  stop: null,
});

// ── 1. Выбор ноги. Нога типа `legType` (колл, пока не сказано иное) нужного срока с |дельтой|
// ближе всего к целевой; ничего кроме этого схема про момент входа не спрашивает. Отсутствующее
// поле legType читается как колл, поэтому старые вызывающие правок не требуют, а живой тракт
// (buildSellStructure) этот параметр не передаёт вовсе. Строка обязана нести ВСЕ поля расчёта
// (mark, bid/ask, IV, вега): нога без них не оценивается, и подставлять оценку вместо наблюдения
// здесь нельзя.
//   rows - строки поверхности одного снимка (любой итерируемый);
//   поля строки: h часов до экспирации, s тип "C"/"P", m марк, d дельта, b/a бид/аск, iv, vg вега.
// rankSellLegs - те же фильтры, но до `limit` кандидатов в порядке близости дельты. Нужен
// санитарии (дизайн §1.8: вето переключает контракт, а не останавливает цепочку), поэтому
// вызывающему требуется не один победитель, а очередь запасных В ДОПУСКЕ по дельте.
// Сортировка стабильна (ES2019), при равном расстоянии порядок строк сохраняется - тот же выбор,
// что делал старый цикл со строгим `<`.
export function rankSellLegs(rows, cfg = SELLHEDGE_DEFAULTS, limit = 1) {
  const want = cfg.legType === "P" ? "P" : "C"; // всё, что не «P», означает колл - как и раньше
  const out = [];
  for (const r of rows ?? []) {
    if (!fin(r?.h) || r.h < cfg.expiryMinH || r.h > cfg.expiryMaxH || r.s !== want) continue;
    if (!(r.m > 0) || !fin(r.d) || !fin(r.b) || !fin(r.a) || !fin(r.iv) || !fin(r.vg)) continue;
    const dd = Math.abs(Math.abs(r.d) - cfg.deltaTarget);
    if (dd <= cfg.deltaTol) out.push({ r, dd });
  }
  out.sort((x, y) => x.dd - y.dd);
  return out.slice(0, Math.max(1, limit | 0)).map((x) => x.r);
}

export function pickSellLeg(rows, cfg = SELLHEDGE_DEFAULTS) {
  return rankSellLegs(rows, cfg, 1)[0] ?? null;
}

// ── 2. Вход. `costs` приходит от computeTradeCosts (единый источник издержек проекта), `imUsd` от
// legMargin. ДО ЭКСПИРАЦИИ ПЛАТИТСЯ ТОЛЬКО ВХОД: опцион гасится сам, и второй раз книгу пересекать
// не надо, поэтому берётся половина круга. Начальный хедж равен дельте проданной ноги: короткий
// колл несёт дельту −d, значит нейтрализует его ЛОНГ перпа на +d. Формула `qPerp = leg.d` общая по
// знаку: у пута дельта отрицательна, и тот же код даёт ШОРТ перпа - подставлять |d| со своим знаком
// было бы второй записью того же правила.
export function openSellTrade({ leg, spotUsd, costs, imUsd, cfg = SELLHEDGE_DEFAULTS } = {}) {
  if (!leg || !posNum(spotUsd) || !costs || !posNum(leg.m)) return null;
  const premSold = leg.m - (cfg.ivHaircut > 0 ? leg.vg * cfg.ivHaircut : 0);
  if (!(premSold > 0)) return null;
  const optCost = (costs.roundTripCostPct / 100) * leg.m / 2;
  const qPerp = leg.d;
  return { premSold, optCost, imUsd, qPerp, hedgeFee: Math.abs(qPerp) * spotUsd * cfg.perpFee };
}

// Половина модельного спреда для computeTradeCosts. Отдельной функцией, потому что множитель
// spreadScale это ДОПУЩЕНИЕ (модельные bid/ask записи занижают круг на 6% против живой записи), и
// оно обязано быть видимым, а не растворяться в арифметике вызывающего.
export function halfSpreadUsd(leg, cfg = SELLHEDGE_DEFAULTS) {
  return ((leg.a - leg.b) / 2) * cfg.spreadScale;
}

// ── 3-4. Хедж. Нужный размер перпа равен дельте позиции; перекладываемся, только когда разрыв
// ВЫШЕ полосы. Ни триггера по времени, ни по цене, ни фильтра выгоды: замер по живой записи дал,
// что проверка раз в 5 минут и раз в час приводит к ОДНОМУ результату - решает полоса, а не частота.
export function wantHedge(deltaOfPosition) {
  return fin(deltaOfPosition) ? deltaOfPosition : 0;
}
export function shouldRehedge({ want, have, bandBtc } = {}) {
  return fin(want) && fin(have) && fin(bandBtc) && Math.abs(want - have) > bandBtc;
}

// ── 5. Протяжка до экспирации. Выход БОЕВОЙ схемы один - экспирация: ни тейка, ни стопа, ни
// падения воли, ни тайм-стопа. Досрочный выход существует ТОЛЬКО как замеряемая опция (`stopAt`,
// см. раздел 6) и по умолчанию выключен: без этого колбэка цикл ниже исполняется ровно как
// прежде. Возвращает { exitVal, exitIndex, hedgePnl, hedgeFee, funding, rehedges, turnoverBtc,
// lastSpot } плюс поля стопа, либо null, если цена не вышла хотя бы на одном шаге (см. шапку).
// `turnoverBtc` - суммарный ОБОРОТ хеджа (вход плюс все поправки, без закрытия перпа в экспирацию):
// число перекладок само по себе ничего не говорит о том, сколько через них прошло.
//   count       - сколько шагов доступно ПОСЛЕ входа, k = 0..count−1;
//   tsAt(k)     - метка шага;
//   spotAt(k)   - индекс на шаге либо null: снимок без спота пропускается целиком;
//   priceAt(k)  - { markUsd, delta } лестницей цены, вызывается ТОЛЬКО при валидном споте;
//   fundRateAt(tsMs) - часовая ставка фандинга (положительная = лонги платят);
//   expiryMs    - экспирация проданной ноги;
//   entry       - { qPerp, hedgeFee } из openSellTrade;
//   entryTsMs / entrySpot - метка и индекс на входе;
//   onStep      - НАБЛЮДАТЕЛЬ шага (опционально): {ts, S, mark, delta, qPerp, hedgePnl, funding,
//                 hedgeFee, atExpiry} после начислений и цены, ДО перекладки. Нужен измерителю
//                 маржинального пути и режиму ликвидации эталона (ревизия 2026-08-25 Р2): без него
//                 внутрисделочный путь пришлось бы восстанавливать второй реализацией этой же
//                 протяжки. Наблюдатель только читает; без него поведение прежнее до бита.
export function walkSellTrade({
  count, tsAt, spotAt, priceAt, fundRateAt, expiryMs, entry, entryTsMs, entrySpot, onStep, stopAt,
  cfg = SELLHEDGE_DEFAULTS,
} = {}) {
  if (!Number.isInteger(count) || count <= 0 || !entry) return null;
  let qPerp = entry.qPerp;
  let hedgeFee = entry.hedgeFee;
  let hedgePnl = 0;
  let funding = 0;
  let rehedges = 1; // вход в хедж это уже одна поправка
  let turnoverBtc = Math.abs(qPerp); // и один оборот
  let prevS = entrySpot;
  let prevTs = entryTsMs;
  let exitIndex = -1;
  let exitVal = null;
  // Состояние ДОСРОЧНОГО выхода. Без `stopAt` не меняется вовсе: scale остаётся 1, накопители
  // нулями, и возвращаемая структура несёт optLegOverride === null, то есть settleSellTrade
  // считает старой формулой. `scale` это доля позиции, ещё живая на шаге (1 или 0.5 после
  // урезания); `optRealized` - уже зафиксированная часть опционной ноги на 1.0 контракта.
  let scale = 1;
  let optRealized = 0;
  let stopCost = 0;
  let stopped = false;
  let stopIndex = -1;
  let stopCount = 0;

  for (let k = 0; k < count; k++) {
    const S = spotAt(k);
    if (!(S > 0)) continue;
    const ts = tsAt(k);
    hedgePnl += qPerp * (S - prevS);
    funding += qPerp * S * (fundRateAt(ts) ?? 0) * ((ts - prevTs) / 3600000);
    prevS = S;
    prevTs = ts;
    const p = priceAt(k);
    if (!p) return null; // цена не вышла: сделка не засчитывается, вызывающий обязан это СЧИТАТЬ
    exitIndex = k;
    if (onStep) onStep({ ts, S, mark: p.markUsd, delta: p.delta ?? null, qPerp, hedgePnl, funding, hedgeFee, atExpiry: ts >= expiryMs });
    if (ts >= expiryMs) {
      exitVal = p.markUsd;
      break;
    }
    // ДОСРОЧНЫЙ ВЫХОД. Экспирация проверена ВЫШЕ и имеет приоритет: на экспирационном шаге стоп
    // уже не спрашивается, иначе правило «успевало» бы выйти из сделки, которая и так завершена.
    // Вердикт даёт вызывающий (счёт и цена выхода живут у него), протяжка исполняет механику.
    if (stopAt) {
      const act = stopAt({ k, ts, S, mark: p.markUsd, delta: p.delta ?? null, qPerp, hedgePnl, funding, hedgeFee, scale });
      if (act && act.action) {
        stopCount += 1;
        if (stopIndex < 0) stopIndex = k;
        if (act.action === "restore") {
          // Возврат к полному размеру: недостающая доля ПРОДАЁТСЯ заново по марку ЭТОГО шага,
          // а не по премии входа, поэтому поправка равна add·(марк − премия входа).
          const add = 1 - scale;
          if (add > 0) {
            optRealized += add * (p.markUsd - entry.premSold);
            stopCost += add * (act.costUsd ?? 0);
            scale += add;
          }
        } else if (act.action === "exit" || act.action === "halve") {
          const cut = act.action === "halve" ? scale * 0.5 : scale;
          optRealized += cut * (entry.premSold - p.markUsd);
          stopCost += cut * (act.costUsd ?? 0);
          scale -= cut;
          stopped = true;
          if (scale <= 0) { exitVal = p.markUsd; break; }
        }
      }
    }
    // Умножение на scale выписано ветвью НАМЕРЕННО: при выключенном стопе обязано исполняться
    // ровно прежнее выражение, иначе побайтовая сверка пятилетних книг перестаёт быть проверкой.
    const want = scale === 1 ? wantHedge(p.delta ?? 0) : wantHedge(p.delta ?? 0) * scale;
    if (shouldRehedge({ want, have: qPerp, bandBtc: cfg.bandBtc })) {
      hedgeFee += Math.abs(want - qPerp) * S * cfg.perpFee;
      turnoverBtc += Math.abs(want - qPerp);
      qPerp = want;
      rehedges += 1;
    }
  }
  if (exitVal == null) return null;
  hedgeFee += Math.abs(qPerp) * prevS * cfg.perpFee; // закрытие перпа в экспирацию либо на стопе
  return {
    exitVal, exitIndex, hedgePnl, hedgeFee, funding, rehedges, turnoverBtc, lastSpot: prevS,
    // Поля стопа. Без `stopAt` они тождественно нулевые/пустые, и settleSellTrade идёт прежней
    // веткой. `optLegOverride` уже содержит и зафиксированную часть, и остаток до экспирации.
    stopped, stopIndex, stopCount, scale,
    stopCost: stopped ? stopCost : 0,
    optLegOverride: stopped ? optRealized + scale * (entry.premSold - exitVal) : null,
  };
}

// Итог одной сделки на ОДИН контракт 1.0 BTC. Поправка цепочки применяется к ИТОГУ, а не к статьям:
// это множитель типа контракта (обратная цепочка против линейной), а не свойство какой-то статьи.
export function settleSellTrade({ open, walk, cfg = SELLHEDGE_DEFAULTS } = {}) {
  if (!open || !walk) return null;
  // Обе ветки выписаны явно: при выключенном стопе обязана исполняться прежняя арифметика в
  // прежнем порядке слагаемых, иначе последний разряд поплывёт и побайтовая сверка книг умрёт.
  const optLeg = walk.optLegOverride == null ? open.premSold - walk.exitVal : walk.optLegOverride;
  const cost = walk.stopCost ? open.optCost + walk.hedgeFee + walk.stopCost : open.optCost + walk.hedgeFee;
  const pnl = (optLeg + walk.hedgePnl - cost - walk.funding) * cfg.chainAdj;
  return { pnl, optLeg, hedgeLeg: walk.hedgePnl, cost, fund: walk.funding };
}

// МтМ сделки на один контракт НА ШАГЕ протяжки, в конвенции settleSellTrade: (премия − марк) +
// хедж − (вход + комиссии хеджа) − фандинг, целиком × chainAdj. Функция существует затем, что эту
// величину уже считают ДВА вызывающих (режим ликвидации эталона и офлайн-оценщик ускорения
// оборота), а одна формула в двух скриптах - ровно тот класс дефекта («две части системы решают
// одну задачу разными правилами»), ради которого модуль и заведён. Издержки шага НЕ включают
// закрытие перпа в экспирацию (walk добавляет его после цикла) - при нулевой комиссии перпа
// разницы нет; на экспирационном шаге при бесплатном перпе МтМ равен итогу settleSellTrade, и это
// закреплено тестом, а не подразумевается.
export function stepMtm({ premSold, optCost, step, cfg = SELLHEDGE_DEFAULTS } = {}) {
  if (!step || !fin(premSold) || !fin(optCost)) return null;
  return (premSold - step.mark + step.hedgePnl - (optCost + step.hedgeFee) - step.funding) * cfg.chainAdj;
}

// ── 6. ДОСРОЧНЫЙ ВЫХОД: ПРЕДИКАТ И ЗАТВОР.
//
// ЭТОГО В БОЕВОЙ СХЕМЕ НЕТ И ПО УМОЛЧАНИЮ НЕ БУДЕТ. Правило заведено под ЗАМЕР предложения
// заказчика, предрегистрация `bot2-sl-предрегистрация-2026-08-28.md`: пороги, сетка и критерий
// зачёта заморожены ДО первого прогона. Пока `cfg.stop` равен null, ни одна строка ниже не
// исполняется, и книги остаются побайтово теми же.
//
// ПОЧЕМУ ПРЕДИКАТ ОТДЕЛЬНО ОТ ЗАТВОРА, А ЗАТВОР ОТДЕЛЬНО ОТ ПРОТЯЖКИ. Пять метрик делятся на две
// группы: `premx`, `im`, `mny` считаются на ОДИН контракт и не зависят от размера позиции, а `eq`
// и `mmu` зависят от счёта и от лотов. Протяжка про счёт не знает и знать не должна (она ведёт
// один контракт), поэтому решение принимает ВЫЗЫВАЮЩИЙ, у которого есть и счёт, и запись, а
// протяжка получает готовый вердикт колбэком - тем же приёмом, что и наблюдатель `onStep`.
// Затвор (`makeStopGate`) держит гистерезис в ОДНОМ месте: иначе каждый из трёх вызывающих
// написал бы свой, а это ровно тот класс дефекта, ради которого заведён этот модуль.
//
//   mtm1     - МтМ сделки на 1.0 контракта (stepMtm), в конвенции settleSellTrade;
//   premSold - премия входа на контракт; imUsd - залог на контракт; mmUsd - поддерживающая
//              маржа на контракт; qty - размер позиции в контрактах; equityUsd - счёт;
//   spotUsd  - индекс на шаге; strikes - ноги структуры [{ type, strike }] (у пары обе).
export function shouldStopOut({
  metric, level, mtm1, premSold, imUsd, equityUsd, qty, mmUsd, spotUsd, strikes,
} = {}) {
  if (!metric || !fin(level)) return false;
  switch (metric) {
    // Стоп по P&L: убыток сделки достиг кратности проданной премии / доли залога / доли счёта.
    case "premx": return fin(mtm1) && posNum(premSold) && mtm1 <= -level * premSold;
    case "im": return fin(mtm1) && posNum(imUsd) && mtm1 <= -level * imUsd;
    case "eq": return fin(mtm1) && posNum(qty) && posNum(equityUsd) && mtm1 * qty <= -level * equityUsd;
    // Стоп по ЭКСПОЗИЦИИ: спот ушёл за страйк на `level`. Не зависит ни от размера, ни от
    // переоценки; у пары срабатывает уход ЛЮБОЙ ноги в свою сторону.
    case "mny": {
      if (!posNum(spotUsd) || !Array.isArray(strikes) || !strikes.length) return false;
      return strikes.some((leg) => posNum(leg?.strike) && (leg.type === "P"
        ? spotUsd <= leg.strike * (1 - level)
        : spotUsd >= leg.strike * (1 + level)));
    }
    // Стоп по РИСКУ, а не по убытку: утилизация поддерживающей маржи. Смотрит на способность
    // счёта пережить СЛЕДУЮЩИЙ ход, а не на уже понесённый минус. Счёт ниже нуля означает, что
    // биржа закрыла бы позицию сама, поэтому это безусловное срабатывание, а не деление на минус.
    case "mmu": {
      if (!posNum(mmUsd) || !posNum(qty) || !posNum(equityUsd) || !fin(mtm1)) return false;
      const eq = equityUsd + mtm1 * qty;
      return eq <= 0 || (mmUsd * qty) / eq >= level;
    }
    default: return false;
  }
}

// Затвор гистерезиса. Принимает вердикт предиката на шаге и возвращает ДЕЙСТВИЕ либо null:
//   "exit"    - закрыть сделку целиком;
//   "halve"   - урезать позицию вдвое (де-леверидж, тета остаётся работать);
//   "restore" - вернуть полный размер (только при hyst "rearm", после ухода метрики за гистерезис);
//   "none"    - только счётчик срабатываний, механики нет (частотный контроль фазы 1ч).
//   breached  - предикат на этом шаге; cleared - метрика ушла ниже порога возврата (по умолчанию
//               это просто отсутствие пробоя; для 20% гистерезиса вызывающий считает свой).
// hyst: "oneshot" срабатывает один раз за сделку; "band" требует ДВУХ шагов подряд за порогом
// (защита от одиночного выброса часовой сетки); "rearm" перевооружается после возврата.
// fill: "next" откладывает действие на следующий шаг (выход по марку СЛЕДУЮЩЕГО часа) - стресс
// исполнения из предрегистрации, п. 4(в).
// Разбор спецификации правила. Живёт здесь, а не в скриптах, чтобы эталон и гарнир принимали
// РОВНО один набор метрик и значений осей: разошедшийся разбор дал бы разные сетки под одним
// именем. Возвращает { stop } либо { error } с готовым текстом; печать ошибки за вызывающим.
export function parseStopSpec(spec, opts = {}) {
  if (spec == null) return { stop: null };
  const METRICS = ["premx", "im", "eq", "mny", "mmu"];
  const [metric, lv] = String(spec).split(":");
  const level = Number(lv);
  if (!METRICS.includes(metric) || !fin(level)) {
    return { error: `ожидается «метрика:уровень», метрика из ${METRICS.join("|")}, получено «${spec}»` };
  }
  const ALLOWED = { action: ["exit", "halve", "none"], hyst: ["oneshot", "band", "rearm"], fill: ["same", "next"] };
  const DEF = { action: "exit", hyst: "band", fill: "same" };
  const out = { metric, level };
  for (const k of ["action", "hyst", "fill"]) {
    const v = opts[k] ?? DEF[k];
    if (!ALLOWED[k].includes(v)) return { error: `${k}: ${ALLOWED[k].join("|")}, получено «${v}»` };
    out[k] = v;
  }
  return { stop: out };
}

// Вторая половина круга издержек по цене ВЫХОДА, на 1.0 контракта. ЭТО НЕ ПРИДИРКА К ТОЧНОСТИ:
// комиссия стороны равна min(0.0003·индекс, 0.125·марк), поэтому у выросшего в разы марка она
// считается по другой ветке, чем на входе. Наблюдённый спред берётся, когда он в записи ЕСТЬ;
// замер 2026-08-28 показал, что при |дельте| выше 0.8 (а стоп уводит сделку именно туда) bid/ask
// в записи отсутствуют в 100% строк, поэтому фолбэк на долю спреда ВХОДА это не редкий случай, а
// основной режим, и он обязан быть виден в отчёте как допущение.
export function stopCostUsd({
  markUsd, indexPrice, bidUsd, askUsd, entryHalfSpreadPct, mult = 1, cfg = SELLHEDGE_DEFAULTS,
} = {}) {
  if (!posNum(markUsd) || !posNum(indexPrice)) return 0;
  const half = fin(bidUsd) && fin(askUsd) && askUsd >= bidUsd
    ? ((askUsd - bidUsd) / 2) * cfg.spreadScale
    : (fin(entryHalfSpreadPct) ? (entryHalfSpreadPct / 100) * markUsd : 0);
  const c = computeTradeCosts({ markUsd, bidUsd: Math.max(0, markUsd - half), askUsd: markUsd + half,
    indexPrice, execModel: cfg.execModel });
  return c ? (c.roundTripCostPct / 100) * markUsd / 2 * mult : 0;
}

// Готовый колбэк `stopAt` для протяжки: собирает аргументы предиката из шага и прогоняет их через
// затвор. Живёт здесь, а не у вызывающих, по той же причине, по которой здесь живёт само правило:
// эталон и измерительный гарнир обязаны судить сделку ОДНИМ кодом, иначе сетка померит разницу
// двух снабжений вместо разницы порогов.
//   marginAt(ctx) - поддерживающая маржа на 1.0 контракта на шаге (зовётся только для метрики mmu);
//   costAt(ctx)   - вторая половина круга издержек по цене ВЫХОДА, на 1.0 контракта.
// Счёт в аргументы не входит намеренно: при размере, пропорциональном счёту, он сокращается из
// обеих «размер-зависимых» метрик (qty = deployPct/im на $1 счёта), и правило остаётся свойством
// сделки, а не портфеля.
export function makeStopAt({
  stop, premSold, optCost, imUsd, deployPct, strikes, marginAt, costAt, cfg = SELLHEDGE_DEFAULTS,
} = {}) {
  const gate = makeStopGate(stop);
  if (!gate || !posNum(imUsd) || !posNum(deployPct)) return undefined;
  const qty = deployPct / imUsd;
  return (ctx) => {
    const mtm1 = stepMtm({ premSold, optCost, step: ctx, cfg });
    if (!fin(mtm1)) return null;
    const args = { metric: stop.metric, level: stop.level, mtm1, premSold, imUsd, equityUsd: 1, qty,
      spotUsd: ctx.S, strikes, mmUsd: stop.metric === "mmu" && marginAt ? marginAt(ctx) : null };
    // «Вернулась» для перевооружения это уход метрики на 20% ниже порога, а не просто отсутствие
    // пробоя: иначе правило дребезжало бы на часовой сетке вокруг самого порога.
    const action = gate(shouldStopOut(args), !shouldStopOut({ ...args, level: stop.level * 0.8 }));
    return action ? { action, costUsd: costAt ? costAt(ctx) : 0 } : null;
  };
}

// ЧИСТЫЙ шаг затвора: (состояние, вердикт) даёт (новое состояние, действие). Живёт отдельно от
// замыкания НЕ ради стиля: в живом движке состояние обязано пережить `JSON.stringify` файла
// состояния и перезапуск приложения. Затвор в замыкании этого не умеет, а гистерезис, начинающийся
// с нуля после каждого рестарта, это ДРУГОЕ правило: `oneshot` становится многоразовым, `band`
// теряет счётчик подряд идущих часов. Поэтому офлайн-прогон и бот зовут ОДНУ эту функцию, а
// различаются лишь тем, где держат её состояние.
export const STOP_GATE_INIT = Object.freeze({ run: 0, fired: false, waiting: false, reduced: false, pending: null });

export function stopGateStep(prev, stop, breached, cleared) {
  const s = { ...STOP_GATE_INIT, ...(prev ?? {}) };
  if (!stop || !stop.metric || !stop.action) return { state: s, action: null };
  const hyst = stop.hyst || "oneshot";
  const fill = stop.fill || "same";
  if (s.pending) return { state: { ...s, pending: null }, action: s.pending };
  if (hyst === "rearm") {
    if (s.waiting) {
      if (!cleared) return { state: s, action: null };
      if (s.reduced && stop.action === "halve") {
        return { state: { ...s, waiting: false, reduced: false }, action: "restore" };
      }
      return { state: { ...s, waiting: false }, action: null };
    }
  } else if (s.fired) return { state: s, action: null };
  const run = breached ? s.run + 1 : 0;
  if (run < (hyst === "band" ? 2 : 1)) return { state: { ...s, run }, action: null };
  const after = hyst === "rearm"
    ? { ...s, run: 0, waiting: true, reduced: stop.action === "halve" }
    : { ...s, run: 0, fired: true };
  if (fill === "next" && stop.action !== "none") {
    return { state: { ...after, pending: stop.action }, action: null };
  }
  return { state: after, action: stop.action };
}

// Замыкание поверх чистого шага: удобная форма для офлайн-протяжки, где состояние живёт внутри
// одной сделки и сериализовать его не надо.
export function makeStopGate(stop = null) {
  if (!stop || !stop.metric || !stop.action) return null;
  let s = null;
  return function gate(breached, cleared = !breached) {
    const r = stopGateStep(s, stop, breached, cleared);
    s = r.state;
    return r.action;
  };
}

// ── 7. НАСТРОЙКИ ДВИЖКА, ПРИ КОТОРЫХ СХЕМА ИЗМЕРЕНА ────────────────────────────────────────────
//
// ЗАЧЕМ ЭТО ЗДЕСЬ, И ЭТО НЕ УДОБСТВО. Пятилетний результат ×46.5 получен движком бота 2 ровно один
// раз: внутри `scripts/replay-sellhedge.mjs`, где эти настройки были выставлены РУКАМИ.
// Живые дефолты бота 2 не совпадают ни с одной из них, и цена расхождения измерена парной сверкой
// на тех же пяти годах (`parity-sellhedge.mjs`, 84 сделки):
//   полоса 0.1 BTC на контракт вместо 0.03      ×24.2 против ×46.5, просадка 20.1% против 13.5%;
//   λ 1.25 и триггер цены 0.5%                  ×39.4, просадка 18.3%;
//   триггер времени 60 с                        ×39.9, просадка 17.4%.
// Пока эти числа живут в скрипте, «перенести схему в бой» означает переписать их заново, а это ровно
// тот класс дефекта («две части системы решают одну задачу разными правилами»), ради которого весь
// остальной модуль и появился. Поэтому конфигурация становится КОДОМ, а скрипт её вызывающим.
//
// ПОЧЕМУ ГЕЙТЫ ВЫКЛЮЧАЮТСЯ, А НЕ НАСТРАИВАЮТСЯ. У схемы ОДНО правило перекладки: разрыв больше
// полосы. Триггеры цены и времени добавляют поводы переложиться, которых у измеренной схемы нет,
// а фильтр «выгода против издержек» добавляет повод НЕ перекладываться, которого у неё нет тоже.
// Исторический замер цены фильтра (до правки маргинальной цены хеджа `estimateCost` клал в
// издержки ОДНОЙ перекладки фандинг ВСЕЙ целевой позиции): при полосе 0.03 и споте $100k движок
// перекладывался на 1.05 полосы при нулевом фандинге, на 1.44 при +1 б.п. за 8 часов и на 3.03
// при +5 б.п. Сегодня фандинг считается на приращении и полоса со ставкой так не разъезжается,
// но λ = 0 остаётся не упрощением, а точным воспроизведением измеренного: парная сверка пяти лет
// получена решениями «разрыв больше полосы», без гейта выгоды вовсе.
//
// НЕДОСТИЖИМЫЙ ПОРОГ ВМЕСТО ФЛАГА - осознанно: у движка нет выключателя триггеров, а заводить его
// значило бы менять чужой контракт ради этой схемы. 1e9 процентов движения и 1e9 секунд не
// наступают ни на каких данных, и такой порог ЧИТАЕТСЯ в отчёте как «никогда», в отличие от нуля.
const NEVER = 1e9;

// sellhedgeEngineCfg(cfg) отдаёт патч настроек бота 2, воспроизводящий измеренную схему.
// `deadbandRefQty: 1.0` переводит полосу на КОНТРАКТ: `effectiveDeadband` считает
// bandBtc·(размер/refQty), поэтому при якоре 1.0 позиция в q контрактов получает ровно bandBtc·q,
// то есть то же число, каким мерил эталон. Хранить вместо этого 0.0003 при якоре 0.01 можно, но
// тогда одно и то же правило записано двумя разными парами чисел, и сверять их придётся глазами.
export function sellhedgeEngineCfg(cfg = SELLHEDGE_DEFAULTS) {
  return {
    deadbandBtc: cfg.bandBtc,
    deadbandRefQty: 1.0,
    priceTriggerPct: NEVER, // триггера цены у схемы нет
    rehedgeSec: NEVER, // триггера времени у схемы нет
    lambda: 0, // гейт вырождается в «выгода > 0», то есть решает одна полоса
    settlementBlackout: false, // у схемы нет выходных: эталон хеджится и в окне расчёта
    // Правило досрочного выхода едет в ЗАМОРОЖЕННУЮ конфигурацию структуры вместе с остальными
    // правилами схемы. Иначе работающая позиция судилась бы правилом, которое оператор поставил
    // ПОСЛЕ её открытия, а этого не должно быть ни в одну сторону: ни включения, ни выключения
    // посреди сделки. По умолчанию null, то есть выхода нет.
    stop: cfg.stop ?? null,
    // Множитель модельного спреда едет вместе с правилом по той же причине: вход в опцион уже
    // оценён им (structure.js зовёт computeTradeCosts с этим числом), и цена ВЫХОДА обязана
    // считаться тем же допущением. Живой тракт ставит 1 явно: котировки там настоящие.
    spreadScale: cfg.spreadScale,
    execModel: cfg.execModel,
  };
}

// ── 8. ПЕРЕВХОД. Правило цепочки эталона звучит одной строкой (`hist-sellhedge.mjs`, функция
// `chain`): «закрылась сделка, в тот же день открывается следующая; ни пропусков, ни выбора
// момента». Годовые проценты делают 16-17 сделок ПОДРЯД, и без перевхода живой бот даёт одну
// сделку из семнадцати.
//
// ПОЧЕМУ ПРАВИЛО ЗДЕСЬ, А НЕ У ВЫЗЫВАЮЩЕГО. До этой правки перевход существовал ровно в одном
// месте - строкой `if (!hadStructure)` внутри `replay-sellhedge.mjs`, то есть в ТЕСТОВОМ драйвере.
// Сверка книг за пять лет поэтому доказывала свойство скрипта, а не приложения: харнесс сам
// открывал сделки, которые в бою не открыл бы никто. Пока правило живёт в драйвере, сверка мерит
// себя.
//
// ПОРЯДОК ВЫЗОВА ЗНАЧИМ И ОДИН НА ОБОИХ ВЫЗЫВАЮЩИХ: спросить перевход НАДО ДО `evaluate`. На тике
// экспирации структура ещё открыта, `shouldOpenNext` даёт false, и расчёт делает `evaluate` этого
// же тика; следующая сделка открывается СЛЕДУЮЩИМ тиком. Ровно так считает и эталон: `i = endIdx + 1`.
// Спросить после `evaluate` значило бы открыть новую сделку в ту же метку, что и расчёт старой.
//   hasStructure  - есть ли открытая структура ПРЯМО СЕЙЧАС (до evaluate этого тика);
//   chainOn       - включён ли режим цепочки;
//   stopRequested - оператор остановил цепочку: текущая сделка доживает, следующей не будет;
//   mode          - "continuous" (по умолчанию) либо "once": одна сделка, после её расчёта
//                   перевхода нет. Отсутствующее поле читается как непрерывный режим, поэтому
//                   старые вызывающие (прогон записи) правок не требуют;
//   tradesCount   - сколько сделок цепочка уже закрыла (нужен только режиму "once").
// ОЖИДАНИЕ ПОСЛЕ ДОСРОЧНОГО ВЫХОДА - часть правила, а не деталь драйвера. Замер зафиксировал
// головным режимом «следующая сделка не раньше ИСХОДНОЙ экспирации остановленной»: при немедленном
// перевходе то же самое правило разоряет счёт в 89 раз быстрее (вырожденный контроль дал ×0.01
// против ×0.89), потому что капитал переразмещается раньше, чем сделка кончилась бы сама. Живой
// бот обязан ждать по тем же часам, иначе он исполняет измеренное правило только наполовину.
//   reopenAfterMs - метка, до которой цепочка не открывает новую сделку (null = ждать нечего);
//   nowMs         - текущие часы; без них ожидание не проверяется вовсе.
export function shouldOpenNext({
  hasStructure, chainOn, stopRequested, mode, tradesCount, reopenAfterMs, nowMs,
} = {}) {
  if (mode === "once" && Number(tradesCount) > 0) return false;
  // Сравнение НЕСТРОГОЕ намеренно: эталон открывает следующую сделку тиком ПОСЛЕ шага экспирации
  // (`i = expiryEndIdx + 1`), а шаг экспирации это первый тик с меткой не раньше самой экспирации.
  // Строгое «<» открыло бы движок на час раньше эталона, и книги разошлись бы на каждой
  // остановленной сделке.
  if (fin(reopenAfterMs) && fin(nowMs) && nowMs <= reopenAfterMs) return false;
  return chainOn === true && stopRequested !== true && hasStructure !== true;
}

// shouldOpenDegraded - истекло ли окно ожидания санитарии (§1.8: не прошла ни одна нога - схема
// ждёт с показанной причиной; ожидание дольше окна - открывается лучшая доступная с постоянной
// пометкой «ухудшенная санитария»). Чистая: обе метки приходят от вызывающего.
export function shouldOpenDegraded({ sanityWaitingSince, nowMs, windowMs } = {}) {
  return fin(sanityWaitingSince) && fin(nowMs) && fin(windowMs) && nowMs - sanityWaitingSince >= windowMs;
}

// ── ДОЛЛАРОВАЯ ДЕЛЬТА ОБРАТНОГО ПЕРПА. Функция существует, чтобы S4 не унаследовала чужую
// конвенцию, а не потому, что кому-то нужна ещё одна формула.
//
// В ЧЁМ РАЗНИЦА, И ОНА НЕ КОСМЕТИЧЕСКАЯ. `markPerp` бота 2 (pnl.js:51) отдаёт
// `futuresDeltaBtc = qty·cs/mark`, то есть НОМИНАЛ позиции в BTC по ТЕКУЩЕЙ цене. Это верный
// ответ на вопрос «сколько BTC номинала я несу» и НЕВЕРНЫЙ на вопрос «на сколько изменится мой
// долларовый P&L при движении спота на доллар». Второй ответ равен `qty·cs/avgEntry`, и он прямо
// следует из формулы, которую тот же модуль строкой ниже и книжит:
//   upl_usd = qty·cs·(mark − avgEntry)/avgEntry  ⇒  ∂upl_usd/∂mark = qty·cs/avgEntry = const.
// Два числа расходятся в `mark/avgEntry` раз, то есть ровно настолько, насколько цена ушла от
// среднего входа позиции.
//
// ПОЧЕМУ ЭТО ВАЖНО ИМЕННО ПРОДАВЦУ. Опцион здесь оценивается в ДОЛЛАРАХ (премия по Блэку-76), его
// дельта это ∂USD/∂S, и нейтральность обязана сводиться в одной системе отсчёта. Подстановка
// номинальной дельты вместо долларовой возвращает направленную ставку - ровно ту, ради снятия
// которой хедж и заводится (дельта даёт 81% дисперсии итога и никакого преимущества).
//
// ЗАМЕР, КОТОРЫЙ ЭТО ПОЙМАЛ (parity-sellhedge.mjs, 5 лет, 2.5 б.п.): вариант с номинальной дельтой
// даёт ×13.20 против ×10.24 у эталона, то есть ЛУЧШЕ, и при меньшем разбросе. На падающем годе он
// же даёт ×1.22 против ×1.28, то есть ХУЖЕ. Знак эффекта следует за направлением рынка - это
// подпись направленной ставки, а пятилетний выигрыш есть артефакт бычьей выборки. Конвенция бота 2
// закреплена его тестами и здесь НЕ меняется: правка живого хеджа это отдельное решение.
//
// Плоская позиция даёт ноль: applyFill обнуляет avgEntry ровно тогда, когда qty приходит в ноль,
// и 0/0 обязан быть перехвачен здесь, а не всплыть NaN-ом в P&L.
export function usdDeltaOfInversePerp({ qty, contractSize, avgEntry } = {}) {
  if (!fin(qty) || qty === 0 || !posNum(contractSize) || !posNum(avgEntry)) return 0;
  return (qty * contractSize) / avgEntry;
}

// ── 6. Размер. У ПРОДАВЦА связывающее ограничение это ЗАЛОГ, а не премия, и это не оттенок:
// замер по пяти годам даёт медиану залога $92 за минимальный лот против премии $21.91, то есть
// покупательский гейт (`computeSizing`, риск = уплаченная премия) разрешил бы вчетверо больший
// размер, чем позволяет биржа. Лоты режутся ВНИЗ: остаток счёта это не повод округлить вверх.
export function lotsByMargin({ imUsdPerContract, equityUsd, cfg = SELLHEDGE_DEFAULTS } = {}) {
  if (!posNum(imUsdPerContract) || !posNum(equityUsd)) return { lots: 0, imLotUsd: null, imUsedUsd: 0 };
  const imLotUsd = imUsdPerContract * cfg.lot;
  const lots = Math.floor((equityUsd * cfg.deployPct) / imLotUsd);
  return { lots: Math.max(0, lots), imLotUsd, imUsedUsd: Math.max(0, lots) * imLotUsd };
}

// ── 9. ЗОНА ПРОДАВЦА. Метка режима рынка на момент входа: реализованная волатильность недели ВЫШЕ
// подразумеваемой у проданной ноги - худший исторически режим схемы.
//
// ЗАЧЕМ ФУНКЦИЯ, ЕСЛИ ЭТО ОДНО СРАВНЕНИЕ. Потому что сравнений стало два. Правило жило выражением
// внутри `computeSellScan` (чип «зона продавца» в карточке сканера), а разрез книги по зоне в
// офлайн-отчёте спрашивает ровно ту же величину - и второе написание того же сравнения это ровно
// тот класс дефекта, который проект ловил четырежды. Живой чип и строка книги обязаны означать
// одно, иначе оператор видит «худшая зона» там, где отчёт её не считает.
//
// ЭТО НЕ ГЕЙТ И НЕ СТАНОВИТСЯ ИМ. Зона ИНФОРМИРУЕТ: замер показал, что вход по ней только
// ухудшает цепочку (шапка sell-scan.js). Функция отвечает «в каком режиме открылись», а не
// «открываться ли», и вызывающий её вердиктом не связан.
//
// НЕТ ДАННЫХ - НЕТ МЕТКИ: null, а не «normal». Отсутствие RV (недельный разогрев окна в начале
// записи) означает незнание режима, и подставлять сюда благополучный ответ значило бы записать
// сделки разогрева в хорошую зону просто потому, что мерить было нечем.
export function sellerZone({ ivPct, rv7dPct } = {}) {
  if (!fin(ivPct) || !fin(rv7dPct)) return null;
  return rv7dPct > ivPct ? "worst" : "normal";
}
