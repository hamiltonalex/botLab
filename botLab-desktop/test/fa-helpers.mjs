//
// ПРИЁМ, РАДИ КОТОРОГО ЭТОТ ФАЙЛ СУЩЕСТВУЕТ: неверные данные не запрещаются проверкой, они
// делаются НЕВЫРАЗИМЫМИ. Строка строится от ПОТОКА рынка и баз сторон, поэтому тождество
// `|f_long| * B_long = |f_short| * B_short = pot` выполняется по построению, и нарушить его в
// тесте нельзя. Причина конкретная: три первых варианта тестов разбавления задавали ставки
// независимо от баз, то есть описывали рынок, где обе стороны котируют одну ставку при разных
// базах. Такого рынка нет, и один из трёх тестов проверял на нём именно запрет «плательщика
// определяет знак», то есть не проверял ничего.
//
// Отсюда же следует главное свойство задачи, которое иначе легко забыть: МЕНЬШАЯ сторона всегда
// котирует БОЛЬШУЮ ставку по модулю.
//
// Файл общий у тестов разбавления и правила размера: конструктор один, потому что свойство
// «тождество по построению» обязано быть одним и тем же в обоих.

const BASE_MS = 1699999200000; // метка, выровненная по границе часа
export const BASE_S = BASE_MS / 1000;
export const HOUR_MS = 3600 * 1000;

// Часовая строка канонического кадра. Знак f по конвенции Subsquid: f_short > 0 значит получает
// короткая сторона.
export const row = (h, { fs = 0, fl = 0, bs = 0, bl = 0, hl = 0, fbS, fbL } = {}) => ({
  tsHour: BASE_S + h * 3600, f_short: fs, f_long: fl, b_short: bs, b_long: bl, hl_rate: hl,
  ...(fbS === undefined ? null : { fbase_short: fbS }),
  ...(fbL === undefined ? null : { fbase_long: fbL }),
});

// Строка, построенная ПО ТОЖДЕСТВУ. `pot` это весь поток фандинга рынка в долларах за секунду,
// `recv` называет сторону, которая в этот час получает.
export const hour = (h, { pot, bShort, bLong, recv = "short", bs = 0, bl = 0, hl = 0, bases = true }) => {
  const sign = recv === "short" ? 1 : -1;
  return row(h, {
    fs: sign * (pot / bShort), fl: -sign * (pot / bLong), bs, bl, hl,
    ...(bases ? { fbS: bShort, fbL: bLong } : null),
  });
};
